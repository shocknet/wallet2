import type { NostrKeyPair } from "@/Api/nostrHandler"
import type { NostrClientParams } from "@/Api/pub/autogenerated/ts/nostr_client"
import type { NostrRequest } from "@/Api/pub/autogenerated/ts/nostr_transport"
import { vi } from "vitest"

export type SentFrame = {
	relays: string[];
	to: string;
	keys: NostrKeyPair;
	rpcName: string;
	requestId: string;
	body: unknown;
};

export type NostrMockControls = {
	/** Resolves with the next request the client publishes. */
	sent(): Promise<SentFrame>;
	replyOk(frame: SentFrame, payload?: object): void;
	replyError(frame: SentFrame, reason?: string): void;
};

type NostrListener = (event: {
	pub: string;
	to: string;
	content: string;
}) => void;

export function mockNostrLayer(): NostrMockControls {
	const queued: SentFrame[] = [];
	const waiters: Array<(frame: SentFrame) => void> = [];
	const listeners = new Set<NostrListener>();

	function publish(frame: SentFrame) {
		const waiter = waiters.shift();
		if (waiter) waiter(frame);
		else queued.push(frame);
	}

	function sent(): Promise<SentFrame> {
		const existing = queued.shift();
		if (existing) return Promise.resolve(existing);
		return new Promise(resolve => {
			waiters.push(resolve);
		});
	}

	function emit(frame: SentFrame, payload: object) {
		if (listeners.size === 0) {
			throw new Error("Pool has no nostrEvent listener");
		}
		const event = {
			pub: frame.to,
			to: frame.keys.publicKey,
			content: JSON.stringify({ requestId: frame.requestId, ...payload }),
		};
		for (const listener of listeners) listener(event);
	}

	vi.doMock("@/Api/nostrHandler", () => {
		const events = {
			on(event: string, fn: NostrListener) {
				if (event !== "nostrEvent") return () => { };
				listeners.add(fn);
				return () => {
					listeners.delete(fn);
				};
			},
			removeAll() {
				listeners.clear();
			},
		};

		const pool = {
			events,
			syncRelays: async () => { },
			send(relays: string[], to: string, message: string, keys: NostrKeyPair) {
				const parsed = JSON.parse(message) as NostrRequest;
				if (!parsed.rpcName || !parsed.requestId) {
					throw new Error("Published request is missing rpcName or requestId");
				}
				publish({
					relays,
					to,
					keys,
					rpcName: parsed.rpcName,
					requestId: parsed.requestId,
					body: parsed.body,
				});
			},
			reset() {
				events.removeAll();
			},
			pause() { },
			resume() { },
		};

		return { getPool: () => pool };
	});

	vi.doMock("@/Api/pub/autogenerated/ts/nostr_client", () => ({
		default: (
			params: NostrClientParams,
			send: (to: string, message: NostrRequest) => Promise<any>,
			subscribe: (to: string, message: NostrRequest, cb: (res: any) => void) => void,
		) => new Proxy({}, {
			get(_target, propKey: string) {
				// A function for `then` would make this object a thenable.
				if (propKey === "then") return undefined;

				return async (requestOrCb: any) => {
					const auth = await params.retrieveNostrAdminAuth();
					const request: NostrRequest = {
						rpcName: propKey,
						authIdentifier: auth!,
					};

					if (propKey.includes("GetLive")) {
						subscribe(params.pubDestination, request, (data) => {
							if (data?.status === "OK" || data?.status === "ERROR") requestOrCb(data);
							else requestOrCb({ status: "ERROR", reason: "invalid response" });
						});
						return;
					}

					request.body = requestOrCb;
					const data = await send(params.pubDestination, request);
					if (data?.status === "OK" || data?.status === "ERROR") return data;
					return { status: "ERROR", reason: "invalid response" };
				};
			},
		}),
	}));

	return {
		sent,
		replyOk(frame, payload = {}) {
			emit(frame, { status: "OK", ...payload });
		},
		replyError(frame, reason = "boom") {
			emit(frame, { status: "ERROR", reason });
		},
	};
}
