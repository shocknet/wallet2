export class TypedEmitter<Events extends Record<string, any>> {
	private listeners = new Map<keyof Events, Set<(payload: any) => void>>();

	on<K extends keyof Events>(
		event: K,
		fn: (payload: Events[K]) => void,
		opts?: { signal?: AbortSignal }
	): () => void {
		let set = this.listeners.get(event);
		if (!set) {
			set = new Set();
			this.listeners.set(event, set);
		}
		set.add(fn as any);

		const off = () => {
			set!.delete(fn as any);
			if (set!.size === 0) this.listeners.delete(event);
		};

		if (opts?.signal) {
			if (opts.signal.aborted) off();
			else opts.signal.addEventListener("abort", off, { once: true });
		}

		return off;
	}

	emit<K extends keyof Events>(event: K, payload: Events[K]) {
		const set = this.listeners.get(event);
		if (!set) return;

		[...set].forEach((fn) => {
			try {
				(fn as any)(payload);
			} catch (e) {
				console.error("TypedEmitter listener error", e);
			}
		});
	}

	removeAll() {
		this.listeners.clear();
	}
}



function covers(have: string[] | undefined, want: Iterable<string>): boolean {
	if (!have) return false;
	const got = new Set(have);
	for (const item of want) {
		if (!got.has(item)) return false;
	}
	return true;
}

const DEFAULT_QUERY_MAX_WAIT_MS = 10_000;

class PausableDeadline {
	private remainingMs: number;
	private startedAt = 0;
	private timer: ReturnType<typeof setTimeout> | undefined;
	private ended = false;

	constructor(
		milliseconds = DEFAULT_QUERY_MAX_WAIT_MS,
		private readonly onExpire: () => void,
		paused: boolean,
	) {
		this.remainingMs = Math.max(0, milliseconds);
		if (!paused) this.resume();
	}

	pause() {
		if (this.timer === undefined || this.ended) return;
		clearTimeout(this.timer);
		this.timer = undefined;
		this.remainingMs = Math.max(0, this.remainingMs - (performance.now() - this.startedAt));
	}

	resume() {
		if (this.ended || this.timer !== undefined) return;
		this.startedAt = performance.now();
		this.timer = setTimeout(() => this.expire(), this.remainingMs);
	}

	expire() {
		if (this.ended) return;
		this.cancel();
		this.onExpire();
	}

	cancel() {
		this.ended = true;
		if (this.timer !== undefined) clearTimeout(this.timer);
		this.timer = undefined;
	}
}

