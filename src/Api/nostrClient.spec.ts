import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import {
	finalizeEvent,
	generateSecretKey,
	getPublicKey,
	type Event as SignedEvent,
} from "nostr-tools";
import { Buffer } from "buffer";
import { NostrCallbackSingle, NostrClient } from "./nostr";
import { TransportPool, type NostrKeyPair } from "./nostrHandler";
import { decodePayload, decryptData, encodePayload, encryptData, getSharedSecret } from "./nip44v1";
import type { NostrRequest } from "./pub/autogenerated/ts/nostr_transport";
import { MockNostrRelay, type RecordedFrame } from "@tests/support/mock-nostr-relay";



function makeKeys(): NostrKeyPair {
	const secret = generateSecretKey();
	return {
		privateKey: Buffer.from(secret).toString("hex"),
		publicKey: getPublicKey(secret),
	};
}

function makeRequest(requestId: string, rpcName = "GetUserInfo"): NostrRequest {
	return { requestId, rpcName } as NostrRequest;
}



function publishedFrames(server: MockNostrRelay, fromPubkey?: string): RecordedFrame[] {
	return server.frames.filter(({ message }) =>
		message[0] === "EVENT" &&
		(!fromPubkey || (message[1] as SignedEvent).pubkey === fromPubkey),
	);
}

function eventOf(frame: RecordedFrame): SignedEvent {
	return frame.message[1] as SignedEvent;
}

async function waitForPublishedCount(server: MockNostrRelay, n: number, from: string) {
	await vi.waitFor(() => {
		expect(publishedFrames(server, from)).toHaveLength(n);
	}, { timeout: 3_000, interval: 5 });
	return publishedFrames(server, from)[n - 1];
}

function acceptPublish(server: MockNostrRelay, frame: RecordedFrame) {
	server.send(["OK", eventOf(frame).id, true, ""], frame.connectionId);
}



describe("NostrClient single RPCs through real TransportPool", () => {
	let server: MockNostrRelay;
	let pool: TransportPool;
	let client: NostrClient;
	let caller: NostrKeyPair;
	let service: NostrKeyPair;
	let sequence: number;


	function single(reqId: string): NostrCallbackSingle {
		const cb = client.clientCbs.get(reqId);
		expect(cb?.type).toBe("single");
		return cb as NostrCallbackSingle;
	}

	function request(rpcName = "GetUserInfo") {
		const id = `rpc-test-${++sequence}`;
		const outcome = client.clientSend(service.publicKey, makeRequest(id, rpcName));
		return { id, outcome };
	}

	function background() {

		client.pauseOrFailSinglesOnBackground();
		pool.onNativeBackground();
	}

	function foreground() {
		pool.onNativeForeground();
		void client.resumePausedSingles();
	}

	// Complete the initial REAL internal RPC and beacon subscriptions
	async function ready() {
		const p = pool.syncRelays({ relays: [server.url], lpk: service.publicKey, keys: caller });
		const rpc = await server.waitForReq("rpc:1");
		const beacon = await server.waitForReq("beacons:1");
		server.send(["EOSE", rpc.message[1]], rpc.connectionId);
		server.send(["EOSE", beacon.message[1]], beacon.connectionId);
		await p;
		return rpc;
	}

	// Wait for a re-fired RPC REQ on a NEW socket and confirm it
	async function confirmReconnectedRpc(connectionId = 2) {
		const rpc = await server.waitForFrame(({ connectionId: c, message }) =>
			c === connectionId && message[0] === "REQ" &&
			(message[2] as { kinds?: number[] }).kinds?.includes(21000) === true,
		);
		server.send(["EOSE", rpc.message[1]], rpc.connectionId);
		// Beacon EOSE is not a prerequisite for RPC readiness; finish it anyway.
		const beacon = await server.waitForFrame(({ connectionId: c, message }) =>
			c === connectionId && message[0] === "REQ" &&
			(message[2] as { kinds?: number[] }).kinds?.includes(30078) === true,
		);
		server.send(["EOSE", beacon.message[1]], beacon.connectionId);
		return rpc;
	}

	// Produce an authentic encrypted RPC reply on the relay's subscribed socket
	function reply(
		id: string,
		rpcSub: RecordedFrame,
		fields: Record<string, unknown> = { status: "OK", value: 42 },
		from: NostrKeyPair = service,
	) {
		const plaintext = JSON.stringify({ requestId: id, ...fields });
		const content = encodePayload(
			encryptData(plaintext, getSharedSecret(from.privateKey, caller.publicKey)),
		);
		const event = finalizeEvent({
			kind: 21000,
			created_at: Math.floor(Date.now() / 1000),
			tags: [["p", caller.publicKey]],
			content,
		}, new Uint8Array(Buffer.from(from.privateKey, "hex")));
		server.send(["EVENT", rpcSub.message[1], event], rpcSub.connectionId);
		return event;
	}

	beforeEach(async () => {
		sequence = 0;
		caller = makeKeys();
		service = makeKeys();
		server = await MockNostrRelay.start();

		pool = new TransportPool();


		const generatedFactory = (() => ({})) as unknown as ConstructorParameters<typeof NostrClient>[4];
		client = new NostrClient(service.publicKey, caller, [server.url], pool, generatedFactory);
		pool.events.on("nostrEvent", evt => { client.onEvent(evt); });
		vi.useFakeTimers();
	});

	afterEach(async () => {
		client.disconnectCalls("test teardown");
		pool.reset();
		await server.stop();
		vi.restoreAllMocks();
		vi.useRealTimers();
	});

	it("fails without publishing if the RPC subscription is rejected before EOSE", async () => {
		const { id, outcome } = request();
		const rpc = await server.waitForReq("rpc:1");
		const beacon = await server.waitForReq("beacons:1");
		server.send(["CLOSED", rpc.message[1], "blocked: read denied"], rpc.connectionId);
		server.send(["CLOSED", beacon.message[1], "blocked: read denied"], beacon.connectionId);
		expect(await outcome).toMatchObject({ status: "ERROR" });
		expect(publishedFrames(server, caller.publicKey)).toHaveLength(0);
		expect(client.clientCbs.has(id)).toBe(false);
	});

	it("accepts a real RPC response before publish OK and ignores a later publish failure", async () => {
		const rpc = await ready();
		const { id, outcome } = request();
		const pub = await waitForPublishedCount(server, 1, caller.publicKey);
		reply(id, rpc);
		expect(await outcome).toMatchObject({ requestId: id, status: "OK" });
		server.send(["OK", eventOf(pub).id, false, "blocked"], pub.connectionId);
		await vi.advanceTimersByTimeAsync(20);
		expect(client.clientCbs.has(id)).toBe(false);
	});

	it("fails and cleans up when the relay rejects publishing", async () => {
		await ready();
		const { id, outcome } = request();
		const pub = await waitForPublishedCount(server, 1, caller.publicKey);
		server.send(["OK", eventOf(pub).id, false, "blocked: write denied"], pub.connectionId);
		const result = await outcome;
		expect(result).toMatchObject({ status: "ERROR" });
		expect(client.clientCbs.has(id)).toBe(false);
	});

	it("times out an unanswered safe RPC after a successful publish", async () => {
		await ready();
		const { id, outcome } = request();
		const pub = await waitForPublishedCount(server, 1, caller.publicKey);
		acceptPublish(server, pub);
		await vi.waitFor(() => expect(single(id).phase).toBe("awaiting-response"));
		vi.advanceTimersByTime(9_000); // 8 second timeout
		expect(await outcome).toMatchObject({ status: "ERROR", reason: "Request timed out" });
		expect(client.clientCbs.has(id)).toBe(false);
	}, 12_000);

	it("pauses readiness across native background and publishes once after EOSE on foreground", async () => {
		const { id, outcome } = request();
		await server.waitForReq("rpc:1");
		await server.waitForReq("beacons:1");
		background();
		expect(single(id).paused).toBe(true);
		expect(single(id).phase).toBe("ensuring");
		foreground();
		const rpc = await confirmReconnectedRpc();
		const pub = await waitForPublishedCount(server, 1, caller.publicKey);
		acceptPublish(server, pub);
		reply(id, rpc);
		expect(await outcome).toMatchObject({ status: "OK" });
		expect(publishedFrames(server, caller.publicKey)).toHaveLength(1);
	});

	it("after a paused in-flight publish rejects, foreground starts one new attempt", async () => {
		await ready();
		const { id, outcome } = request();
		await waitForPublishedCount(server, 1, caller.publicKey); // deliberately no OK
		expect(single(id).phase).toBe("sending");
		background();
		await vi.waitFor(() => expect(single(id).phase).toBe("idle"));
		foreground();
		const rpc = await confirmReconnectedRpc();
		const retry = await waitForPublishedCount(server, 2, caller.publicKey);
		acceptPublish(server, retry);
		reply(id, rpc);
		expect(await outcome).toMatchObject({ status: "OK" });
		expect(publishedFrames(server, caller.publicKey)).toHaveLength(2);
	});

	it("re-sends an unanswered safe RPC on foreground, retaining the requestId", async () => {
		await ready();
		const { id, outcome } = request();
		const first = await waitForPublishedCount(server, 1, caller.publicKey);
		acceptPublish(server, first);
		await vi.waitFor(() => expect(single(id).phase).toBe("awaiting-response"));
		background();
		foreground();
		const rpc = await confirmReconnectedRpc();
		const second = await waitForPublishedCount(server, 2, caller.publicKey);
		expect(eventOf(second).id).not.toBe(eventOf(first).id);
		const decrypted = decryptData(
			decodePayload(eventOf(second).content),
			getSharedSecret(service.privateKey, caller.publicKey),
		);
		expect(JSON.parse(decrypted).requestId).toBe(id);
		acceptPublish(server, second);
		reply(id, rpc);
		expect(await outcome).toMatchObject({ requestId: id, status: "OK" });
	});

	it("does not pause or automatically retry a PayInvoice RPC", async () => {
		await ready();
		const { id, outcome } = request("PayInvoice");
		const pub = await waitForPublishedCount(server, 1, caller.publicKey);
		const cb = single(id);
		expect(cb.safe).toBe(false);
		expect(cb.timeout).toBeUndefined();
		acceptPublish(server, pub);
		await vi.waitFor(() => expect(single(id).phase).toBe("awaiting-response"));

		background();
		expect(single(id).paused).toBeUndefined();
		foreground();
		const rpc = await confirmReconnectedRpc();
		await vi.advanceTimersByTimeAsync(20);
		expect(publishedFrames(server, caller.publicKey)).toHaveLength(1);
		reply(id, rpc);
		expect(await outcome).toMatchObject({ status: "OK" });
	});

	it("reports a failed unsafe payment publish instead of silently retrying it", async () => {
		await ready();
		const { id, outcome } = request("PayInvoice");
		await waitForPublishedCount(server, 1, caller.publicKey); // no relay OK
		background();
		expect(await outcome).toMatchObject({ status: "ERROR" });
		expect(client.clientCbs.has(id)).toBe(false);
		foreground();
		await confirmReconnectedRpc();
		await vi.advanceTimersByTimeAsync(20);
		expect(publishedFrames(server, caller.publicKey)).toHaveLength(1);
	});


	it("disconnectCalls settles pending requests and ignores a late relay response", async () => {
		const rpc = await ready();
		const { id, outcome } = request();
		const pub = await waitForPublishedCount(server, 1, caller.publicKey);
		client.disconnectCalls("identity-switch");
		expect(await outcome).toMatchObject({ status: "ERROR", reason: "identity-switch" });
		acceptPublish(server, pub);
		reply(id, rpc);
		await vi.advanceTimersByTimeAsync(20);
		expect(client.clientCbs.has(id)).toBe(false);
	});

	it("does not start a second pool.send while a relay connection waiter survives foreground", async () => {
		const secondServer = await MockNostrRelay.start({
			pauseConnections: true,
		});

		let twoRelayClient: NostrClient | undefined;

		try {
			// A connects normally. B remains in WebSocket CONNECTING.
			const initialReady = pool.syncRelays({
				relays: [server.url, secondServer.url],
				lpk: service.publicKey,
				keys: caller,
			});

			const rpcA = await server.waitForReq("rpc:1");
			const beaconA = await server.waitForReq("beacons:1");

			server.send(["EOSE", rpcA.message[1]], rpcA.connectionId);
			server.send(["EOSE", beaconA.message[1]], beaconA.connectionId);

			await initialReady;

			await vi.waitFor(() => {
				expect(secondServer.pendingConnectionCount).toBe(1);
			});
			expect(secondServer.connectionCount).toBe(0);

			const factory = (() => ({})) as unknown as
				ConstructorParameters<typeof NostrClient>[4];

			twoRelayClient = new NostrClient(
				service.publicKey,
				caller,
				[server.url, secondServer.url],
				pool,
				factory,
			);

			const active = twoRelayClient;
			pool.events.on("nostrEvent", evt => active.onEvent(evt));

			const id = "pending-through-foreground";
			const outcome = active.clientSend(
				service.publicKey,
				makeRequest(id),
			);

			// A receives the publish but never acknowledges it.
			// B's publish is blocked inside ensureConnection().
			await waitForPublishedCount(server, 1, caller.publicKey);

			expect(publishedFrames(secondServer, caller.publicKey)).toHaveLength(0);
			expect(active.clientCbs.get(id)).toMatchObject({
				phase: "sending",
			});

			// Background the entire application.
			active.pauseOrFailSinglesOnBackground();
			pool.onNativeBackground();

			// Foreground while the original pool.send() is still pending.
			pool.onNativeForeground();
			await active.resumePausedSingles();

			expect(active.clientCbs.get(id)).toMatchObject({
				phase: "sending",
			});

			// Allow B to connect. Its original connection waiter should resume.
			secondServer.resumeConnections();

			const rpcB = await secondServer.waitForReq("rpc:1");
			secondServer.send(["EOSE", rpcB.message[1]], rpcB.connectionId);

			// B now receives the event from the ORIGINAL pool.send().
			const pubB = await waitForPublishedCount(
				secondServer,
				1,
				caller.publicKey,
			);

			acceptPublish(secondServer, pubB);

			await vi.waitFor(() => {
				expect(active.clientCbs.get(id)).toMatchObject({
					phase: "awaiting-response",
				});
			});

			// If foreground started another client-level publish, we would
			// observe additional EVENT frames.
			expect(publishedFrames(server, caller.publicKey)).toHaveLength(1);
			expect(publishedFrames(secondServer, caller.publicKey)).toHaveLength(1);

			// Deliver an actual encrypted RPC response through B.
			const plaintext = JSON.stringify({
				requestId: id,
				status: "OK",
			});

			const response = finalizeEvent({
				kind: 21000,
				created_at: Math.floor(Date.now() / 1000),
				tags: [["p", caller.publicKey]],
				content: encodePayload(encryptData(
					plaintext,
					getSharedSecret(service.privateKey, caller.publicKey),
				)),
			}, new Uint8Array(Buffer.from(service.privateKey, "hex")));

			secondServer.send(
				["EVENT", rpcB.message[1], response],
				rpcB.connectionId,
			);

			expect(await outcome).toMatchObject({
				requestId: id,
				status: "OK",
			});
		} finally {
			twoRelayClient?.disconnectCalls("test teardown");
			await secondServer.stop();
		}
	});

	it("preserves the intentional early return for stream callbacks", async () => {
		await ready();
		const onStream = vi.fn();
		client.clientSub(service.publicKey, makeRequest("stream-request", "GetLiveUserOperations"), onStream);
		await vi.advanceTimersByTimeAsync(20);
		expect(client.clientCbs.get("stream-request")?.type).toBe("stream");
		expect(publishedFrames(server, caller.publicKey)).toHaveLength(0);
		client.removeStreamSub("stream-request");
		expect(client.clientCbs.has("stream-request")).toBe(false);
	});
});
