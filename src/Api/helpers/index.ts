import { getNostrClient, GetNostrClientNprofileArgs } from "../nostr";
import { AddressType } from "../pub/autogenerated/ts/types";
import { generateSecretKey, getPublicKey } from "nostr-tools";
import { NostrKeyPair } from "../nostrHandler";
import { bytesToHex } from "@noble/hashes/utils";
import { Satoshi } from "@/lib/types/units";
import { InputClassification, ParsedInvoiceInput } from "@/lib/types/parse";
import { parseAs } from "@/lib/parse";




export const createNostrInvoice = async (
	nprofile: GetNostrClientNprofileArgs,
	keys: NostrKeyPair,
	amount: Satoshi,
	memo?: string,
	blind = false
): Promise<ParsedInvoiceInput> => {

	const res = await (await getNostrClient(nprofile, keys)).NewInvoice({
		amountSats: +amount,
		memo: memo || "",
		...(blind && { blind })
	})


	if (res.status !== 'OK') {
		throw new Error(res.reason);
	}
	return parseAs(res.invoice, InputClassification.LN_INVOICE, amount);
}



export const getNostrBtcAddress = async (nprofile: GetNostrClientNprofileArgs, keys: NostrKeyPair) => {
	const res = await (await getNostrClient(nprofile, keys)).NewAddress({ addressType: AddressType.WITNESS_PUBKEY_HASH })
	if (res.status !== 'OK') {
		throw new Error(res.reason);
	}

	return res.address
}


export type KeyPair = {
	privateKey: string;
	publicKey: string;
}
export const generateNewKeyPair = () => {
	const privateKey = generateSecretKey();
	const publicKey = getPublicKey(privateKey);
	return {
		privateKey: bytesToHex(privateKey),
		publicKey,
	}
}

