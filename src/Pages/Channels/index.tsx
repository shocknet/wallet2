import { useCallback, useEffect, useMemo, useState } from "react";
import { getNostrClient } from "@/Api/nostr";
import { NostrKeyPair } from "../../Api/nostrHandler";
import { EditChannel } from "./EditChannel";
import { OpenChannelDialog } from "./OpenChannelDialog";
import { listedFromOpenChannels, type ListedChannel } from "./listedChannels";
import moment from "moment";
import type { OpenChannel } from "@/Api/pub/autogenerated/ts/types";
import { nip19 } from "nostr-tools";
import { useIonRouter } from "@ionic/react";
import { DashboardShell } from "@/Layout2/Metrics/DashboardShell";
import { DashErrorBanner } from "@/Pages/Metrics/DashErrorBanner";
import { usePubDashboardCapability } from "@/Pages/Metrics/usePubDashboardCapability";
import { useAppDispatch, useAppSelector } from "@/State/store/hooks";
import { selectSelectedAdminRpcSource, sourceRpcKey } from "@/State/scoped/backups/sources/selectors";
import {
	runtimeActions,
	selectOpenChannelsForSource,
	selectSelectedMetricsAdminSourceId,
} from "@/State/runtime/slice";

const Channels = () => {
	const router = useIonRouter();
	const dispatch = useAppDispatch();
	const [selectedChanId, setSelectedChanId] = useState<string | null>(null);
	const [startForce, setStartForce] = useState(false);
	const [openChannel, setOpenChannel] = useState(false);
	const [error, setError] = useState<string | null>(null);
	const [loading, setLoading] = useState(true);
	const [policyBusy, setPolicyBusy] = useState(false);

	const selectedId = useAppSelector(selectSelectedMetricsAdminSourceId);
	const adminSource = useAppSelector(selectSelectedAdminRpcSource)!;
	const rpcKey = sourceRpcKey(adminSource);
	const cached = useAppSelector((s) => selectOpenChannelsForSource(s, selectedId));
	const { checking: checkingPubCapability } = usePubDashboardCapability(adminSource);
	const listed = useMemo(() => listedFromOpenChannels(cached ?? []), [cached]);
	const selectedChannel = useMemo(
		() => cached?.find((c) => c.channel_id === selectedChanId) ?? null,
		[cached, selectedChanId],
	);

	const loadChannelList = useCallback(async () => {
		const client = await getNostrClient(
			{ pubkey: adminSource.lpk, relays: adminSource.relays },
			adminSource.keys as NostrKeyPair
		);
		const res = await client.ListChannels();
		if (res.status !== "OK") {
			throw new Error(res.reason || "Failed to list channels");
		}
		dispatch(runtimeActions.setOpenChannels({
			sourceId: adminSource.sourceId,
			channels: res.open_channels,
		}));
	}, [rpcKey, dispatch]);

	const fetchChannels = useCallback(async () => {
		setError(null);
		setLoading(true);
		try {
			await loadChannelList();
		} catch (e) {
			console.error(e);
			setError(e instanceof Error ? e.message : "Failed to fetch channels");
		} finally {
			setLoading(false);
		}
	}, [loadChannelList]);

	useEffect(() => {
		if (checkingPubCapability) return;
		if (cached?.some((c) => c.policy)) {
			setLoading(false);
			return;
		}
		if (cached) setLoading(false);
		setPolicyBusy(true);
		void loadChannelList()
			.catch((e) => {
				console.error(e);
				setError(e instanceof Error ? e.message : "Failed to fetch channels");
			})
			.finally(() => {
				setLoading(false);
				setPolicyBusy(false);
			});
	}, [rpcKey, checkingPubCapability, loadChannelList]);

	const totalRemote = sumField(listed.active, (c) => c.channel.remote_balance);
	const totalLocal = sumField(listed.active, (c) => c.channel.local_balance);
	const totalEncumbered = sumField(listed.offline, (c) => c.channel.local_balance);

	const openDetails = (channel: OpenChannel, force = false) => {
		setStartForce(force);
		setSelectedChanId(channel.channel_id);
		if (channel.policy || policyBusy) return;
		setPolicyBusy(true);
		void loadChannelList()
			.catch((e) => {
				console.error(e);
				setError(e instanceof Error ? e.message : "Failed to load channel fees");
			})
			.finally(() => setPolicyBusy(false));
	};

	const showList = !loading || !!cached;

	return (
		<DashboardShell title="Channels">
			{error && (
				<DashErrorBanner
					message={error}
					onRetry={() => void fetchChannels()}
					onChangeSource={() => router.push("/metrics/select", "back")}
				/>
			)}
			{loading && !cached && <p className="dash-field-hint">Loading channels…</p>}

			<div className="Channels">
				{showList && listed.offline.length > 0 && (
					<section className="dash-section">
						<div className="dash-section-head">
							<h2>Offline</h2>
							<span className="dash-section-count">{formatSats(totalEncumbered)} locked</span>
						</div>
						<div className="chan-stack">
							{listed.offline.map((ch) => (
								<OfflineRow
									key={ch.channel.channel_id}
									listed={ch}
									onSelect={() => openDetails(ch.channel)}
									onForceClose={() => openDetails(ch.channel, true)}
								/>
							))}
						</div>
					</section>
				)}

				<section className="dash-section">
					<div className="dash-section-head">
						<h2>Active</h2>
						<span className="dash-section-count">
							{formatSats(totalLocal)} out · {formatSats(totalRemote)} in
						</span>
					</div>
					{showList && listed.active.length === 0 ? (
						<p className="dash-field-hint">No active channels.</p>
					) : (
						<div className="chan-stack">
							{listed.active.map((ch) => (
								<ActiveRow
									key={ch.channel.channel_id}
									listed={ch}
									maxBalance={listed.max}
									onSelect={() => openDetails(ch.channel)}
								/>
							))}
						</div>
					)}
				</section>

				<div className="chan-foot">
					<button type="button" className="dash-btn dash-btn-lined" onClick={() => setOpenChannel(true)}>
						Open channel
					</button>
				</div>

				<OpenChannelDialog
					adminSource={adminSource}
					open={openChannel}
					onClose={() => setOpenChannel(false)}
					onOpened={() => void fetchChannels()}
				/>
				{selectedChannel && (
					<EditChannel
						key={`${selectedChannel.channel_id}-${startForce ? "force" : "view"}`}
						adminSource={adminSource}
						selectedChannel={selectedChannel}
						startForce={startForce}
						onClosed={() => void fetchChannels()}
						policyLoading={policyBusy}
						deselect={() => {
							setSelectedChanId(null);
							setStartForce(false);
						}}
					/>
				)}
				<div className="Channels_footer">
					Connected to <br />
					{nip19.nprofileEncode({ pubkey: adminSource.lpk, relays: adminSource.relays })}
				</div>
			</div>
		</DashboardShell>
	);
};

function OfflineRow({
	listed,
	onSelect,
	onForceClose,
}: {
	listed: ListedChannel;
	onSelect: () => void;
	onForceClose: () => void;
}) {
	const seen = listed.channel.inactive_since_unix;
	return (
		<div className="chan-row">
			<button type="button" className="chan-row-top" onClick={onSelect}>
				<PeerFace listed={listed} />
				<div className="chan-row-sub">
					<span>{formatSats(listed.channel.local_balance)}</span>
					<span>last seen {seen ? moment(seen * 1000).fromNow() : "unknown"}</span>
				</div>
			</button>
			<button type="button" className="chan-force" onClick={onForceClose}>
				Initiate force-close
			</button>
		</div>
	);
}

function ActiveRow({
	listed,
	maxBalance,
	onSelect,
}: {
	listed: ListedChannel;
	maxBalance: number;
	onSelect: () => void;
}) {
	const cap = listed.channel.remote_balance + listed.channel.local_balance;
	return (
		<button type="button" className="chan-row" onClick={onSelect}>
			<div className="chan-row-top">
				<PeerFace listed={listed} />
				<span className="chan-row-amt">{formatSats(cap)}</span>
			</div>
			<div className="chan-bars">
				<BalanceBar kind="in" sats={listed.channel.remote_balance} max={maxBalance} />
				<BalanceBar kind="out" sats={listed.channel.local_balance} max={maxBalance} />
			</div>
		</button>
	);
}

function PeerFace({ listed }: { listed: ListedChannel }) {
	return (
		<div className="chan-row-peer">
			<img src={listed.avatar} width={32} height={32} decoding="async" alt="" />
			<span className="chan-row-name">{listed.name}</span>
		</div>
	);
}

function BalanceBar({ kind, sats, max }: { kind: "in" | "out"; sats: number; max: number }) {
	const pct = max <= 0 ? 0 : Math.min(1, Math.max(sats / max, sats > 0 ? 0.02 : 0));
	return (
		<div className="chan-bar">
			<span className="chan-bar-k">{kind === "in" ? "IN" : "OUT"}</span>
			<div className="chan-bar-track">
				<div className={`chan-bar-fill is-${kind}`} style={{ width: `${pct * 100}%` }} />
			</div>
			<span className="chan-bar-amt">{formatSats(sats)}</span>
		</div>
	);
}

function sumField(list: ListedChannel[], pick: (c: ListedChannel) => number): number {
	return list.reduce((acc, c) => acc + pick(c), 0);
}

function formatSats(amount: number): string {
	if (amount >= 1_000_000) return `${amount / 1_000_000}M sat`;
	if (amount >= 1_000) return `${amount / 1_000}K sat`;
	return `${amount} sat`;
}

export default Channels;
