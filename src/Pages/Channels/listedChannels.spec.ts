import { describe, expect, it } from "vitest";
import type { OpenChannel } from "@/Api/pub/autogenerated/ts/types";
import { listedFromOpenChannels } from "./listedChannels";

const chan = (over: Partial<OpenChannel>): OpenChannel => ({
	active: true,
	capacity: 100,
	channel_id: "1",
	channel_point: "txid:0",
	inactive_since_unix: 0,
	label: "Alice",
	lifetime: 1,
	local_balance: 40,
	remote_balance: 60,
	...over,
});

describe("listedFromOpenChannels", () => {
	it("splits active and offline and tracks the largest side", () => {
		const listed = listedFromOpenChannels([
			chan({ channel_id: "on", local_balance: 10, remote_balance: 90 }),
			chan({ channel_id: "off", active: false, local_balance: 50, remote_balance: 0, label: "" }),
		]);
		expect(listed.active).toHaveLength(1);
		expect(listed.offline).toHaveLength(1);
		expect(listed.max).toBe(90);
		expect(listed.active[0].name).toBe("Alice");
	});
});
