import { getNostrClient } from "@/Api/nostr";
import { ResultError } from "@/Api/pub/autogenerated/ts/types";
import { appApi, appApiCaughtError, appApiError, type AppApiResult } from "@/State/api/api";
import { selectSourceViewById } from "@/State/scoped/backups/sources/selectors";
import type { RootState } from "@/State/store/store";

type PubDashboardCapability = "supported" | "needs_upgrade";

type SourceArg = {
	sourceId: string;
};

type RpcOutcome = ResultError | { status: "OK" };


function judgeCapability(
	newRpc: RpcOutcome,
	baseline: RpcOutcome,
): AppApiResult<PubDashboardCapability> {
	// pub explicitly says it knows the new RPC.
	if (newRpc.status === "OK") {
		return { data: "supported" };
	}

	const newRpcreason = newRpc.reason.toLowerCase();

	// pub explicitly says it doesn't know this new RPC.
	// NOTE: pub reporting that it doesn't know an RPC is a recent addition.
	if (newRpcreason.includes("unknown rpcname") || newRpcreason.includes("unkown rpcname")) {
		return { data: "needs_upgrade" };
	}

	// new RPC times out, but baseline succeeds -> pub is old
	if (newRpcreason === "request timed out") {
		if (baseline.status === "OK") {
			return { data: "needs_upgrade" };
		}
	}

	return appApiError(newRpcreason);
}

export const pubDashboardCapabilityApi = appApi.injectEndpoints({
	endpoints: (b) => ({
		getPubDashboardCapability: b.query<PubDashboardCapability, SourceArg>({
			queryFn: async ({ sourceId }, api): Promise<AppApiResult<PubDashboardCapability>> => {
				const source = selectSourceViewById(api.getState() as RootState, sourceId);
				if (!source) return appApiError("Source is not available");

				try {
					const client = await getNostrClient(
						{ pubkey: source.lpk, relays: source.relays },
						source.keys,
					);
					const [newRpc, baseline] = await Promise.all([
						client.GetUsersAdminInfo({ skip: 0, take: 1 }),
						client.LndGetInfo({ nodeId: 0 }),
					]);
					return judgeCapability(newRpc, baseline);
				} catch (e: unknown) {
					return appApiCaughtError(e, "Failed to probe dashboard capability");
				}
			},
		}),
	}),
});

export const { useGetPubDashboardCapabilityQuery } = pubDashboardCapabilityApi;
