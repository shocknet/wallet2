import { useState } from "react";
import { RouteComponentProps } from "react-router-dom";
import {
	IonBadge,
	IonButton,
	IonCard,
	IonCardContent,
	IonCardHeader,
	IonCardTitle,
	IonSkeletonText,
	IonText,
} from "@ionic/react";
import { UserAdminInfo } from "@/Api/pub/autogenerated/ts/types";
import { DashBoardPageChrome } from "@/Layout2/Metrics/DashBoardPageChrome";
import { DashErrorBanner } from "./DashErrorBanner";
import type { AppApiError } from "@/State/api/api";
import { useDashboardSource } from "./DashboardSourceContext";
import { formatTableAmount, MetricsDataTable, MetricsTableEmpty, MetricsTableRow } from "./metricsDataTable";
import { PubUpgradeNotice } from "./PubUpgradeNotice";
import { useGetUsersAdminInfoQuery } from "./pubDashApi";
import { useGetPubDashboardCapabilityQuery } from "./pubDashboardCapabilityApi";

const PAGE_SIZE = 50;
const USERS_GRID = "minmax(100px, 1.2fr) minmax(90px, 1fr) minmax(120px, 1.5fr) 68px";

function trimId(id: string): string {
	return id.length <= 12 ? id : `${id.slice(0, 6)}…${id.slice(-4)}`;
}

export default function UsersAdmin({ history }: RouteComponentProps) {
	const { sourceId } = useDashboardSource();

	const cap = useGetPubDashboardCapabilityQuery({ sourceId });
	const needsUpgrade = cap.data === "needs_upgrade";
	const capPending = !cap.data && (cap.isFetching || !cap.error);

	const [page, setPage] = useState(0);
	const skip = page * PAGE_SIZE;
	const { data, error, isFetching, refetch } = useGetUsersAdminInfoQuery(
		{ sourceId, skip, take: PAGE_SIZE },
		{ skip: needsUpgrade || capPending },
	);
	const loading = !data && (isFetching || !error);

	const rangeStart = !data || data.total === 0 ? 0 : skip + 1;
	const rangeEnd = data ? Math.min(skip + data.users.length, data.total) : 0;
	const hasPrev = page > 0;
	const hasNext = !!data && skip + data.users.length < data.total;

	const openUser = (user: UserAdminInfo) => {
		history.push(`/metrics/users/${user.user_id}`, { user });
	};

	return (
		<DashBoardPageChrome title="Users">
			{needsUpgrade ? (
				<PubUpgradeNotice
					featureLabel="Users admin"
					onRecheck={() => cap.refetch()}
					checking={cap.isFetching}
				/>
			) : capPending || loading ? (
				<UsersTableSkeleton />
			) : !data ? (
				<DashErrorBanner
					message={(error as AppApiError | undefined)?.message || "Could not list users"}
					onRetry={() => void refetch()}
				/>
			) : (
				<IonCard className="ion-margin-top">
					<IonCardHeader>
						<IonCardTitle>
							Users
							{data.total > 0 && (
								<IonText color="medium" style={{ fontSize: "0.85rem", fontWeight: 400, marginLeft: "8px" }}>
									({data.total.toLocaleString()})
								</IonText>
							)}
						</IonCardTitle>
					</IonCardHeader>
					<IonCardContent>
						<IonText color="medium" style={{ fontSize: "0.8rem", display: "block", marginBottom: "12px" }}>
							{data.total === 0
								? "No users"
								: `Showing ${rangeStart}–${rangeEnd} of ${data.total.toLocaleString()}`}
						</IonText>

						{data.users.length === 0 ? (
							<MetricsTableEmpty message="No users" />
						) : (
							<MetricsDataTable
								grid={USERS_GRID}
								minWidth="420px"
								header={
									<>
										<span>User</span>
										<span style={{ textAlign: "right" }}>Balance</span>
										<span>Details</span>
										<span style={{ textAlign: "center" }}>Status</span>
									</>
								}
							>
								{data.users.map((user, i) => (
									<MetricsTableRow
										key={user.user_id}
										grid={USERS_GRID}
										isLast={i === data.users.length - 1}
										onClick={() => openUser(user)}
									>
										<span style={{ overflow: "hidden", textOverflow: "ellipsis", whiteSpace: "nowrap" }}>
											{trimId(user.user_id)}
										</span>
										<span style={{ textAlign: "right", fontVariantNumeric: "tabular-nums" }}>
											{formatTableAmount(user.balance)}
										</span>
										<span style={{ fontSize: "0.8rem" }}>
											{user.app_users.length} app user{user.app_users.length === 1 ? "" : "s"}
											{user.owner_of_app_id ? ` · owns ${trimId(user.owner_of_app_id)}` : ""}
										</span>
										<div style={{ display: "flex", justifyContent: "center" }}>
											{user.locked ? (
												<IonBadge color="danger">Locked</IonBadge>
											) : (
												<IonText color="medium" style={{ fontSize: "0.8rem" }}>—</IonText>
											)}
										</div>
									</MetricsTableRow>
								))}
							</MetricsDataTable>
						)}

						<div style={{ display: "flex", gap: 8, marginTop: 12 }}>
							<IonButton fill="outline" disabled={!hasPrev || isFetching} onClick={() => setPage((p) => p - 1)}>
								Previous
							</IonButton>
							<IonButton fill="outline" disabled={!hasNext || isFetching} onClick={() => setPage((p) => p + 1)}>
								Next
							</IonButton>
							<IonButton fill="outline" disabled={isFetching} onClick={() => void refetch()}>
								Refresh
							</IonButton>
						</div>
					</IonCardContent>
				</IonCard>
			)}
		</DashBoardPageChrome>
	);
}

function UsersTableSkeleton() {
	return (
		<IonCard className="ion-margin-top">
			<IonCardHeader>
				<IonCardTitle>Users</IonCardTitle>
			</IonCardHeader>
			<IonCardContent>
				<IonSkeletonText animated style={{ width: "40%", height: 12, marginBottom: 12 }} />
				<IonSkeletonText animated style={{ width: "100%", height: 36, margin: 0 }} />
				<IonSkeletonText animated style={{ width: "100%", height: 36, marginTop: 8 }} />
				<IonSkeletonText animated style={{ width: "100%", height: 36, marginTop: 8 }} />
				<IonSkeletonText animated style={{ width: "70%", height: 36, marginTop: 8 }} />
			</IonCardContent>
		</IonCard>
	);
}
