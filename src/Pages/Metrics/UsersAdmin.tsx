import { useMemo, useState } from "react";
import { RouteComponentProps } from "react-router-dom";
import { IonButton, IonCard, IonCardContent, IonSkeletonText } from "@ionic/react";
import { Period } from "@/Components/Dropdowns/LVDropdown";
import { UserAdminInfo } from "@/Api/pub/autogenerated/ts/types";
import { DashBoardPageChrome } from "@/Layout2/Metrics/DashBoardPageChrome";
import { DashErrorBanner } from "./DashErrorBanner";
import type { AppApiError } from "@/State/api/api";
import { useDashboardSource } from "./DashboardSourceContext";
import { formatTableAmount, formatTableTs, MetricsDataTable, MetricsTableEmpty, MetricsTableRow } from "./metricsDataTable";
import { PubUpgradeNotice } from "./PubUpgradeNotice";
import { useGetAppsMetricsQuery, useGetUsersAdminInfoQuery } from "./pubDashApi";
import { useGetPubDashboardCapabilityQuery } from "./pubDashboardCapabilityApi";
import {
	appNamesById,
	arrangeUsers,
	isNodeAdmin,
	listHasLastSeen,
	trimUserId,
	UserAppChips,
	userAppLabels,
	userAppSortKey,
} from "./userAdminDisplay";

const PAGE_SIZE = 50;
type SortKey = "user" | "balance" | "app" | "seen";
type UsersSort = { key: SortKey; dir: "asc" | "desc" };

function usersGrid(showSeen: boolean): string {
	const base = "minmax(140px, 0.9fr) minmax(96px, 0.55fr) minmax(180px, 1.6fr)";
	return showSeen ? `${base} minmax(156px, 1fr)` : base;
}

function toggleSort(current: UsersSort | null, key: SortKey): UsersSort {
	if (!current || current.key !== key) {
		const dir = key === "user" || key === "app" ? "asc" : "desc";
		return { key, dir };
	}
	return { key, dir: current.dir === "asc" ? "desc" : "asc" };
}

function compareUsers(a: UserAdminInfo, b: UserAdminInfo, key: SortKey, names: Map<string, string>): number {
	if (key === "balance") return a.balance - b.balance;
	if (key === "seen") return (a.last_seen_at_unix ?? 0) - (b.last_seen_at_unix ?? 0);
	if (key === "app") return userAppSortKey(a, names).localeCompare(userAppSortKey(b, names));
	return a.user_id.localeCompare(b.user_id);
}

function sortedUsers(users: UserAdminInfo[], sort: UsersSort | null, names: Map<string, string>): UserAdminInfo[] {
	if (!sort) return users;
	const dir = sort.dir === "asc" ? 1 : -1;
	return [...users].sort((a, b) => compareUsers(a, b, sort.key, names) * dir);
}

export default function UsersAdmin({ history }: RouteComponentProps) {
	const source = useDashboardSource();
	const sourceId = source.sourceId;
	const adminNpub = source.keys.publicKey;
	const cap = useGetPubDashboardCapabilityQuery({ sourceId });
	const needsUpgrade = cap.data === "needs_upgrade";
	const capPending = !cap.data && (cap.isFetching || !cap.error);
	const [page, setPage] = useState(0);
	const [sort, setSort] = useState<UsersSort | null>(null);
	const skip = page * PAGE_SIZE;
	const { data, error, isFetching, refetch } = useGetUsersAdminInfoQuery(
		{ sourceId, skip, take: PAGE_SIZE },
		{ skip: needsUpgrade || capPending },
	);
	const apps = useGetAppsMetricsQuery(
		{ sourceId, period: Period.ALL_TIME, offset: 0 },
		{ skip: needsUpgrade || capPending },
	);
	const names = useMemo(
		() => appNamesById(apps.data?.apps.map((row) => row.app) ?? []),
		[apps.data],
	);
	const loading = !data && (isFetching || !error);
	const showSeen = !!data && listHasLastSeen(data.users);
	const rows = useMemo(
		() => (data ? arrangeUsers(data.users, adminNpub, (rest) => sortedUsers(rest, sort, names)) : []),
		[data, sort, names, adminNpub],
	);

	const rangeStart = !data || data.total === 0 ? 0 : skip + 1;
	const rangeEnd = data ? Math.min(skip + data.users.length, data.total) : 0;
	const hasPrev = page > 0;
	const hasNext = !!data && skip + data.users.length < data.total;
	const grid = usersGrid(showSeen);

	const openUser = (user: UserAdminInfo) => {
		history.push(`/dashboard/users/${user.user_id}`, { user });
	};

	return (
		<DashBoardPageChrome title="Users">
			{needsUpgrade ? (
				<PubUpgradeNotice
					featureLabel="Users admin"
					onRecheck={() => cap.refetch()}
					checking={cap.isFetching}
				/>
			) : capPending || loading ? (
				<UsersTableSkeleton />
			) : !data ? (
				<DashErrorBanner
					message={(error as AppApiError | undefined)?.message || "Could not list users"}
					onRetry={() => void refetch()}
				/>
			) : (
				<IonCard>
					<IonCardContent>
						<p className="dash-table-meta">
							{data.total === 0
								? "No users"
								: `Showing ${rangeStart}–${rangeEnd} of ${data.total.toLocaleString()}`}
						</p>
						{rows.length === 0 ? (
							<MetricsTableEmpty message="No users" />
						) : (
							<UsersTable
								rows={rows}
								names={names}
								adminNpub={adminNpub}
								grid={grid}
								showSeen={showSeen}
								sort={sort}
								onSort={(key) => setSort((current) => toggleSort(current, key))}
								onOpen={openUser}
							/>
						)}
						<UsersPager
							hasPrev={hasPrev}
							hasNext={hasNext}
							busy={isFetching}
							onPrev={() => setPage((p) => p - 1)}
							onNext={() => setPage((p) => p + 1)}
							onRefresh={() => void refetch()}
						/>
					</IonCardContent>
				</IonCard>
			)}
		</DashBoardPageChrome>
	);
}

function UsersTable({
	rows,
	names,
	adminNpub,
	grid,
	showSeen,
	sort,
	onSort,
	onOpen,
}: {
	rows: UserAdminInfo[];
	names: Map<string, string>;
	adminNpub: string;
	grid: string;
	showSeen: boolean;
	sort: UsersSort | null;
	onSort: (key: SortKey) => void;
	onOpen: (user: UserAdminInfo) => void;
}) {
	return (
		<MetricsDataTable
			grid={grid}
			minWidth={showSeen ? "720px" : "520px"}
			header={
				<>
					<SortHeader label="User" sortKey="user" sort={sort} onSort={onSort} />
					<SortHeader label="Balance" sortKey="balance" sort={sort} onSort={onSort} align="right" />
					<SortHeader label="App" sortKey="app" sort={sort} onSort={onSort} />
					{showSeen && <SortHeader label="Last seen" sortKey="seen" sort={sort} onSort={onSort} />}
				</>
			}
		>
			{rows.map((user, i) => (
				<MetricsTableRow
					key={user.user_id}
					grid={grid}
					isLast={i === rows.length - 1}
					onClick={() => onOpen(user)}
				>
					<UserIdCell user={user} />
					<span style={{ textAlign: "right", fontVariantNumeric: "tabular-nums" }}>
						{formatTableAmount(user.balance)}
					</span>
					<UserAppChips labels={userAppLabels(user, names)} admin={isNodeAdmin(user, adminNpub)} />
					{showSeen && (
						<span style={{ fontSize: "0.8rem" }}>{formatTableTs(user.last_seen_at_unix ?? 0)}</span>
					)}
				</MetricsTableRow>
			))}
		</MetricsDataTable>
	);
}

function UserIdCell({ user }: { user: UserAdminInfo }) {
	return (
		<span className="dash-user-cell">
			<span className="dash-user-id">{trimUserId(user.user_id)}</span>
			{user.locked && <span className="dash-chip is-locked">Locked</span>}
		</span>
	);
}

function SortHeader({
	label,
	sortKey,
	sort,
	onSort,
	align,
}: {
	label: string;
	sortKey: SortKey;
	sort: UsersSort | null;
	onSort: (key: SortKey) => void;
	align?: "right";
}) {
	const active = sort?.key === sortKey;
	return (
		<button
			type="button"
			className={`dash-sort${align === "right" ? " is-right" : ""}${active ? " is-active" : ""}`}
			onClick={() => onSort(sortKey)}
		>
			{label}
			{active && <span aria-hidden>{sort.dir === "asc" ? "↑" : "↓"}</span>}
		</button>
	);
}

function UsersPager({
	hasPrev,
	hasNext,
	busy,
	onPrev,
	onNext,
	onRefresh,
}: {
	hasPrev: boolean;
	hasNext: boolean;
	busy: boolean;
	onPrev: () => void;
	onNext: () => void;
	onRefresh: () => void;
}) {
	return (
		<div style={{ display: "flex", gap: 8, marginTop: 16 }}>
			<IonButton fill="outline" disabled={!hasPrev || busy} onClick={onPrev}>Previous</IonButton>
			<IonButton fill="outline" disabled={!hasNext || busy} onClick={onNext}>Next</IonButton>
			<IonButton fill="outline" disabled={busy} onClick={onRefresh}>Refresh</IonButton>
		</div>
	);
}

function UsersTableSkeleton() {
	return (
		<IonCard>
			<IonCardContent>
				<IonSkeletonText animated style={{ width: "40%", height: 12, marginBottom: 12 }} />
				<IonSkeletonText animated style={{ width: "100%", height: 36, margin: 0 }} />
				<IonSkeletonText animated style={{ width: "100%", height: 36, marginTop: 8 }} />
				<IonSkeletonText animated style={{ width: "100%", height: 36, marginTop: 8 }} />
				<IonSkeletonText animated style={{ width: "70%", height: 36, marginTop: 8 }} />
			</IonCardContent>
		</IonCard>
	);
}
