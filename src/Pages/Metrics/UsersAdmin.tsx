import { useCallback, useEffect, useMemo, useState } from "react";
import { RouteComponentProps } from "react-router-dom";
import {
    IonBadge,
    IonButton,
    IonCard,
    IonCardContent,
    IonCardHeader,
    IonCardTitle,
    IonText,
    useIonRouter,
} from "@ionic/react";
import { toast } from "react-toastify";
import { getNostrClient } from "@/Api/nostr";
import { UserAdminInfo, UsersAdminInfo } from "@/Api/pub/autogenerated/ts/types";
import { DashboardShell } from "@/Layout2/Metrics/DashboardShell";
import { DashErrorBanner } from "./DashErrorBanner";
import { useAppSelector } from "@/State/store/hooks";
import { selectAdminSourceViews } from "@/State/scoped/backups/sources/selectors";
import { selectSelectedMetricsAdminSourceId } from "@/State/runtime/slice";
import { formatTableAmount, MetricsDataTable, MetricsTableEmpty, MetricsTableRow } from "./metricsDataTable";
import { PubUpgradeNotice } from "./PubUpgradeNotice";
import { MetricsProbeSkeleton } from "./MetricsProbeSkeleton";
import { isMissingDashboardRpcError } from "./pubDashboardCapability";
import { usePubDashboardCapability } from "./usePubDashboardCapability";

const PAGE_SIZE = 50;
const USERS_GRID = "minmax(100px, 1.2fr) minmax(90px, 1fr) minmax(120px, 1.5fr) 68px";

function trimId(id: string): string {
    return id.length <= 12 ? id : `${id.slice(0, 6)}…${id.slice(-4)}`;
}

export default function UsersAdmin({ history }: RouteComponentProps) {
    const router = useIonRouter();
    const admins = useAppSelector(selectAdminSourceViews);
    const selectedId = useAppSelector(selectSelectedMetricsAdminSourceId);
    const adminSource = useMemo(
        () => admins.find((a) => a.sourceId === selectedId),
        [admins, selectedId]
    );
    const {
        needsUpgrade,
        checking: checkingPubCapability,
        recheck,
        markNeedsUpgrade,
    } = usePubDashboardCapability(adminSource);

    const [page, setPage] = useState(0);
    const [data, setData] = useState<UsersAdminInfo>({ total: 0, users: [] });
    const [loading, setLoading] = useState(true);
    const [error, setError] = useState<string | null>(null);

    const skip = page * PAGE_SIZE;
    const rangeStart = data.total === 0 ? 0 : skip + 1;
    const rangeEnd = Math.min(skip + data.users.length, data.total);
    const hasPrev = page > 0;
    const hasNext = skip + data.users.length < data.total;

    const fetchUsers = useCallback(async () => {
        if (!adminSource) return;
        setError(null);
        setLoading(true);
        try {
            const client = await getNostrClient(
                { pubkey: adminSource.lpk, relays: adminSource.relays },
                adminSource.keys
            );
            const res = await client.GetUsersAdminInfo({ skip, take: PAGE_SIZE });
            if (res.status !== "OK") {
                if (isMissingDashboardRpcError(res.reason)) {
                    markNeedsUpgrade();
                    return;
                }
                setError(res.reason || "Could not list users");
                toast.error(res.reason || "Could not list users");
                return;
            }
            setData(res);
        } catch (e) {
            const msg = e instanceof Error ? e.message : "Could not list users";
            if (isMissingDashboardRpcError(msg)) {
                markNeedsUpgrade();
                return;
            }
            setError(msg);
            toast.error(msg);
        } finally {
            setLoading(false);
        }
    }, [adminSource, markNeedsUpgrade, skip]);

    useEffect(() => {
        if (checkingPubCapability) return;
        if (needsUpgrade) {
            setLoading(false);
            return;
        }
        void fetchUsers();
    }, [checkingPubCapability, needsUpgrade, page, selectedId]);

    const openUser = (user: UserAdminInfo) => {
        history.push(`/metrics/users/${user.user_id}`, { user });
    };

    return (
        <DashboardShell title="Users">
                {needsUpgrade && (
                    <PubUpgradeNotice
                        featureLabel="Users admin"
                        onRecheck={recheck}
                        checking={checkingPubCapability}
                    />
                )}

                {!needsUpgrade && checkingPubCapability && (
                    <MetricsProbeSkeleton variant="page" />
                )}

                {!needsUpgrade && !checkingPubCapability && error && (
                    <DashErrorBanner
                        message={error}
                        onRetry={() => void fetchUsers()}
                        onChangeSource={() => router.push("/metrics/select", "back")}
                    />
                )}

                {!needsUpgrade && !checkingPubCapability && !error && (
                    <>
                        <IonCard className="ion-margin-top">
                            <IonCardHeader>
                                <IonCardTitle>
                                    Users
                                    {data.total > 0 && (
                                        <IonText color="medium" style={{ fontSize: "0.85rem", fontWeight: 400, marginLeft: "8px" }}>
                                            ({data.total.toLocaleString()})
                                        </IonText>
                                    )}
                                </IonCardTitle>
                            </IonCardHeader>
                            <IonCardContent>
                                <IonText color="medium" style={{ fontSize: "0.8rem", display: "block", marginBottom: "12px" }}>
                                    {loading
                                        ? "Loading users…"
                                        : data.total === 0
                                        ? "No users"
                                        : `Showing ${rangeStart}–${rangeEnd} of ${data.total.toLocaleString()}`}
                                </IonText>

                                {loading && data.users.length === 0 ? (
                                    <p className="dash-field-hint">Loading users…</p>
                                ) : data.users.length === 0 ? (
                                    <MetricsTableEmpty message="No users" />
                                ) : (
                                    <MetricsDataTable
                                        grid={USERS_GRID}
                                        minWidth="420px"
                                        header={
                                            <>
                                                <span>User</span>
                                                <span style={{ textAlign: "right" }}>Balance</span>
                                                <span>Details</span>
                                                <span style={{ textAlign: "center" }}>Status</span>
                                            </>
                                        }
                                    >
                                        {data.users.map((user, i) => (
                                            <MetricsTableRow
                                                key={user.user_id}
                                                grid={USERS_GRID}
                                                isLast={i === data.users.length - 1}
                                                onClick={() => openUser(user)}
                                            >
                                                <span style={{ overflow: "hidden", textOverflow: "ellipsis", whiteSpace: "nowrap" }}>
                                                    {trimId(user.user_id)}
                                                </span>
                                                <span style={{ textAlign: "right", fontVariantNumeric: "tabular-nums" }}>
                                                    {formatTableAmount(user.balance)}
                                                </span>
                                                <span style={{ fontSize: "0.8rem" }}>
                                                    {user.app_users.length} app user{user.app_users.length === 1 ? "" : "s"}
                                                    {user.owner_of_app_id ? ` · owns ${trimId(user.owner_of_app_id)}` : ""}
                                                </span>
                                                <div style={{ display: "flex", justifyContent: "center" }}>
                                                    {user.locked ? (
                                                        <IonBadge color="danger">Locked</IonBadge>
                                                    ) : (
                                                        <IonText color="medium" style={{ fontSize: "0.8rem" }}>—</IonText>
                                                    )}
                                                </div>
                                            </MetricsTableRow>
                                        ))}
                                    </MetricsDataTable>
                                )}

                                <div style={{ display: "flex", gap: 8, marginTop: 12 }}>
                                    <IonButton fill="outline" disabled={!hasPrev || loading} onClick={() => setPage((p) => p - 1)}>
                                        Previous
                                    </IonButton>
                                    <IonButton fill="outline" disabled={!hasNext || loading} onClick={() => setPage((p) => p + 1)}>
                                        Next
                                    </IonButton>
                                    <IonButton fill="outline" disabled={loading} onClick={() => void fetchUsers()}>
                                        Refresh
                                    </IonButton>
                                </div>
                            </IonCardContent>
                        </IonCard>
                    </>
                )}
        </DashboardShell>
    );
}
