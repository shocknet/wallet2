import { UserAdminInfo } from "@/Api/pub/autogenerated/ts/types";

export type UserAppLabel = { name: string; owner: boolean };

export function isNodeAdmin(user: UserAdminInfo, adminNpub: string): boolean {
	if (user.is_node_admin) return true;
	const want = adminNpub.trim().toLowerCase();
	if (!want) return false;
	return user.app_users.some((appUser) => (appUser.npub || "").toLowerCase() === want);
}

export function arrangeUsers(
	users: UserAdminInfo[],
	adminNpub: string,
	sort: ((users: UserAdminInfo[]) => UserAdminInfo[]) | null,
): UserAdminInfo[] {
	const pinned: UserAdminInfo[] = [];
	const rest: UserAdminInfo[] = [];
	for (const user of users) {
		if (isPinnedUser(user, adminNpub)) pinned.push(user);
		else rest.push(user);
	}
	pinned.sort((a, b) => pinRank(a, adminNpub) - pinRank(b, adminNpub) || a.user_id.localeCompare(b.user_id));
	return [...pinned, ...(sort ? sort(rest) : rest)];
}

function isPinnedUser(user: UserAdminInfo, adminNpub: string): boolean {
	return isNodeAdmin(user, adminNpub) || !!user.owner_of_app_id;
}

function pinRank(user: UserAdminInfo, adminNpub: string): number {
	if (isNodeAdmin(user, adminNpub)) return 0;
	if (user.owner_of_app_id) return 1;
	return 2;
}

export function trimUserId(id: string): string {
	return id.length <= 12 ? id : `${id.slice(0, 6)}…${id.slice(-4)}`;
}

export function appNamesById(apps: { id: string; name: string }[]): Map<string, string> {
	return new Map(apps.map((app) => [app.id, app.name]));
}

export function userAppLabels(user: UserAdminInfo, names: Map<string, string>): UserAppLabel[] {
	const labels: UserAppLabel[] = [];
	const indexByName = new Map<string, number>();
	for (const appUser of user.app_users) {
		const name = appUser.app_name?.trim();
		if (!name || indexByName.has(name)) continue;
		indexByName.set(name, labels.length);
		labels.push({ name, owner: false });
	}
	return withOwnerLabel(labels, indexByName, user.owner_of_app_id, names);
}

function withOwnerLabel(
	labels: UserAppLabel[],
	indexByName: Map<string, number>,
	ownerAppId: string | undefined,
	names: Map<string, string>,
): UserAppLabel[] {
	if (!ownerAppId) return labels;
	const ownedName = names.get(ownerAppId)?.trim() || trimUserId(ownerAppId);
	const existing = indexByName.get(ownedName);
	if (existing == null) return [{ name: ownedName, owner: true }, ...labels];
	const next = labels.slice();
	next[existing] = { ...next[existing], owner: true };
	return next;
}

export function userAppSortKey(user: UserAdminInfo, names: Map<string, string>): string {
	return userAppLabels(user, names).map((label) => label.name).join(", ").toLowerCase();
}

export function listHasLastSeen(users: UserAdminInfo[]): boolean {
	return users.some((user) => typeof user.last_seen_at_unix === "number");
}

export function UserAppChips({ labels, admin = false }: { labels: UserAppLabel[]; admin?: boolean }) {
	if (labels.length === 0 && !admin) return null;
	return (
		<span className="dash-chips">
			{labels.map((label) => (
				<span key={label.name} className="dash-chips">
					<span>{label.name}</span>
					{label.owner && <span className="dash-chip is-owner">Owner</span>}
				</span>
			))}
			{admin && <span className="dash-chip is-admin">Admin</span>}
		</span>
	);
}
