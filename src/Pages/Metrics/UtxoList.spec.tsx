import { render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { describe, expect, it, vi } from 'vitest';
import { UtxoOrigin, type LndUtxo } from '@/Api/pub/autogenerated/ts/types';
import { UtxoList } from './UtxoList';

const query = vi.hoisted(() => ({ data: [] as LndUtxo[], isFetching: false, error: undefined }));
vi.mock('./pubDashApi', () => ({ useListUtxosQuery: () => query }));
vi.mock('./pubDashboardCapabilityApi', () => ({ useGetPubDashboardCapabilityQuery: () => ({ data: 'supported' }) }));
vi.mock('./DashboardSourceContext', () => ({ useDashboardSource: () => ({ sourceId: 'node-1' }) }));
vi.mock('@/State/store/hooks', () => ({ useAppDispatch: () => vi.fn() }));
vi.mock('@/lib/contexts/useToast', () => ({ useToast: () => ({ showToast: vi.fn() }) }));
vi.mock('@/State/thunks/copyToClipboard', () => ({ copyToClipboard: vi.fn() }));

const coin = (txid: string, amount: number, origin?: UtxoOrigin, change = false): LndUtxo => ({
    txid, amount_sat: amount, origin, is_change: change, address: 'address', confirmations: 1, output_index: 0,
});

describe('UTXO sources', () => {
    it('labels change, filters by origin, and totals only visible coins', async () => {
        query.data = [coin('deposit', 100, UtxoOrigin.USER_DEPOSIT), coin('user-change', 200, UtxoOrigin.USER_DEPOSIT, true),
            coin('channel', 400, UtxoOrigin.CHANNEL, true), coin('mixed', 800, UtxoOrigin.MIXED), coin('unknown', 1600)];
        const user = userEvent.setup();
        render(<UtxoList />);
        expect(screen.getByText('User deposit · change')).toBeInTheDocument();
        expect(screen.getByText('Channel ops · change')).toBeInTheDocument();
        expect(screen.getByText('3 100 sats')).toBeInTheDocument();
        await user.selectOptions(screen.getByRole('combobox', { name: 'UTXO source' }), UtxoOrigin.USER_DEPOSIT);
        expect(screen.getByText('300 sats')).toBeInTheDocument();
        expect(screen.queryByText('Channel ops · change')).not.toBeInTheDocument();
        expect(screen.getAllByRole('button', { name: 'Copy output' })).toHaveLength(2);
        await user.selectOptions(screen.getByRole('combobox', { name: 'UTXO source' }), UtxoOrigin.CHANNEL);
        expect(screen.getByText('400 sats')).toBeInTheDocument();
        expect(screen.queryByText('User deposit · change')).not.toBeInTheDocument();
    });

    it('treats responses from older nodes as unknown and handles an empty filter', async () => {
        query.data = [coin('legacy', 123)];
        const user = userEvent.setup();
        render(<UtxoList />);
        await user.selectOptions(screen.getByRole('combobox', { name: 'UTXO source' }), UtxoOrigin.UNKNOWN);
        expect(screen.getByText('legacy:0')).toBeInTheDocument();
        expect(screen.getByText('123 sats')).toBeInTheDocument();
        await user.selectOptions(screen.getByRole('combobox', { name: 'UTXO source' }), UtxoOrigin.USER_DEPOSIT);
        expect(screen.getByText('No outputs from this source.')).toBeInTheDocument();
        expect(screen.getByText('0 sats')).toBeInTheDocument();
    });
});
