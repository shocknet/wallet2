import { useEffect, useMemo, useState } from "react";
import { getNostrClient } from "@/Api/nostr";
import type { LndUtxo } from "@/Api/pub/autogenerated/ts/types";
import { SourceView } from "@/State/scoped/backups/sources/selectors";
import { formatTableAmount } from "./metricsDataTable";
import { isMissingDashboardRpcError } from "./pubDashboardCapability";

export function UtxoList({ adminSource }: { adminSource: SourceView }) {
	const [utxos, setUtxos] = useState<LndUtxo[]>([]);
	const [loading, setLoading] = useState(true);
	const [missing, setMissing] = useState(false);
	const [error, setError] = useState<string | null>(null);
	const ordered = useMemo(() => sortUtxos(utxos), [utxos]);
	const relayKey = adminSource.relays.join("|");

	useEffect(() => {
		let cancelled = false;
		const load = async () => {
			setError(null);
			setMissing(false);
			setLoading(true);
			try {
				const client = await getNostrClient(
					{ pubkey: adminSource.lpk, relays: adminSource.relays },
					adminSource.keys
				);
				const res = await client.ListUtxos();
				if (cancelled) return;
				if (res.status !== "OK") {
					if (isMissingDashboardRpcError(res.reason)) {
						setMissing(true);
						setUtxos([]);
						return;
					}
					setError(res.reason || "Could not list UTXOs");
					return;
				}
				setUtxos(res.utxos);
			} catch (e) {
				if (cancelled) return;
				const msg = e instanceof Error ? e.message : "Could not list UTXOs";
				if (isMissingDashboardRpcError(msg)) {
					setMissing(true);
					setUtxos([]);
					return;
				}
				setError(msg);
			} finally {
				if (!cancelled) setLoading(false);
			}
		};
		void load();
		return () => {
			cancelled = true;
		};
	}, [adminSource.sourceId, adminSource.lpk, relayKey]);

	if (missing) {
		return (
			<div className="dash-callout">
				<h6>Pub update needed</h6>
				<p>This Pub cannot list on-chain coins yet.</p>
			</div>
		);
	}

	return (
		<div className="dash-section">
			<div className="dash-section-head">
				<h2>On-chain</h2>
				<span className="dash-section-count">{loading ? "…" : ordered.length}</span>
			</div>
			{error && <p className="dash-field-hint">{error}</p>}
			{loading ? (
				<p className="dash-field-hint">Loading UTXOs…</p>
			) : ordered.length === 0 ? (
				<p className="dash-field-hint">No unspent outputs.</p>
			) : (
				<div className="dash-peer-stack">
					{ordered.map((utxo) => (
						<UtxoRow key={outpoint(utxo)} utxo={utxo} />
					))}
				</div>
			)}
		</div>
	);
}

function UtxoRow({ utxo }: { utxo: LndUtxo }) {
	const unconfirmed = utxo.confirmations <= 0;
	return (
		<div className="dash-peer-item">
			<div className="dash-peer-item-main">
				<div className="dash-peer-item-name">{formatTableAmount(utxo.amount_sat)} sats</div>
				<div className="dash-peer-item-sub">
					{shortId(utxo.address)} · {shortId(utxo.txid)}:{utxo.output_index}
					{unconfirmed ? "" : ` · ${utxo.confirmations} conf`}
				</div>
			</div>
			{unconfirmed && <span className="dash-pill is-warn">unconfirmed</span>}
		</div>
	);
}

function sortUtxos(utxos: LndUtxo[]) {
	return [...utxos].sort((a, b) => {
		if (a.confirmations <= 0 && b.confirmations > 0) return -1;
		if (a.confirmations > 0 && b.confirmations <= 0) return 1;
		return b.amount_sat - a.amount_sat;
	});
}

function outpoint(utxo: LndUtxo) {
	return `${utxo.txid}:${utxo.output_index}`;
}

function shortId(value: string) {
	if (value.length < 16) return value || "—";
	return `${value.slice(0, 8)}…${value.slice(-8)}`;
}
