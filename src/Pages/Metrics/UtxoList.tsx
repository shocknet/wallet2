import { useMemo, useState } from "react";
import { UtxoOrigin, type LndUtxo } from "@/Api/pub/autogenerated/ts/types";
import type { AppApiError } from "@/State/api/api";
import { useToast } from "@/lib/contexts/useToast";
import { useAppDispatch } from "@/State/store/hooks";
import { copyToClipboard } from "@/State/thunks/copyToClipboard";
import { formatTableAmount } from "./metricsDataTable";
import { useDashboardSource } from "./DashboardSourceContext";
import { useListUtxosQuery } from "./pubDashApi";
import { useGetPubDashboardCapabilityQuery } from "./pubDashboardCapabilityApi";
import { PubUpgradeNotice } from "./PubUpgradeNotice";

export function UtxoList() {
	const [origin, setOrigin] = useState<UtxoOrigin | "ALL">("ALL");
	const { sourceId } = useDashboardSource();
	const cap = useGetPubDashboardCapabilityQuery({ sourceId });
	const needsUpgrade = cap.data === "needs_upgrade";
	const capPending = !cap.data && (cap.isFetching || !cap.error);
	const { data, error, isFetching } = useListUtxosQuery(
		{ sourceId },
		{ skip: needsUpgrade || capPending },
	);
	const ordered = useMemo(() => {
		const visible = (data ?? []).filter(utxo => origin === "ALL" || utxoOrigin(utxo) === origin);
		return sortUtxos(visible);
	}, [data, origin]);
	const total = ordered.reduce((sum, utxo) => sum + utxo.amount_sat, 0);
	const loading = capPending || (!data && (isFetching || !error));
	const errMsg = (error as AppApiError | undefined)?.message || "Could not list UTXOs";

	if (needsUpgrade) {
		return (
			<PubUpgradeNotice
				featureLabel="listing on-chain coins"
				onRecheck={cap.refetch}
				checking={cap.isFetching}
			/>
		);
	}

	return (
		<div className="dash-section">
			<div className="dash-section-head">
				<h2>On-chain</h2>
				<span className="dash-section-count">{loading ? "…" : ordered.length}</span>
			</div>
			{error ? <p className="dash-field-hint">{errMsg}</p> : null}
			{data?.length ? (
				<div className="dash-utxo-tools">
					<label className="dash-utxo-filter">
						Source
						<select aria-label="UTXO source" value={origin} onChange={event => setOrigin(event.target.value as UtxoOrigin | "ALL")}>
							<option value="ALL">All sources</option>
							<option value={UtxoOrigin.USER_DEPOSIT}>User deposits</option>
							<option value={UtxoOrigin.CHANNEL}>Channel ops</option>
							<option value={UtxoOrigin.MIXED}>Mixed</option>
							<option value={UtxoOrigin.UNKNOWN}>Unknown</option>
						</select>
					</label>
					<span>{formatTableAmount(total)} sats</span>
				</div>
			) : null}
			{loading ? (
				<p className="dash-field-hint">Loading UTXOs…</p>
			) : ordered.length === 0 ? (
				<p className="dash-field-hint">{data?.length ? "No outputs from this source." : "No unspent outputs."}</p>
			) : (
				<div className="dash-utxo">
					<div className="dash-utxo-row is-head">
						<span>Amount</span>
						<span>Source</span>
						<span className="dash-utxo-conf">Conf</span>
						<span>Output</span>
						<span>Hash</span>
					</div>
					{ordered.map((utxo) => (
						<UtxoRow key={outpoint(utxo)} utxo={utxo} />
					))}
				</div>
			)}
			{data?.length ? <p className="dash-field-hint">Includes change. Mixed outputs combine user and channel funds; unknown outputs have no established source.</p> : null}
		</div>
	);
}

function UtxoRow({ utxo }: { utxo: LndUtxo }) {
	const point = outpoint(utxo);
	return (
		<div className="dash-utxo-row">
			<span className="dash-utxo-amt">{formatTableAmount(utxo.amount_sat)}</span>
			<span className={`dash-utxo-source is-${utxoOrigin(utxo).toLowerCase()}`}>
				{originLabel(utxo)}
			</span>
			<span className="dash-utxo-conf">{utxo.confirmations}</span>
			<CopyValue label={shortPoint(utxo)} value={point} name="output" />
			<CopyValue label={shortId(utxo.txid)} value={utxo.txid} name="hash" />
		</div>
	);
}

function utxoOrigin(utxo: LndUtxo) {
	return Object.values(UtxoOrigin).includes(utxo.origin as UtxoOrigin) ? utxo.origin! : UtxoOrigin.UNKNOWN;
}

function originLabel(utxo: LndUtxo) {
	const labels = {
		[UtxoOrigin.USER_DEPOSIT]: "User deposit",
		[UtxoOrigin.CHANNEL]: "Channel ops",
		[UtxoOrigin.MIXED]: "Mixed",
		[UtxoOrigin.UNKNOWN]: "Unknown",
	};
	return `${labels[utxoOrigin(utxo)]}${utxo.is_change ? " · change" : ""}`;
}

function CopyValue({ label, value, name }: { label: string; value: string; name: string }) {
	const dispatch = useAppDispatch();
	const { showToast } = useToast();
	return (
		<button
			type="button"
			className="dash-utxo-copy"
			title={value}
			aria-label={`Copy ${name}`}
			onClick={() => dispatch(copyToClipboard(value, showToast, false))}
		>
			{label}
		</button>
	);
}

function sortUtxos(utxos: LndUtxo[]) {
	return [...utxos].sort((a, b) => {
		if (a.confirmations <= 0 && b.confirmations > 0) return -1;
		if (a.confirmations > 0 && b.confirmations <= 0) return 1;
		return b.amount_sat - a.amount_sat;
	});
}

function outpoint(utxo: LndUtxo) {
	return `${utxo.txid}:${utxo.output_index}`;
}

function shortPoint(utxo: LndUtxo) {
	return `${shortId(utxo.txid)}:${utxo.output_index}`;
}

function shortId(value: string) {
	if (value.length < 14) return value || "—";
	return `${value.slice(0, 6)}…${value.slice(-4)}`;
}
