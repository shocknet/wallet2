function periodFromSearch(): Period {
	const p = new URLSearchParams(window.location.search).get("period");
	if (p && (Object.values(Period) as string[]).includes(p)) return p as Period;
	return Period.WEEK;
}

function offsetFromSearch(): number {
	const raw = new URLSearchParams(window.location.search).get("offset");
	const n = raw != null ? parseInt(raw, 10) : 0;
	return Number.isFinite(n) ? n : 0;
}

function isUnknownRpc(error: unknown): boolean {
	const msg = ((error as AppApiError | undefined)?.message || "").toLowerCase();
	return msg.includes("unknown rpcname") || msg.includes("unkown rpcname");
}

function shortPubkey(value: string): string {
	if (!value) return "—";
	if (value.length <= 16) return value;
	return `${value.slice(0, 8)}…${value.slice(-6)}`;
}

export default function Payments() {
	const [period, setPeriod] = useState<Period>(periodFromSearch);
	const [offset, setOffset] = useState<number>(offsetFromSearch);
	const { sourceId } = useDashboardSource();

	const failed = useGetFailedOutgoingPaymentsInfiniteQuery({ sourceId, period, offset });
	const destinations = useGetPaymentDestinationsQuery({ sourceId, period, offset });

	const needsUpgrade = isUnknownRpc(failed.error) || isUnknownRpc(destinations.error);
	const failedData = failed.currentData;
	const destData = destinations.currentData;
	const payments = useMemo(
		() => failedData?.pages.flatMap((page) => page.payments) ?? [],
		[failedData],
	);
	const reasonCounts = failedData?.pages[0]?.reason_counts ?? [];
	const failedLoading = !failedData && (failed.isFetching || !failed.error);
	const destLoading = !destData && (destinations.isFetching || !destinations.error);
	const failedErr = (failed.error as AppApiError | undefined)?.message || "Failed to load failed payments";
	const destErr = (destinations.error as AppApiError | undefined)?.message || "Failed to load destinations";

	const nextOffset = () => {
		if (period === Period.ALL_TIME || offset >= 0) return;
		setOffset(offset + 1);
	};
	const prevOffset = () => {
		if (period === Period.ALL_TIME) return;
		setOffset(offset - 1);
	};

	const refetchAll = () => {
		void failed.refetch();
		void destinations.refetch();
	};

	return (
		<DashBoardPageChrome title="Payments">
			<PeriodSelector
				period={period}
				offset={offset}
				setPeriod={setPeriod}
				resetOffset={() => setOffset(0)}
				prevOffset={prevOffset}
				nextOffset={nextOffset}
				disabled={failed.isFetching || destinations.isFetching}
			/>
			{needsUpgrade ? (
				<PubUpgradeNotice
					featureLabel="payment reports"
					onRecheck={refetchAll}
					checking={failed.isFetching || destinations.isFetching}
				/>
			) : (
				<>
					<FailedPaymentsSection
						loading={failedLoading}
						error={!failedData ? failedErr : null}
						onRetry={() => void failed.refetch()}
						reasonCounts={reasonCounts}
						payments={payments}
						hasNextPage={!!failed.hasNextPage}
						loadingMore={failed.isFetchingNextPage}
						onLoadMore={() => void failed.fetchNextPage()}
					/>
					<DestinationsSection
						loading={destLoading}
						error={!destData ? destErr : null}
						onRetry={() => void destinations.refetch()}
						destinations={destData?.destinations ?? []}
					/>
				</>
			)}
		</DashBoardPageChrome>
	);
}

function FailedPaymentsSection({
	loading,
	error,
	onRetry,
	reasonCounts,
	payments,
	hasNextPage,
	loadingMore,
	onLoadMore,
}: {
	loading: boolean;
	error: string | null;
	onRetry: () => void;
	reasonCounts: FailedOutgoingPaymentReasonCount[];
	payments: FailedOutgoingPayment[];
	hasNextPage: boolean;
	loadingMore: boolean;
	onLoadMore: () => void;
}) {
	const history = useHistory();
	const grid = "minmax(120px, 0.9fr) minmax(72px, 0.5fr) minmax(160px, 1.4fr) minmax(96px, 0.7fr) minmax(110px, 0.9fr) minmax(90px, 0.6fr)";

	return (
		<IonCard className="ion-margin-top">
			<IonCardHeader>
				<IonCardTitle>Failed outgoing</IonCardTitle>
			</IonCardHeader>
			<IonCardContent>
				{loading ? (
					<PaymentsSkeleton rows={3} />
				) : error ? (
					<DashErrorBanner message={error} onRetry={onRetry} />
				) : (
					<>
						{reasonCounts.length > 0 && (
							<div style={{ display: "flex", flexWrap: "wrap", gap: 8, marginBottom: 16 }}>
								{reasonCounts.map((row) => (
									<div
										key={`${row.failure_reason}:${row.operator_reason}`}
										className="dash-chip"
										title={row.failure_reason || undefined}
										style={{ padding: "6px 10px" }}
									>
										<strong>{row.count}</strong>
										<span style={{ marginLeft: 6 }}>{row.operator_reason || row.failure_reason || "Unknown"}</span>
									</div>
								))}
							</div>
						)}
						{payments.length === 0 ? (
							<MetricsTableEmpty message="No failed payments in this period" />
						) : (
							<>
								<MetricsDataTable
									grid={grid}
									minWidth="760px"
									header={
										<>
											<span>When</span>
											<span style={{ textAlign: "right" }}>Amount</span>
											<span>Reason</span>
											<span>User</span>
											<span>Dest</span>
											<span>LP</span>
										</>
									}
								>
									{payments.map((payment, i) => (
										<MetricsTableRow
											key={payment.serial_id}
											grid={grid}
											isLast={i === payments.length - 1}
										>
											<span style={{ fontSize: "0.8rem" }}>{formatTableTs(payment.failed_at_unix)}</span>
											<span style={{ textAlign: "right", fontVariantNumeric: "tabular-nums" }}>
												{formatTableAmount(payment.amount_sats)}
											</span>
											<span title={payment.failure_reason || undefined}>
												{payment.operator_reason || payment.failure_reason || "—"}
											</span>
											<button
												type="button"
												className="dash-utxo-copy"
												title={payment.user_id}
												onClick={() => history.push(`/dashboard/users/${payment.user_id}`)}
											>
												{trimUserId(payment.user_id)}
											</button>
											<CopyCell label={shortPubkey(payment.dest_pubkey)} value={payment.dest_pubkey} name="dest pubkey" />
											<span style={{ fontSize: "0.8rem" }}>
												{payment.liquidity_provider ? shortPubkey(payment.liquidity_provider) : "—"}
											</span>
										</MetricsTableRow>
									))}
								</MetricsDataTable>
								{hasNextPage && (
									<IonButton
										expand="block"
										fill="outline"
										className="ion-margin-top"
										disabled={loadingMore}
										onClick={onLoadMore}
									>
										{loadingMore ? "Loading…" : "Load more"}
									</IonButton>
								)}
							</>
						)}
					</>
				)}
			</IonCardContent>
		</IonCard>
	);
}

function DestinationsSection({
	loading,
	error,
	onRetry,
	destinations,
}: {
	loading: boolean;
	error: string | null;
	onRetry: () => void;
	destinations: PaymentDestination[];
}) {
	const grid = "minmax(180px, 1.4fr) minmax(72px, 0.5fr) minmax(110px, 0.8fr)";

	return (
		<IonCard className="ion-margin-top">
			<IonCardHeader>
				<IonCardTitle>Popular destinations</IonCardTitle>
			</IonCardHeader>
			<IonCardContent>
				{loading ? (
					<PaymentsSkeleton rows={3} />
				) : error ? (
					<DashErrorBanner message={error} onRetry={onRetry} />
				) : destinations.length === 0 ? (
					<MetricsTableEmpty message="No successful outbound payments in this period" />
				) : (
					<>
						<IonText color="medium" style={{ fontSize: "0.8rem", display: "block", marginBottom: 12 }}>
							Successful user Lightning payments grouped by destination node
						</IonText>
						<MetricsDataTable
							grid={grid}
							minWidth="420px"
							header={
								<>
									<span>Node</span>
									<span style={{ textAlign: "right" }}>Count</span>
									<span style={{ textAlign: "right" }}>Volume</span>
								</>
							}
						>
							{destinations.map((dest, i) => (
								<MetricsTableRow key={dest.pubkey} grid={grid} isLast={i === destinations.length - 1}>
									<div style={{ display: "flex", flexDirection: "column", gap: 2, minWidth: 0 }}>
										<span>{dest.alias?.trim() || shortPubkey(dest.pubkey)}</span>
										<CopyCell label={shortPubkey(dest.pubkey)} value={dest.pubkey} name="pubkey" />
									</div>
									<span style={{ textAlign: "right", fontVariantNumeric: "tabular-nums" }}>
										{formatTableAmount(dest.count)}
									</span>
									<span style={{ textAlign: "right", fontVariantNumeric: "tabular-nums" }}>
										{formatTableAmount(dest.volume_sats)}
									</span>
								</MetricsTableRow>
							))}
						</MetricsDataTable>
					</>
				)}
			</IonCardContent>
		</IonCard>
	);
}

function CopyCell({ label, value, name }: { label: string; value: string; name: string }) {
	const dispatch = useAppDispatch();
	const { showToast } = useToast();
	if (!value) return <span>—</span>;
	return (
		<button
			type="button"
			className="dash-utxo-copy"
			title={value}
			aria-label={`Copy ${name}`}
			onClick={() => dispatch(copyToClipboard(value, showToast, false))}
		>
			{label}
		</button>
	);
}

function PaymentsSkeleton({ rows }: { rows: number }) {
	return (
		<>
			{Array.from({ length: rows }, (_, i) => (
				<IonSkeletonText
					key={i}
					animated
					style={{ width: "100%", height: 36, marginTop: i === 0 ? 0 : 8 }}
				/>
			))}
		</>
	);
}
