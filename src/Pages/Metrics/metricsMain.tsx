function balanceChart(
	chain: Types.GraphPoint[],
	chans: Types.GraphPoint[],
	chart: ReturnType<typeof chartColors>,
) {
	const aligned = alignBalanceSeries(asBalancePts(chain), asBalancePts(chans))
	const chainPts = fillBlockGaps(aligned.chain)
	const chansPts = fillBlockGaps(aligned.chans)
	const yRanges = pairAxisRanges(chainPts, chansPts)
	const xs = [...chainPts, ...chansPts].map((p) => p.x)
	const xMin = xs.length ? Math.min(...xs) : 0
	const xMax = xs.length ? Math.max(...xs) : 1
	return {
		data: {
			datasets: [
				lineSeries("Chain", chainPts, chart.chain, "y"),
				lineSeries("Channels", chansPts, chart.chans, "y1"),
			],
		},
		options: {
			animation: false as const,
			interaction: { mode: "nearest" as const, axis: "x" as const, intersect: false },
			layout: { padding: 0 },
			responsive: true,
			maintainAspectRatio: false,
			elements: {
				line: { borderWidth: 2, tension: 0 },
				point: { radius: 0, hitRadius: 8 },
			},
			plugins: {
				legend: {
					display: true,
					position: "chartArea" as const,
					align: "start" as const,
					labels: {
						boxWidth: 8,
						boxHeight: 8,
						color: chart.text,
						font: { family: "DM Mono", size: 10 },
						usePointStyle: true,
						generateLabels: legendWithLatest,
					},
				},
				tooltip: {
					usePointStyle: true,
					callbacks: {
						title: (items: TooltipItem<"line">[]) => {
							const x = items[0]?.parsed.x
							return x == null ? "" : `Block ${Math.round(x)}`
						},
						label: (ctx: TooltipItem<"line">) => {
							const y = ctx.parsed.y
							return `${ctx.dataset.label}: ${formatFr(y ?? 0)}`
						},
						labelColor: (ctx: { dataset: { borderColor?: unknown } }) => {
							const color = String(ctx.dataset.borderColor || "#888")
							return { borderColor: color, backgroundColor: color, borderWidth: 2 }
						},
					},
				},
			},
			scales: {
				x: {
					type: "linear" as const,
					bounds: "data" as const,
					min: xMin,
					max: xMax === xMin ? xMax + 1 : xMax,
					grid: { color: chart.grid },
					ticks: {
						color: chart.text,
						maxTicksLimit: 6,
						callback: (value: string | number) => String(Math.round(Number(value))),
					},
					border: { color: chart.grid },
				},
				y: {
					...yRanges.chain,
					position: "left" as const,
					grid: { color: chart.grid },
					ticks: { display: false },
					border: { color: chart.grid },
				},
				y1: {
					...yRanges.chans,
					position: "right" as const,
					grid: { drawOnChartArea: false },
					ticks: { display: false },
					border: { display: false },
				},
			},
		},
	}
}

function asBalancePts(pts: Types.GraphPoint[]) {
	return pts.map((p) => ({ x: Number(p.x), y: Number(p.y) }))
}

function latestBlock(series: Types.GraphPoint[][]) {
	const xs = series.flat().map((p) => Number(p.x)).filter(Number.isFinite)
	return xs.length ? Math.max(...xs) : 0
}

function extendGraphToBlock(pts: Types.GraphPoint[], maxBlock: number) {
	if (pts.length === 0 || Number(pts[pts.length - 1].x) === maxBlock) return
	pts.push({ x: maxBlock, y: pts[pts.length - 1].y })
}

function lineSeries(label: string, data: { x: number; y: number }[], color: string, yAxisID: "y" | "y1") {
	return {
		label,
		data,
		borderColor: color,
		backgroundColor: color,
		pointBackgroundColor: color,
		pointBorderColor: color,
		pointRadius: data.length === 1 ? 2 : 0,
		fill: false,
		stepped: "after" as const,
		yAxisID,
	}
}

function legendWithLatest(chart: ChartJS) {
	return ChartJS.defaults.plugins.legend.labels.generateLabels(chart).map((item) => {
		const ds = chart.data.datasets[item.datasetIndex ?? 0]
		const pts = ds?.data as { y: number }[] | undefined
		const y = pts?.[pts.length - 1]?.y
		if (y == null) return item
		return { ...item, text: `${ds.label} ${formatFr(y)}` }
	})
}

function formatFr(n: number): string {
	return new Intl.NumberFormat("fr-FR").format(n);
}

function chartColors(theme: "dark" | "light") {
	if (theme === "light") {
		return {
			grid: "#d0d0cc",
			text: "#555555",
			chain: "#d75ad7",
			chainBorder: "rgba(215, 90, 215, 0.55)",
			chans: "#ff9900",
			chansBorder: "rgba(255, 153, 0, 0.55)",
		};
	}
	return {
		grid: "rgba(255, 255, 255, 0.06)",
		text: "#8a8a8a",
		chain: "#f040f5",
		chainBorder: "rgba(240, 64, 245, 0.55)",
		chans: "#ff8a00",
		chansBorder: "rgba(255, 138, 0, 0.55)",
	};
}

