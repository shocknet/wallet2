type ChannelsInfo = {
	offlineChannels: number
	onlineChannels: number
	pendingChannels: number
	closingChannels: number
	bestLocalChan: string
	bestRemoteChan: string
	forwardedEvents: number
	forwardedFees: number
}

const EVENT_PREVIEW = 2
const EVENT_PAGE = 20

function queryFailed(q: { data?: unknown; error?: unknown; isFetching: boolean }) {
	return !q.data && !!q.error && !q.isFetching;
}

const Dashboard = () => {
	const [period, setPeriod] = useState<Period>(Period.WEEK);
	const [offset, setOffset] = useState(0);
	const adminSource = useDashboardSource();
	const sourceId = adminSource.sourceId;
	useGetPubDashboardCapabilityQuery({ sourceId }); // start query so pages that need it later hit cache
	const lndInfo = useGetLndInfoQuery({ sourceId });
	const apps = useGetAppsMetricsQuery({ sourceId, period, offset });
	const lnd = useGetLndMetricsQuery({ sourceId, period, offset });
	const allFailed = queryFailed(lndInfo) && queryFailed(apps) && queryFailed(lnd);

	const nextOffset = () => {
		if (period === Period.ALL_TIME || offset >= 0) {
			return
		}
		setOffset(offset + 1)
	}

	const prevOffset = () => {
		if (period === Period.ALL_TIME) {
			return
		}
		setOffset(offset - 1)
	}

	const connectedLabel = nip19.nprofileEncode({
		pubkey: adminSource.lpk,
		relays: adminSource.relays,
	});

	return (
		<DashBoardPageChrome title="Overview">
			{allFailed ? (
				<DashErrorBanner
					message="Couldn't load overview"
					onRetry={() => {
						void lndInfo.refetch();
						void apps.refetch();
						void lnd.refetch();
					}}
				/>
			) : (
				<>
					<div className="dash-toolbar">
						<OverviewStatusPills sourceId={sourceId} />
						<PeriodSelector
							period={period}
							offset={offset}
							setPeriod={setPeriod}
							resetOffset={() => setOffset(0)}
							prevOffset={prevOffset}
							nextOffset={nextOffset}
							disabled={apps.isFetching || lnd.isFetching}
						/>
					</div>
					<OverviewLndChart
						sourceId={sourceId}
						period={period}
						offset={offset}
					/>
					<span className="dash-section-tag">Highlights</span>
					<div className="dash-kpi-grid">
						<OverviewEarned
							sourceId={sourceId}
							period={period}
							offset={offset}
						/>
						<OverviewLndKpis
							sourceId={sourceId}
							period={period}
							offset={offset}
						/>
						<OverviewAppCards
							sourceId={sourceId}
							period={period}
							offset={offset}
						/>
					</div>
					<OverviewLndEvents
						sourceId={sourceId}
						period={period}
						offset={offset}
					/>
				</>
			)}
			<div className="dash-footer" title={connectedLabel}>{connectedLabel}</div>
		</DashBoardPageChrome>
	);
}

function deriveLndOverview(data: Types.LndMetrics, period: Period, offset: number) {
	const nodeStats = data.nodes[0]
	if (!nodeStats) return null
	const chain = nodeStats.chain_balance.map((p) => ({ ...p }))
	const channels = nodeStats.channel_balance.map((p) => ({ ...p }))
	const external = nodeStats.external_balance.map((p) => ({ ...p }))
	const maxBlock = latestBlock([chain, channels, external])
	extendGraphToBlock(chain, maxBlock)
	extendGraphToBlock(channels, maxBlock)
	extendGraphToBlock(external, maxBlock)
	const openChannels = nodeStats.open_channels
	const bestLocal = { n: "", v: 0 }
	const bestRemote = { n: "", v: 0 }
	for (const c of openChannels) {
		if (c.remote_balance > bestRemote.v) {
			bestRemote.v = c.remote_balance
			bestRemote.n = displayPeerName(c.label, c.channel_id)
		}
		if (c.local_balance > bestLocal.v) {
			bestLocal.v = c.local_balance
			bestLocal.n = displayPeerName(c.label, c.channel_id)
		}
	}
	return {
		chain,
		channels,
		channelsInfo: {
			closingChannels: nodeStats.closing_channels,
			offlineChannels: nodeStats.offline_channels,
			onlineChannels: nodeStats.online_channels,
			pendingChannels: nodeStats.pending_channels,
			bestLocalChan: bestLocal.n,
			bestRemoteChan: bestRemote.n,
			forwardedEvents: nodeStats.forwarding_events,
			forwardedFees: nodeStats.forwarding_fees,
		} satisfies ChannelsInfo,
		events: buildOverviewEvents(
			{ ...nodeStats, open_channels: openChannels },
			getUnixTimeRange(period, offset),
		),
	}
}

function useOverviewLnd(sourceId: string, period: Period, offset: number) {
	const { data, error, isFetching, refetch } = useGetLndMetricsQuery({
		sourceId,
		period,
		offset,
	});
	const view = useMemo(
		() => (data ? deriveLndOverview(data, period, offset) : undefined),
		[data, period, offset],
	);
	return {
		view,
		error,
		refetch,
		loading: !data && (isFetching || !error),
	};
}

const OverviewLndChart = memo(function OverviewLndChart({
	sourceId,
	period,
	offset,
}: {
	sourceId: string;
	period: Period;
	offset: number;
}) {
	const theme = useEffectiveTheme();
	const { view, error, loading, refetch } = useOverviewLnd(sourceId, period, offset);
	const chartProps = useMemo(
		() => (view ? balanceChart(view.chain, view.channels, chartColors(theme)) : null),
		[view, theme],
	);

	if (loading) {
		return (
			<div className="dash-card dash-chart">
				<IonSkeletonText animated style={{ width: "100%", height: "100%", margin: 0, borderRadius: 8 }} />
			</div>
		);
	}

	if (!view || !chartProps) {
		return (
			<DashErrorBanner
				message={(error as AppApiError | undefined)?.message || "Lnd metrics failed"}
				onRetry={() => void refetch()}
			/>
		);
	}

	return (
		<div className="dash-card dash-chart">
			{view.chain.length === 0 && view.channels.length === 0 ? (
				<div className="dash-chart-empty">No balance history yet</div>
			) : (
				<div className="dash-chart-frame">
					<Line {...chartProps} />
				</div>
			)}
		</div>
	);
});

