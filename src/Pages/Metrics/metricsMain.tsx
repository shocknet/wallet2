import { useCallback, useState, useEffect, useRef } from 'react';
import {
	useIonRouter
} from "@ionic/react";
import { Chart as ChartJS, registerables, Legend, TooltipItem } from 'chart.js';
import { Line } from 'react-chartjs-2'
ChartJS.register(...registerables, Legend);
import { getNostrClient } from '../../Api/nostr';
import * as Types from '../../Api/pub/autogenerated/ts/types';
import moment from 'moment';
import { Period } from '../../Components/Dropdowns/LVDropdown';
import { toast } from "react-toastify";
import Toast from "../../Components/Toast";
import { Client } from '../../Api/nostr';
import { getUnixTimeRange } from './earnings';
import PeriodSelector from '@/Components/Dropdowns/PeriodDropdown/PeriodSelector';
import { nip19 } from 'nostr-tools';
import { DashboardShell } from '@/Layout2/Metrics/DashboardShell';
import { useAppDispatch, useAppSelector } from "@/State/store/hooks";
import { selectSelectedAdminRpcSource } from "@/State/scoped/backups/sources/selectors";
import { runtimeActions, selectSelectedMetricsAdminSourceId } from "@/State/runtime/slice";
import { PubUpgradeNotice } from "./PubUpgradeNotice";
import { MetricsProbeSkeleton } from "./MetricsProbeSkeleton";
import { usePubDashboardCapability } from "./usePubDashboardCapability";
import { DashErrorBanner } from "./DashErrorBanner";
import { useEffectiveTheme } from "@/Hooks/useEffectiveTheme";
import { buildOverviewEvents, displayPeerName, OverviewEvent } from "./overviewEvents";
import { OverviewEventDialog } from "./OverviewEventDialog";
import { alignBalanceSeries, axisRange, xBounds } from "./balanceSeries";

type ChannelsInfo = {
	offlineChannels: number
	onlineChannels: number
	pendingChannels: number
	closingChannels: number
	bestLocalChan: string
	bestRemoteChan: string
	forwardedEvents: number
	forwardedFees: number
}
type AppsInfo = {
	earnedInPeriod: number
	appsUsers: { appName: string, users: number, invoices: number }[]
}

const EVENT_PREVIEW = 2
const EVENT_PAGE = 20

const Dashboard = () => {
	const router = useIonRouter();

	const [chainGraphData, setChainGraphData] = useState<Types.GraphPoint[]>([])
	const [chansGraphData, setChansGraphData] = useState<Types.GraphPoint[]>([])
	const [extGraphData, setExtGraphData] = useState<Types.GraphPoint[]>([])
	const [channelsInfo, setChannelsInfo] = useState<ChannelsInfo>()
	const [appsInfo, setAppsInfo] = useState<AppsInfo>()
	const [period, setPeriod] = useState<Period>(Period.WEEK);
	const [error, setError] = useState<string | null>(null)
	const [lndStatus, setLndStatus] = useState("Loading...")
	const [dogStatus, setDogStatus] = useState("Loading...")
	const [rootOps, setRootOps] = useState<OverviewEvent[]>([])
	const [selectedEvent, setSelectedEvent] = useState<OverviewEvent | null>(null)
	const [eventsLimit, setEventsLimit] = useState(EVENT_PREVIEW)
	const [offset, setOffset] = useState(0);
	const isFetchingRef = useRef(false);
	const fetchMetricsRef = useRef<(() => Promise<void>) | null>(null);

	const dispatch = useAppDispatch();
	const selectedId = useAppSelector(selectSelectedMetricsAdminSourceId);
	const mempoolUrl = useAppSelector((s) => s.prefs.mempoolUrl);
	const adminSource = useAppSelector(selectSelectedAdminRpcSource)!;
	const { needsUpgrade, checking: checkingPubCapability, recheck } =
		usePubDashboardCapability(adminSource);

	const fetchInfo = useCallback(async (client: Client) => {
		const info = await client.LndGetInfo({ nodeId: 0 })
		if (info.status !== 'OK') {
			toast.error(<Toast title="Metrics Error" message={`Failed to fetch service status. ${info.reason}`} />)
			return
		}
		setDogStatus(info.watchdog_barking ? "Ops Locked" : "")
		if (!info.synced_to_chain) {
			setLndStatus("Syncing to chain")
			return
		}
		if (!info.synced_to_graph) {
			setLndStatus("Syncing to graph")
			return
		}
		setLndStatus("")
	}, [])

	const fetchMetrics = useCallback(async () => {
		if (isFetchingRef.current) {
			return;
		}
		isFetchingRef.current = true;
		setError(null);

		try {
			const client = await getNostrClient(
				{ pubkey: adminSource.lpk, relays: adminSource.relays },
				adminSource.keys
			);

			const periodRange = getUnixTimeRange(period, offset);


			const apps = await client.GetAppsMetrics({ include_operations: false, ...periodRange })
			const lnd = await client.GetLndMetrics({ ...periodRange })
			await fetchInfo(client)

			if (apps.status !== 'OK') {
				setError(apps.reason || "App metrics failed");
				return;
			}
			if (lnd.status !== 'OK') {
				setError(lnd.reason || "Lnd metrics failed");
				return;
			}
			const nodeStats = lnd.nodes[0]
			if (selectedId) {
				dispatch(runtimeActions.setOpenChannels({
					sourceId: selectedId,
					channels: nodeStats.open_channels,
				}));
			}
			console.log({ lnd: nodeStats, apps: apps.apps })
			const chain = nodeStats.chain_balance
			const channels = nodeStats.channel_balance
			const external = nodeStats.external_balance
			const showExternal = external.length > 1
			const toMin = []
			const toMax = []
			if (chain.length > 0) {
				toMin.push(chain[0].x)
				toMax.push(chain[chain.length - 1].x)
			}
			if (channels.length > 0) {
				toMin.push(channels[0].x)
				toMax.push(channels[channels.length - 1].x)
			}
			if (external.length > 0) {
				toMin.push(external[0].x)
				toMax.push(external[external.length - 1].x)
			}
			const minBlock = Math.min(...toMin) || 0
			const maxBlock = Math.max(...toMax) || 0
			console.log({ minBlock, maxBlock })

			if (chain.length > 0 && chain[chain.length - 1].x !== maxBlock) {
				chain.push({ x: maxBlock, y: chain[chain.length - 1].y })
			}

			if (channels.length > 0 && channels[channels.length - 1].x !== maxBlock) {
				channels.push({ x: maxBlock, y: channels[channels.length - 1].y })
			}

			if (external.length > 0 && external[external.length - 1].x !== maxBlock) {
				external.push({ x: maxBlock, y: external[external.length - 1].y })
			}
			setChansGraphData(channels)
			setChainGraphData(chain)
			if (showExternal) {
				setExtGraphData(external)
			}
			const openChannels = nodeStats.open_channels
			const bestLocal = { n: "", v: 0 }
			const bestRemote = { n: "", v: 0 }
			for (const c of openChannels) {
				if (c.remote_balance > bestRemote.v) {
					bestRemote.v = c.remote_balance
					bestRemote.n = displayPeerName(c.label, c.channel_id)
				}
				if (c.local_balance > bestLocal.v) {
					bestLocal.v = c.local_balance
					bestLocal.n = displayPeerName(c.label, c.channel_id)
				}
			}
			setRootOps(buildOverviewEvents({ ...nodeStats, open_channels: openChannels }, periodRange))
			setEventsLimit(EVENT_PREVIEW)
			setChannelsInfo({
				closingChannels: nodeStats.closing_channels,
				offlineChannels: nodeStats.offline_channels,
				onlineChannels: nodeStats.online_channels,
				pendingChannels: nodeStats.pending_channels,
				bestLocalChan: bestLocal.n,
				bestRemoteChan: bestRemote.n,
				forwardedEvents: nodeStats.forwarding_events,
				forwardedFees: nodeStats.forwarding_fees
			})
			let earnedInPeriod = 0
			for (const app of apps.apps) {
				earnedInPeriod += app.fees
			}
			const appsUsers = apps.apps
				.filter((app) => app.app.id !== "unlinked")
				.map((app) => ({ appName: app.app.name, users: app.users.total, invoices: app.invoices }))
			setAppsInfo({
				earnedInPeriod,
				appsUsers
			})
		} catch (e) {
			console.error(e);
			setError(e instanceof Error ? e.message : "Failed to fetch metrics");
			toast.error(<Toast title="Metrics Error" message={`Failed to fetch metrics. ${e instanceof Error ? e.message : ""}`} />);
		} finally {
			isFetchingRef.current = false;
		}
	}, [period, adminSource.sourceId, adminSource.lpk, adminSource.relays, adminSource.keys, offset, fetchInfo, dispatch, selectedId]);

	useEffect(() => {
		fetchMetricsRef.current = fetchMetrics;
	}, [fetchMetrics]);

	useEffect(() => {
		if (checkingPubCapability || needsUpgrade) return;
		void fetchMetricsRef.current?.();
	}, [checkingPubCapability, needsUpgrade, selectedId, period, offset]);

	const nextOffset = () => {
		if (period === Period.ALL_TIME || offset >= 0) {
			return
		}
		setOffset(offset + 1)
	}

	const prevOffset = () => {
		if (period === Period.ALL_TIME) {
			return
		}
		setOffset(offset - 1)
	}

	const gotoChannels = () => {
		router.push("/metrics/channels", "forward");
	}

	const onEventClick = (event: OverviewEvent) => {
		setSelectedEvent(event)
	}

	const theme = useEffectiveTheme();
	const chart = chartColors(theme);
	const visibleEvents = rootOps.slice(0, eventsLimit)
	const hasMoreEvents = eventsLimit < rootOps.length
	const showingMoreEvents = eventsLimit > EVENT_PREVIEW
	const connectedLabel = adminSource
		? nip19.nprofileEncode({ pubkey: adminSource.lpk, relays: adminSource.relays })
		: "(no source)";

	return (
		<DashboardShell title="Overview">
			{needsUpgrade && (
				<PubUpgradeNotice
					onRecheck={recheck}
					checking={checkingPubCapability}
				/>
			)}

			{!needsUpgrade && !error && !appsInfo && (
				<MetricsProbeSkeleton variant="page" />
			)}

			{error && (
				<DashErrorBanner
					message={error}
					onRetry={() => void fetchMetrics()}
					onChangeSource={() => router.push("/metrics/select", "back")}
				/>
			)}

			{appsInfo && channelsInfo && !error && (
				<>
					<div className="dash-toolbar">
						<div className="dash-pills">
							<span className={lndStatus ? "dash-pill is-warn" : "dash-pill is-ok"}>
								Lightning · {lndStatus || "Synced"}
							</span>
							<span className={dogStatus ? "dash-pill is-bad" : "dash-pill is-ok"}>
								Watchdog · {dogStatus || "Quiet"}
							</span>
						</div>
						<PeriodSelector
							period={period}
							offset={offset}
							setPeriod={setPeriod}
							resetOffset={() => setOffset(0)}
							prevOffset={prevOffset}
							nextOffset={nextOffset}
						/>
					</div>

					<div className="dash-card dash-chart">
						<Line {...balanceChart(chainGraphData, chansGraphData, chart)} />
					</div>

					<span className="dash-section-tag">Highlights</span>
					<div className="dash-kpi-grid">
						<button
							type="button"
							className="dash-card is-clickable"
							onClick={() => router.push("/metrics/earnings?period=" + period + "&offset=" + offset, "forward")}
						>
							<p className="dash-kpi-label">Earned</p>
							<p className="dash-kpi-value">{formatFr(appsInfo.earnedInPeriod)} sats</p>
							<div className="dash-kpi-sub">this period</div>
						</button>

						<button type="button" className="dash-card is-clickable" onClick={gotoChannels}>
							<p className="dash-kpi-label">Channels</p>
							<p className="dash-kpi-value">
								{channelsInfo.onlineChannels + channelsInfo.pendingChannels + channelsInfo.offlineChannels + channelsInfo.closingChannels}
							</p>
							<div className="dash-dot-row">
								<span><i className="dash-dot ok" />{channelsInfo.onlineChannels} online</span>
								<span><i className="dash-dot pending" />{channelsInfo.pendingChannels} pending</span>
								<span><i className="dash-dot warn" />{channelsInfo.offlineChannels} offline</span>
								<span><i className="dash-dot bad" />{channelsInfo.closingChannels} closing</span>
							</div>
						</button>

						<div className="dash-card">
							<p className="dash-kpi-label">Top channels</p>
							<div className="dash-kpi-meta">
								<span className="dash-kpi-pair-k">In</span>
								<span className="dash-kpi-pair-v" title={channelsInfo.bestLocalChan}>
									{channelsInfo.bestLocalChan || "—"}
								</span>
								<span className="dash-kpi-pair-k">Out</span>
								<span className="dash-kpi-pair-v" title={channelsInfo.bestRemoteChan}>
									{channelsInfo.bestRemoteChan || "—"}
								</span>
							</div>
						</div>

						<button
							type="button"
							className="dash-card is-clickable"
							onClick={() => router.push("/metrics/routing?period=" + period + "&offset=" + offset)}
						>
							<p className="dash-kpi-label">Routing</p>
							<p className="dash-kpi-value">{formatFr(channelsInfo.forwardedFees)} sats</p>
							<div className="dash-kpi-sub">{channelsInfo.forwardedEvents} forwards</div>
						</button>

						{appsInfo.appsUsers.map((app) => (
							<div key={app.appName} className="dash-card">
								<p className="dash-kpi-label">{app.appName}</p>
								<p className="dash-kpi-value">{formatFr(app.users)} users</p>
								<div className="dash-kpi-sub">{formatFr(app.invoices)} invoices</div>
							</div>
						))}
					</div>

					<div className="dash-section">
						<div className="dash-section-head">
							<h2>Events</h2>
							<div className="dash-event-actions">
								{hasMoreEvents && (
									<button
										type="button"
										className="dash-text-btn"
										onClick={() => setEventsLimit((n) => n === EVENT_PREVIEW ? EVENT_PAGE : n + EVENT_PAGE)}
									>
										Show more
									</button>
								)}
								{showingMoreEvents && (
									<button
										type="button"
										className="dash-text-btn"
										onClick={() => setEventsLimit(EVENT_PREVIEW)}
									>
										Show less
									</button>
								)}
							</div>
						</div>
						<div className="dash-events">
							{visibleEvents.length === 0 && (
								<div className="dash-event"><span>No events in this period</span></div>
							)}
							{visibleEvents.map((e, i) => (
								<button
									type="button"
									key={`${e.unix}-${e.message}-${i}`}
									className="dash-event is-clickable"
									onClick={() => onEventClick(e)}
								>
									<span>{e.message}</span>
									{e.unix > 0 && <time>{moment(e.unix * 1000).fromNow()}</time>}
								</button>
							))}
						</div>
					</div>

					{selectedEvent && (
						<OverviewEventDialog
							event={selectedEvent}
							mempoolUrl={mempoolUrl}
							onClose={() => setSelectedEvent(null)}
						/>
					)}

					<div className="dash-footer" title={connectedLabel}>{connectedLabel}</div>
				</>
			)}
		</DashboardShell>
	);
}

function balanceChart(
	chain: Types.GraphPoint[],
	chans: Types.GraphPoint[],
	chart: ReturnType<typeof chartColors>,
) {
	const aligned = alignBalanceSeries(chain, chans)
	const xRange = xBounds(aligned.chain, aligned.chans)
	return {
		data: {
			datasets: [
				lineSeries("Chain", aligned.chain, chart.chain, "y"),
				lineSeries("Channels", aligned.chans, chart.chans, "y1"),
			],
		},
		options: {
			interaction: { mode: "nearest" as const, axis: "x" as const, intersect: false },
			layout: { padding: 0 },
			responsive: true,
			maintainAspectRatio: false,
			elements: {
				line: { borderWidth: 2, tension: 0 },
				point: { radius: 0, hitRadius: 8 },
			},
			plugins: {
				legend: {
					display: true,
					position: "chartArea" as const,
					align: "start" as const,
					labels: {
						boxWidth: 8,
						boxHeight: 8,
						color: chart.text,
						font: { family: "DM Mono", size: 10 },
						usePointStyle: true,
						generateLabels: legendWithLatest,
					},
				},
				tooltip: {
					usePointStyle: true,
					callbacks: {
						title: (items: TooltipItem<"line">[]) => {
							const x = items[0]?.parsed.x
							return x == null ? "" : `Block ${Math.round(x)}`
						},
						label: (ctx: TooltipItem<"line">) => {
							const y = ctx.parsed.y
							return `${ctx.dataset.label}: ${formatFr(y ?? 0)}`
						},
						labelColor: (ctx: { dataset: { borderColor?: unknown } }) => {
							const color = String(ctx.dataset.borderColor || "#888")
							return { borderColor: color, backgroundColor: color, borderWidth: 2 }
						},
					},
				},
			},
			scales: {
				x: {
					type: "linear" as const,
					bounds: "data" as const,
					min: xRange.min,
					max: xRange.max,
					grid: { color: chart.grid },
					ticks: {
						color: chart.text,
						maxTicksLimit: 6,
						callback: (value: string | number) => String(Math.round(Number(value))),
					},
					border: { color: chart.grid },
				},
				y: {
					...axisRange(aligned.chain),
					position: "left" as const,
					grid: { color: chart.grid },
					ticks: { display: false },
					border: { color: chart.grid },
				},
				y1: {
					...axisRange(aligned.chans),
					position: "right" as const,
					grid: { drawOnChartArea: false },
					ticks: { display: false },
					border: { display: false },
				},
			},
		},
	}
}

function lineSeries(label: string, data: Types.GraphPoint[], color: string, yAxisID: "y" | "y1") {
	return {
		label,
		data,
		borderColor: color,
		backgroundColor: color,
		pointBackgroundColor: color,
		pointBorderColor: color,
		fill: false,
		stepped: "after" as const,
		yAxisID,
	}
}

function legendWithLatest(chart: ChartJS) {
	return ChartJS.defaults.plugins.legend.labels.generateLabels(chart).map((item) => {
		const ds = chart.data.datasets[item.datasetIndex ?? 0]
		const pts = ds?.data as { y: number }[] | undefined
		const y = pts?.[pts.length - 1]?.y
		if (y == null) return item
		return { ...item, text: `${ds.label} ${formatFr(y)}` }
	})
}

function formatFr(n: number): string {
	return new Intl.NumberFormat("fr-FR").format(n);
}

function chartColors(theme: "dark" | "light") {
	if (theme === "light") {
		return {
			grid: "#d0d0cc",
			text: "#555555",
			chain: "#d75ad7",
			chainBorder: "rgba(215, 90, 215, 0.55)",
			chans: "#ff9900",
			chansBorder: "rgba(255, 153, 0, 0.55)",
		};
	}
	return {
		grid: "rgba(255, 255, 255, 0.06)",
		text: "#8a8a8a",
		chain: "#f040f5",
		chainBorder: "rgba(240, 64, 245, 0.55)",
		chans: "#ff8a00",
		chansBorder: "rgba(255, 138, 0, 0.55)",
	};
}

export default Dashboard;
