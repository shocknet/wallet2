export const AssetsAndLiab = () => {
	const { sourceId } = useDashboardSource();
	const dispatch = useAppDispatch();
	const cap = useGetPubDashboardCapabilityQuery({ sourceId });
	const needsUpgrade = cap.data === "needs_upgrade";
	const capPending = !cap.data && (cap.isFetching || !cap.error);
	const { data, error, isFetching, refetch } = useGetAssetsAndLiabilitiesQuery(
		{ sourceId },
		{ skip: needsUpgrade || capPending },
	);
	const [fetchAssets, fetchMore] = useFetchAssetsAndLiabilitiesMutation();
	const loading = !data && (isFetching || !error);
	const errMsg = (error as AppApiError | undefined)?.message || "Failed to fetch assets";
	const loadingMorePubkey = fetchMore.isLoading
		? fetchMore.originalArgs?.lnd_providers[0]?.pubkey
			?? fetchMore.originalArgs?.liquidity_providers[0]?.pubkey
			?? null
		: null;
	const busy = isFetching || fetchMore.isLoading;

	const totalAssets = useMemo(() => {
		if (!data) return 0;
		let sum = 0;
		for (const lnd of data.lnds) {
			if (lnd.tracked) {
				sum +=
					lnd.tracked.confirmed_balance +
					lnd.tracked.unconfirmed_balance +
					lnd.tracked.channels_balance;
			}
		}
		for (const lp of data.liquidity_providers) {
			if (lp.tracked) sum += lp.tracked.balance;
		}
		return sum;
	}, [data]);

	const allOperations = useMemo(
		() => (data ? collectAllOperations(data) : []),
		[data],
	);

	const onLoadMoreLnd = (pubkey: string) => {
		const tracked = data?.lnds.find((lnd) => lnd.pubkey === pubkey)?.tracked;
		if (!tracked) return;
		fetchAssets({
			sourceId,
			lnd_providers: [lndLoadMoreFilter(tracked, pubkey)],
			liquidity_providers: [],
		}).unwrap().then((incoming) => {
			dispatch(pubDashApi.util.updateQueryData("getAssetsAndLiabilities", { sourceId }, (draft) => {
				mergeAssetsPage(draft, incoming, pubkey, "lnd");
			}));
		}).catch((e) => {
			toast.error((e as AppApiError).message || "Failed to load more operations");
		});
	};

	const onLoadMoreLp = (pubkey: string) => {
		const tracked = data?.liquidity_providers.find((lp) => lp.pubkey === pubkey)?.tracked;
		if (!tracked) return;
		fetchAssets({
			sourceId,
			lnd_providers: [],
			liquidity_providers: [lpLoadMoreFilter(tracked, pubkey)],
		}).unwrap().then((incoming) => {
			dispatch(pubDashApi.util.updateQueryData("getAssetsAndLiabilities", { sourceId }, (draft) => {
				mergeAssetsPage(draft, incoming, pubkey, "lp");
			}));
		}).catch((e) => {
			toast.error((e as AppApiError).message || "Failed to load more operations");
		});
	};

	return (
		<DashBoardPageChrome title="Assets">
			{needsUpgrade ? (
				<PubUpgradeNotice
					featureLabel="Assets & Liabilities"
					onRecheck={cap.refetch}
					checking={cap.isFetching}
				/>
			) : capPending || loading ? (
				<AssetsSkeleton />
			) : !data ? (
				<DashErrorBanner
					message={errMsg}
					onRetry={() => refetch()}
				/>
			) : (
				<>
					<IonCard>
						<IonCardHeader>
							<div style={{ display: "flex", justifyContent: "space-between", alignItems: "center" }}>
								<IonCardTitle>Summary</IonCardTitle>
								<IonButton
									size="small"
									fill="outline"
									disabled={busy}
									onClick={() => refetch()}
								>
									{isFetching ? "Loading…" : "Refresh"}
								</IonButton>
							</div>
						</IonCardHeader>
						<IonCardContent>
							<div
								style={{
									display: "flex",
									flexDirection: "column",
									gap: "12px",
									padding: "12px",
									background: "var(--dash-surface-3)",
									borderRadius: "8px",
									color: "var(--dash-text)",
								}}
							>
								{(() => {
									const liabilities = data.users_balance;
									const assets = totalAssets;
									const total = liabilities + assets;
									const liabilityPct = total > 0 ? (liabilities / total) * 100 : 50;
									const assetPct = total > 0 ? (assets / total) * 100 : 50;
									const diff = Math.abs(assets - liabilities);
									return (
										<>
											<div
												style={{
													display: "flex",
													alignItems: "stretch",
													height: "28px",
													borderRadius: "8px",
													overflow: "hidden",
													boxShadow: "inset 0 1px 2px rgba(0,0,0,0.1)",
												}}
											>
												<div
													style={{
														width: `${liabilityPct}%`,
														minWidth: total === 0 ? "50%" : liabilityPct < 2 ? "0" : undefined,
														background: "var(--ion-color-danger)",
													}}
													title={formatSats(liabilities)}
												/>
												<div
													style={{
														width: "3px",
														flexShrink: 0,
														background: "var(--ion-color-dark)",
														opacity: 0.8,
													}}
												/>
												<div
													style={{
														width: `${assetPct}%`,
														minWidth: total === 0 ? "50%" : assetPct < 2 ? "0" : undefined,
														background: "var(--ion-color-success)",
													}}
													title={formatSats(assets)}
												/>
											</div>
											<div style={{ display: "flex", justifyContent: "space-between", fontSize: "0.9rem" }}>
												<IonText color="danger">
													<IonIcon icon={peopleOutline} style={{ marginRight: "4px", verticalAlign: "middle" }} />
													<strong>{formatSats(liabilities)}</strong> liability
												</IonText>
												<IonText color="success">
													<strong>{formatSats(assets)}</strong> assets
													<IonIcon icon={walletOutline} style={{ marginLeft: "4px", verticalAlign: "middle" }} />
												</IonText>
											</div>
											<div style={{ textAlign: "center", fontSize: "0.85rem" }}>
												{total === 0 ? (
													<IonText color="medium">No data</IonText>
												) : assets > liabilities ? (
													<IonText color="success">
														Assets exceed liabilities by <strong>{formatSats(diff)}</strong>
													</IonText>
												) : liabilities > assets ? (
													<IonText color="danger">
														Liabilities exceed assets by <strong>{formatSats(diff)}</strong>
													</IonText>
												) : (
													<IonText color="medium">Assets and liabilities are equal</IonText>
												)}
											</div>
										</>
									);
								})()}
							</div>
						</IonCardContent>
					</IonCard>

					<UtxoList />

					<IonText className="ion-margin-top" style={{ fontSize: "1.2rem", fontWeight: "bold", display: "block", marginBottom: "8px" }}>
						<IonIcon icon={walletOutline} style={{ marginRight: "8px" }} />
						Provider balances
					</IonText>
					{data.lnds.length === 0 && data.liquidity_providers.length === 0 && (
						<IonCard>
							<IonCardContent style={{ textAlign: "center", padding: "24px" }}>
								<IonIcon icon={walletOutline} style={{ fontSize: "48px", color: "var(--ion-color-medium)", marginBottom: "8px" }} />
								<IonText color="medium">No providers</IonText>
							</IonCardContent>
						</IonCard>
					)}
					{data.lnds.map((lnd, i) => (
						<LndAssetCard
							key={lnd.pubkey + i}
							provider={lnd}
							operationCount={lnd.tracked ? countProviderOperations(lnd.tracked) : 0}
							hasMore={lnd.tracked ? lndProviderHasMore(lnd.tracked) : false}
							loadingMore={loadingMorePubkey === lnd.pubkey}
							onLoadMore={() => onLoadMoreLnd(lnd.pubkey)}
						/>
					))}
					{data.liquidity_providers.map((lp, i) => (
						<LiquidityAssetCard
							key={lp.pubkey + i}
							provider={lp}
							operationCount={lp.tracked ? countProviderOperations(lp.tracked) : 0}
							hasMore={lp.tracked ? lpProviderHasMore(lp.tracked) : false}
							loadingMore={loadingMorePubkey === lp.pubkey}
							onLoadMore={() => onLoadMoreLp(lp.pubkey)}
						/>
					))}

					<IonCard className="ion-margin-top">
						<IonCardHeader>
							<IonCardTitle>
								Operations
								{allOperations.length > 0 && (
									<IonText color="medium" style={{ fontSize: "0.85rem", fontWeight: 400, marginLeft: "8px" }}>
										({allOperations.length})
									</IonText>
								)}
							</IonCardTitle>
						</IonCardHeader>
						<IonCardContent>
							<AssetOperationsTable operations={allOperations} />
						</IonCardContent>
					</IonCard>
				</>
			)}
		</DashBoardPageChrome>
	);
};

