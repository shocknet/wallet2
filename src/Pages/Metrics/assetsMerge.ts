import type {
	AssetOperation,
	AssetsAndLiabilitiesV2,
	LiquidityAssetOperationsPage,
	LiquidityProviderFilter,
	LndAssetOperationsPage,
	LndProviderFilter,
	TrackedLiquidityProviderV2,
	TrackedLndProviderV2,
} from "@/Api/pub/autogenerated/ts/types";

const ASSETS_OPS_PAGE_SIZE = 25;

function assetOperationKey(op: AssetOperation): string {
	const tracked = op.tracked;
	return `${op.ts}:${op.amount}:${tracked?.type ?? ""}:${tracked?.user_id ?? ""}`;
}

function mergeAssetOperations(existing: AssetOperation[], incoming: AssetOperation[]): AssetOperation[] {
	if (incoming.length === 0) return existing;
	const seen = new Set(existing.map(assetOperationKey));
	const merged = [...existing];
	for (const op of incoming) {
		const key = assetOperationKey(op);
		if (seen.has(key)) continue;
		seen.add(key);
		merged.push(op);
	}
	return merged.sort((a, b) => b.ts - a.ts);
}

function mergeLndOpsPage(existing: LndAssetOperationsPage, incoming: LndAssetOperationsPage): LndAssetOperationsPage {
	return {
		has_more: incoming.has_more,
		next_index_offset: incoming.next_index_offset,
		start_height: incoming.start_height ?? existing.start_height,
		operations: mergeAssetOperations(existing.operations, incoming.operations),
	};
}

function mergeLpOpsPage(existing: LiquidityAssetOperationsPage, incoming: LiquidityAssetOperationsPage): LiquidityAssetOperationsPage {
	return {
		has_more: incoming.has_more,
		next_cursor: incoming.next_cursor,
		timeout: incoming.timeout,
		operations: mergeAssetOperations(existing.operations, incoming.operations),
	};
}

export function lndLoadMoreFilter(tracked: TrackedLndProviderV2, pubkey: string): LndProviderFilter {
	const txHasMore = tracked.incoming_tx.has_more || tracked.outgoing_tx.has_more;
	const txIndexOffset = tracked.incoming_tx.next_index_offset ?? tracked.outgoing_tx.next_index_offset;
	const txStartHeight = tracked.incoming_tx.start_height ?? tracked.outgoing_tx.start_height;
	return {
		pubkey,
		limit_invoices: ASSETS_OPS_PAGE_SIZE,
		limit_payments: ASSETS_OPS_PAGE_SIZE,
		limit_transactions: ASSETS_OPS_PAGE_SIZE,
		...(tracked.invoices.has_more && tracked.invoices.next_index_offset != null
			? { invoice_index_offset: tracked.invoices.next_index_offset }
			: {}),
		...(tracked.payments.has_more && tracked.payments.next_index_offset != null
			? { payment_index_offset: tracked.payments.next_index_offset }
			: {}),
		...(txHasMore && txIndexOffset != null ? { tx_index_offset: txIndexOffset } : {}),
		...(txHasMore && txStartHeight != null ? { tx_start_height: txStartHeight } : {}),
	};
}

export function lpLoadMoreFilter(tracked: TrackedLiquidityProviderV2, pubkey: string): LiquidityProviderFilter {
	return {
		pubkey,
		limit: ASSETS_OPS_PAGE_SIZE,
		...(tracked.invoices.has_more && tracked.invoices.next_cursor
			? { latestIncomingInvoice: tracked.invoices.next_cursor }
			: {}),
		...(tracked.payments.has_more && tracked.payments.next_cursor
			? { latestOutgoingInvoice: tracked.payments.next_cursor }
			: {}),
	};
}

function mergeLndIntoSnapshot(
	draft: AssetsAndLiabilitiesV2,
	incoming: AssetsAndLiabilitiesV2,
	pubkey: string,
) {
	const existing = draft.lnds.find((lnd) => lnd.pubkey === pubkey);
	if (!existing?.tracked) return;
	const page = incoming.lnds.find((lnd) => lnd.pubkey === pubkey);
	if (!page?.tracked) {
		existing.tracked.invoices.has_more = false;
		existing.tracked.payments.has_more = false;
		existing.tracked.incoming_tx.has_more = false;
		existing.tracked.outgoing_tx.has_more = false;
		return;
	}
	existing.tracked = {
		confirmed_balance: page.tracked.confirmed_balance,
		unconfirmed_balance: page.tracked.unconfirmed_balance,
		channels_balance: page.tracked.channels_balance,
		invoices: mergeLndOpsPage(existing.tracked.invoices, page.tracked.invoices),
		payments: mergeLndOpsPage(existing.tracked.payments, page.tracked.payments),
		incoming_tx: mergeLndOpsPage(existing.tracked.incoming_tx, page.tracked.incoming_tx),
		outgoing_tx: mergeLndOpsPage(existing.tracked.outgoing_tx, page.tracked.outgoing_tx),
	};
}

function mergeLpIntoSnapshot(
	draft: AssetsAndLiabilitiesV2,
	incoming: AssetsAndLiabilitiesV2,
	pubkey: string,
) {
	const existing = draft.liquidity_providers.find((lp) => lp.pubkey === pubkey);
	if (!existing?.tracked) return;
	const page = incoming.liquidity_providers.find((lp) => lp.pubkey === pubkey);
	if (!page?.tracked) {
		existing.tracked.invoices.has_more = false;
		existing.tracked.payments.has_more = false;
		return;
	}
	existing.tracked = {
		balance: page.tracked.balance,
		invoices: mergeLpOpsPage(existing.tracked.invoices, page.tracked.invoices),
		payments: mergeLpOpsPage(existing.tracked.payments, page.tracked.payments),
	};
}

export function mergeAssetsPage(
	draft: AssetsAndLiabilitiesV2,
	incoming: AssetsAndLiabilitiesV2,
	pubkey: string,
	kind: "lnd" | "lp",
) {
	if (kind === "lnd") mergeLndIntoSnapshot(draft, incoming, pubkey);
	else mergeLpIntoSnapshot(draft, incoming, pubkey);
}
