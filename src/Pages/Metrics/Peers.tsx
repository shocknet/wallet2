import { useEffect, useMemo, useState } from "react";
import { useIonRouter } from "@ionic/react";
import { getNostrClient } from "@/Api/nostr";
import type { LndPeer } from "@/Api/pub/autogenerated/ts/types";
import { DashboardShell } from "@/Layout2/Metrics/DashboardShell";
import { DashDialog } from "@/Layout2/Metrics/DashDialog";
import { useAppSelector } from "@/State/store/hooks";
import { SourceView, selectAdminSourceViews, sourceRpcKey } from "@/State/scoped/backups/sources/selectors";
import { selectSelectedMetricsAdminSourceId } from "@/State/runtime/slice";
import { isMissingDashboardRpcError } from "./pubDashboardCapability";
import { AddPeerForm } from "./AddPeerForm";
import { ChannelOpenForm } from "./ChannelOpenForm";
import { DashErrorBanner } from "./DashErrorBanner";

export default function Peers() {
	const router = useIonRouter();
	const admins = useAppSelector(selectAdminSourceViews);
	const selectedId = useAppSelector(selectSelectedMetricsAdminSourceId);
	const adminSource = useMemo(
		() => admins.find((a) => a.sourceId === selectedId),
		[admins, selectedId]
	)!;
	const [error, setError] = useState<string | null>(null);
	const [needsListPeers, setNeedsListPeers] = useState(false);
	const [peers, setPeers] = useState<LndPeer[]>([]);
	const [loading, setLoading] = useState(true);
	const [selected, setSelected] = useState<LndPeer | null>(null);
	const ordered = useMemo(() => channelPeersFirst(peers), [peers]);
	const rpcKey = sourceRpcKey(adminSource);

	const loadPeers = async () => {
		setError(null);
		setNeedsListPeers(false);
		setLoading(true);
		try {
			const client = await getNostrClient(
				{ pubkey: adminSource.lpk, relays: adminSource.relays },
				adminSource.keys
			);
			const res = await client.ListPeers();
			if (res.status !== "OK") {
				if (isMissingDashboardRpcError(res.reason)) {
					setNeedsListPeers(true);
					setPeers([]);
					return;
				}
				setError(res.reason || "Could not list peers");
				return;
			}
			setPeers(res.peers);
		} catch (e) {
			const msg = e instanceof Error ? e.message : "Could not list peers";
			if (isMissingDashboardRpcError(msg)) {
				setNeedsListPeers(true);
				setPeers([]);
				return;
			}
			setError(msg);
		} finally {
			setLoading(false);
		}
	};

	useEffect(() => {
		void loadPeers();
	}, [rpcKey]);

	return (
		<DashboardShell title="Peers">
			{error && (
				<DashErrorBanner
					message={error}
					onRetry={() => void loadPeers()}
					onChangeSource={() => router.push("/metrics/select", "back")}
				/>
			)}
			<AddPeerForm adminSource={adminSource} onAdded={() => void loadPeers()} />
			{needsListPeers && (
				<div className="dash-callout">
					<h6>Pub update needed</h6>
					<p>This Pub cannot list connected peers yet. Add peer still works. Open a channel from Channels.</p>
				</div>
			)}
			{loading ? (
				<p className="dash-field-hint">Loading peers…</p>
			) : !needsListPeers && (
				<PeerList peers={ordered} onSelect={setSelected} />
			)}
			{selected && (
				<PeerDialog
					peer={selected}
					adminSource={adminSource}
					onClose={() => setSelected(null)}
					onOpened={() => {
						setSelected(null);
						void loadPeers();
					}}
				/>
			)}
		</DashboardShell>
	);
}

function PeerList({ peers, onSelect }: { peers: LndPeer[]; onSelect: (peer: LndPeer) => void }) {
	if (peers.length === 0) {
		return <p className="dash-field-hint">No connected peers. Add one above.</p>;
	}
	return (
		<div className="dash-section">
			<div className="dash-section-head">
				<h2>Connected</h2>
				<span className="dash-section-count">{peers.length}</span>
			</div>
			<div className="dash-peer-stack">
				{peers.map((peer) => (
					<PeerRow key={peer.pubkey} peer={peer} onSelect={onSelect} />
				))}
			</div>
		</div>
	);
}

function PeerRow({ peer, onSelect }: { peer: LndPeer; onSelect: (peer: LndPeer) => void }) {
	return (
		<button type="button" className="dash-peer-item" onClick={() => onSelect(peer)}>
			<div className="dash-peer-item-main">
				<div className="dash-peer-item-name">{displayName(peer)}</div>
				<div className="dash-peer-item-sub">
					{peer.address || shortPubkey(peer.pubkey)}
					{peer.alias ? ` · ${shortPubkey(peer.pubkey)}` : ""}
				</div>
			</div>
			{peer.has_channel && <span className="dash-pill is-ok">channel</span>}
		</button>
	);
}

function PeerDialog({
	peer,
	adminSource,
	onClose,
	onOpened,
}: {
	peer: LndPeer;
	adminSource: SourceView;
	onClose: () => void;
	onOpened: () => void;
}) {
	return (
		<DashDialog title={displayName(peer)} onClose={onClose}>
			<dl className="dash-policy">
				<div className="dash-policy-row">
					<dt>Pubkey</dt>
					<dd>{peer.pubkey}</dd>
				</div>
				{peer.address && (
					<div className="dash-policy-row">
						<dt>Address</dt>
						<dd>{peer.address}</dd>
					</div>
				)}
				<div className="dash-policy-row">
					<dt>Channel</dt>
					<dd>{peer.has_channel ? "yes" : "gossip only"}</dd>
				</div>
			</dl>
			<span className="dash-section-tag">Open channel</span>
			<ChannelOpenForm
				adminSource={adminSource}
				peerLocked={peer.pubkey}
				onOpened={onOpened}
			/>
		</DashDialog>
	);
}

function channelPeersFirst(peers: LndPeer[]) {
	const withChannel: LndPeer[] = [];
	const gossip: LndPeer[] = [];
	for (const peer of peers) {
		if (peer.has_channel) withChannel.push(peer);
		else gossip.push(peer);
	}
	return [...withChannel, ...gossip];
}

function displayName(peer: LndPeer) {
	const alias = peer.alias?.trim();
	if (alias && alias !== peer.pubkey) return alias;
	return shortPubkey(peer.pubkey);
}

function shortPubkey(pubkey: string) {
	if (pubkey.length < 16) return pubkey;
	return `${pubkey.slice(0, 8)}…${pubkey.slice(-8)}`;
}
