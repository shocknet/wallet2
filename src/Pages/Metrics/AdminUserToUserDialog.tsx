import { useMemo, useState } from "react";
import { toast } from "react-toastify";
import type { UserAdminInfo } from "@/Api/pub/autogenerated/ts/types";
import { DashDialog } from "@/Layout2/Metrics/DashDialog";
import type { AppApiError } from "@/State/api/api";
import { useDashboardSource } from "./DashboardSourceContext";
import { formatTableAmount } from "./metricsDataTable";
import { useAdminSendUserToUserMutation } from "./pubDashApi";
import { trimUserId } from "./userAdminDisplay";

type AdminUserToUserDialogProps = {
	onClose: () => void;
	users: UserAdminInfo[];
	initialFromUserId?: string;
	initialToUserId?: string;
};

type Step = "form" | "confirm";

export function AdminUserToUserDialog({
	onClose,
	users,
	initialFromUserId = "",
	initialToUserId = "",
}: AdminUserToUserDialogProps) {
	const { sourceId } = useDashboardSource();
	const [fromUserId, setFromUserId] = useState(initialFromUserId);
	const [toUserId, setToUserId] = useState(initialToUserId);
	const [amount, setAmount] = useState("");
	const [step, setStep] = useState<Step>("form");
	const [send, { isLoading }] = useAdminSendUserToUserMutation();

	const fromUser = useMemo(
		() => users.find((u) => u.user_id === fromUserId.trim()),
		[users, fromUserId],
	);
	const toUser = useMemo(
		() => users.find((u) => u.user_id === toUserId.trim()),
		[users, toUserId],
	);

	const parsedAmount = Number(amount.replace(/\s/g, ""));
	const amountOk = Number.isFinite(parsedAmount) && parsedAmount > 0 && Number.isInteger(parsedAmount);
	const fromOk = fromUserId.trim().length > 0;
	const toOk = toUserId.trim().length > 0;
	const sameUser = fromOk && toOk && fromUserId.trim() === toUserId.trim();
	const canReview = fromOk && toOk && amountOk && !sameUser;

	const goConfirm = () => {
		if (!fromOk || !toOk) {
			toast.error("Enter from and to user ids");
			return;
		}
		if (sameUser) {
			toast.error("From and to must be different users");
			return;
		}
		if (!amountOk) {
			toast.error("Enter a positive whole number of sats");
			return;
		}
		setStep("confirm");
	};

	const onSubmit = async () => {
		try {
			const res = await send({
				sourceId,
				from_user_id: fromUserId.trim(),
				to_user_id: toUserId.trim(),
				amount: parsedAmount,
			}).unwrap();
			const feeNote = res.fees > 0 ? ` (fee ${formatTableAmount(res.fees)} sats)` : "";
			toast.success(`Moved ${formatTableAmount(res.amount)} sats${feeNote}`);
			onClose();
		} catch (e) {
			toast.error((e as AppApiError).message || "Could not transfer sats");
		}
	};

	if (step === "confirm") {
		return (
			<DashDialog
				title="Confirm transfer"
				onClose={onClose}
				footer={
					<>
						<button type="button" className="dash-btn dash-btn-ghost" onClick={() => setStep("form")} disabled={isLoading}>
							Back
						</button>
						<button type="button" className="dash-btn" disabled={isLoading} onClick={() => void onSubmit()}>
							{isLoading ? "Sending…" : "Send"}
						</button>
					</>
				}
			>
				<p className="dash-field-hint">
					Moves Pub ledger sats between users. Does not spend on-chain or Lightning funds.
				</p>
				<dl className="dash-policy">
					<div className="dash-policy-row">
						<dt>From</dt>
						<dd title={fromUserId.trim()}>{trimUserId(fromUserId.trim())}</dd>
					</div>
					<div className="dash-policy-row">
						<dt>To</dt>
						<dd title={toUserId.trim()}>{trimUserId(toUserId.trim())}</dd>
					</div>
					<div className="dash-policy-row">
						<dt>Amount</dt>
						<dd>{formatTableAmount(parsedAmount)} sats</dd>
					</div>
				</dl>
			</DashDialog>
		);
	}

	return (
		<DashDialog
			title="Transfer sats"
			onClose={onClose}
			footer={
				<>
					<button type="button" className="dash-btn dash-btn-ghost" onClick={onClose}>
						Cancel
					</button>
					<button type="button" className="dash-btn" disabled={!canReview} onClick={goConfirm}>
						Review
					</button>
				</>
			}
		>
			<UserIdField
				id="u2u-from"
				label="From user"
				value={fromUserId}
				onChange={setFromUserId}
				users={users}
				balance={fromUser?.balance}
			/>
			<UserIdField
				id="u2u-to"
				label="To user"
				value={toUserId}
				onChange={setToUserId}
				users={users}
				balance={toUser?.balance}
			/>
			<div className="dash-field">
				<label htmlFor="u2u-amount">Amount (sats)</label>
				<input
					id="u2u-amount"
					type="number"
					min={1}
					step={1}
					inputMode="numeric"
					placeholder="1000"
					value={amount}
					onChange={(e) => setAmount(e.target.value)}
				/>
				{fromUser != null && (
					<p className="dash-field-hint">
						Sender balance: {formatTableAmount(fromUser.balance)} sats
						{fromUser.locked ? " · locked" : ""}
					</p>
				)}
			</div>
		</DashDialog>
	);
}

function UserIdField({
	id,
	label,
	value,
	onChange,
	users,
	balance,
}: {
	id: string;
	label: string;
	value: string;
	onChange: (v: string) => void;
	users: UserAdminInfo[];
	balance?: number;
}) {
	const listId = `${id}-list`;
	return (
		<div className="dash-field">
			<label htmlFor={id}>{label}</label>
			<input
				id={id}
				list={listId}
				type="text"
				spellCheck={false}
				autoComplete="off"
				placeholder="user id"
				value={value}
				onChange={(e) => onChange(e.target.value)}
			/>
			<datalist id={listId}>
				{users.map((user) => (
					<option key={user.user_id} value={user.user_id}>
						{trimUserId(user.user_id)}
						{user.owner_of_app_id ? " · owner" : ""}
						{user.locked ? " · locked" : ""}
						{` · ${formatTableAmount(user.balance)} sats`}
					</option>
				))}
			</datalist>
			{balance != null && value.trim() && (
				<p className="dash-field-hint">Balance {formatTableAmount(balance)} sats</p>
			)}
		</div>
	);
}
