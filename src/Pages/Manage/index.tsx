import { useCallback, useEffect, useMemo, useRef, useState, type ReactNode } from "react";
import { toast } from "react-toastify";
import Toast from "../../Components/Toast";
import { getNostrClient } from "@/Api/nostr";
import { useIonRouter, useIonLoading } from "@ionic/react";
import { DashboardShell } from "@/Layout2/Metrics/DashboardShell";
import { DashErrorBanner } from "@/Pages/Metrics/DashErrorBanner";
import { nip19 } from "nostr-tools";
import { useAppSelector } from "@/State/store/hooks";
import { selectAdminSourceViews, sourceRpcKey } from "@/State/scoped/backups/sources/selectors";
import { selectSelectedMetricsAdminSourceId } from "@/State/runtime/slice";
import type { AdminNodeSettings } from "@/Api/pub/autogenerated/ts/types";
import { adminNodeSettingsNeedsUpgrade } from "@/Pages/Metrics/pubDashboardCapability";
import { uploadAvatarToBlossom } from "./blossomAvatar";

type NodeForm = {
	nodeName: string;
	avatarUrl: string;
	automate: boolean;
	backups: boolean;
	lspAutoBuy: boolean;
	lspThreshold: number;
};

type FieldStatus = "readonly" | "locked" | "unavailable";

const DEFAULT_LSP_THRESHOLD = 1_000_000;
const MAX_LSP_THRESHOLD = 100_000_000_000;

const persistLspThreshold = (autoBuy: boolean, threshold: number) => {
	if (!autoBuy) return 0;
	return threshold > 0 ? threshold : DEFAULT_LSP_THRESHOLD;
};

const isValidLspThreshold = (threshold: number) =>
	Number.isSafeInteger(threshold) && threshold >= 1 && threshold <= MAX_LSP_THRESHOLD;

const keepLastThreshold = (fromServer: NodeForm, previous: NodeForm): NodeForm => {
	if (fromServer.lspAutoBuy || previous.lspThreshold <= 0) return fromServer;
	return { ...fromServer, lspThreshold: previous.lspThreshold };
};

const emptyForm = (): NodeForm => ({
	nodeName: "",
	avatarUrl: "",
	automate: true,
	backups: false,
	lspAutoBuy: true,
	lspThreshold: DEFAULT_LSP_THRESHOLD,
});

const formFromSettings = (s: AdminNodeSettings): NodeForm => {
	const threshold = typeof s.lsp_channel_threshold === "number"
		? s.lsp_channel_threshold
		: DEFAULT_LSP_THRESHOLD;
	return {
		nodeName: s.node_name,
		avatarUrl: s.avatar_url,
		automate: s.automate_liquidity,
		backups: s.push_backups_to_nostr,
		lspAutoBuy: threshold > 0,
		lspThreshold: threshold > 0 ? threshold : DEFAULT_LSP_THRESHOLD,
	};
};

const toUpdateReq = (form: NodeForm) => ({
	node_name: form.nodeName.trim(),
	avatar_url: form.avatarUrl.trim(),
	automate_liquidity: form.automate,
	push_backups_to_nostr: form.backups,
	lsp_channel_threshold: persistLspThreshold(form.lspAutoBuy, form.lspThreshold),
});

const fieldStatus = (locked: boolean): FieldStatus | undefined => {
	if (locked) return "locked";
	return undefined;
};

const Manage = () => {
	const router = useIonRouter();
	const [isRevealed, setIsRevealed] = useState(false);
	const [seed, setSeed] = useState<string[]>([]);
	const [form, setForm] = useState<NodeForm>(emptyForm);
	const [saved, setSaved] = useState<NodeForm>(emptyForm);
	const [locks, setLocks] = useState({ name: false, automate: false, backups: false, lsp: false });
	const [needsUpgrade, setNeedsUpgrade] = useState(false);
	const [loading, setLoading] = useState(true);
	const [saving, setSaving] = useState(false);
	const [uploading, setUploading] = useState(false);
	const fileInputRef = useRef<HTMLInputElement>(null);
	const [error, setError] = useState<string | null>(null);
	const [presentLoading, dismissLoading] = useIonLoading();

	const admins = useAppSelector(selectAdminSourceViews);
	const selectedId = useAppSelector(selectSelectedMetricsAdminSourceId);
	const adminSource = useMemo(
		() => admins.find(a => a.sourceId === selectedId),
		[admins, selectedId]
	)!;
	const relayUrl = adminSource.relays[0] || "";
	const robohashUrl = `https://robohash.org/${adminSource.lpk}.png?bgset=bg1`;
	const avatarPreviewUrl = isHttpsAvatarUrl(form.avatarUrl) && form.avatarUrl.trim()
		? form.avatarUrl.trim()
		: robohashUrl;
	const showingRobohash = avatarPreviewUrl === robohashUrl;
	const identityBlocked = needsUpgrade || loading;
	const autoStatus = fieldStatus(locks.automate);
	const lspStatus = fieldStatus(locks.lsp);
	const backupStatus = fieldStatus(locks.backups);
	const rpcKey = sourceRpcKey(adminSource);

	const clientForAdmin = useCallback(async () => {
		return getNostrClient(
			{ pubkey: adminSource.lpk, relays: adminSource.relays },
			adminSource.keys!
		);
	}, [rpcKey]);

	useEffect(() => {
		let cancelled = false;
		const load = async () => {
			setError(null);
			setNeedsUpgrade(false);
			setLoading(true);
			let client: Awaited<ReturnType<typeof clientForAdmin>> | undefined;
			try {
				client = await clientForAdmin();
				const res = await client.GetAdminNodeSettings();
				if (cancelled) return;
				if (res.status !== "OK") {
					if (await adminNodeSettingsNeedsUpgrade(res.reason, client)) {
						setNeedsUpgrade(true);
						return;
					}
					setError(res.reason || "Failed to load settings");
					return;
				}
				const next = formFromSettings(res);
				setForm(next);
				setSaved(next);
				setLocks({
					name: res.node_name_env_locked,
					automate: res.automate_liquidity_env_locked,
					backups: res.backups_env_locked,
					lsp: res.lsp_threshold_env_locked,
				});
			} catch (e) {
				if (cancelled) return;
				const msg = e instanceof Error ? e.message : "Failed to load settings";
				if (client && await adminNodeSettingsNeedsUpgrade(msg, client)) {
					setNeedsUpgrade(true);
					return;
				}
				setError(msg);
			} finally {
				if (!cancelled) setLoading(false);
			}
		};
		void load();
		return () => {
			cancelled = true;
		};
	}, [clientForAdmin]);

	const persist = async (next: NodeForm) => {
		if (!isHttpsAvatarUrl(next.avatarUrl)) {
			setError("Avatar URL must be https");
			toast.error(<Toast title="Manage" message="Avatar URL must be https" />);
			return false;
		}
		const toSave = next.lspAutoBuy && next.lspThreshold <= 0
			? { ...next, lspThreshold: DEFAULT_LSP_THRESHOLD }
			: next;
		if (toSave.lspAutoBuy && !isValidLspThreshold(toSave.lspThreshold)) {
			setError("Inbound threshold must be a sat amount");
			toast.error(<Toast title="Manage" message="Inbound threshold must be a sat amount" />);
			return false;
		}
		setSaving(true);
		setError(null);
		try {
			const client = await clientForAdmin();
			const res = await client.UpdateAdminNodeSettings(toUpdateReq(toSave));
			if (res.status !== "OK") {
				setError(res.reason || "Failed to save settings");
				toast.error(<Toast title="Manage" message={res.reason || "Failed to save settings"} />);
				return false;
			}
			const savedForm = keepLastThreshold(formFromSettings(res), toSave);
			setForm(savedForm);
			setSaved(savedForm);
			setLocks({
				name: res.node_name_env_locked,
				automate: res.automate_liquidity_env_locked,
				backups: res.backups_env_locked,
				lsp: res.lsp_threshold_env_locked,
			});
			return true;
		} catch (e) {
			const msg = e instanceof Error ? e.message : "Failed to save settings";
			setError(msg);
			toast.error(<Toast title="Manage" message={msg} />);
			return false;
		} finally {
			setSaving(false);
		}
	};

	const fetchSeed = async () => {
		setError(null);
		if (isRevealed) {
			setIsRevealed(false);
			return;
		}
		setIsRevealed(true);
		await dismissLoading();
		await presentLoading({ message: "Fetching seed...", cssClass: "app-loading" });
		try {
			const client = await clientForAdmin();
			const res = await client.GetSeed();
			if (res.status !== "OK") {
				setError(res.reason || "Failed to fetch seed");
				toast.error(
					<Toast title="Metrics Error" message={`failed to fetch seed ${res.reason}`} />
				);
				return;
			}
			setSeed(res.seed);
		} catch (e) {
			const msg = e instanceof Error ? e.message : "Failed to fetch seed";
			setError(msg);
			toast.error(<Toast title="Metrics Error" message={`failed to fetch seed ${msg}`} />);
		} finally {
			await dismissLoading();
		}
	};

	const onToggleAutomate = async () => {
		if (locks.automate || needsUpgrade || loading || saving) return;
		const next = { ...form, automate: !form.automate };
		setForm(next);
		await persist(next);
	};

	const onToggleBackups = async () => {
		if (locks.backups || needsUpgrade || loading || saving) return;
		const next = { ...form, backups: !form.backups };
		setForm(next);
		await persist(next);
	};

	const onToggleLsp = async () => {
		if (locks.lsp || needsUpgrade || loading || saving) return;
		const next = { ...form, lspAutoBuy: !form.lspAutoBuy };
		if (next.lspAutoBuy && next.lspThreshold <= 0) next.lspThreshold = DEFAULT_LSP_THRESHOLD;
		setForm(next);
		await persist(next);
	};

	const onLspThresholdBlur = async () => {
		if (locks.lsp || needsUpgrade || !form.lspAutoBuy) return;
		const next = form.lspThreshold > 0 ? form : { ...form, lspThreshold: DEFAULT_LSP_THRESHOLD };
		if (next.lspThreshold !== form.lspThreshold) setForm(next);
		if (next.lspThreshold === saved.lspThreshold && next.lspAutoBuy === saved.lspAutoBuy) return;
		await persist(next);
	};

	const onPickAvatar = async (file: File | undefined) => {
		if (!file || identityBlocked || !adminSource.keys) return;
		setUploading(true);
		setError(null);
		try {
			const url = await uploadAvatarToBlossom(file, adminSource.keys);
			const next = { ...form, avatarUrl: url };
			setForm(next);
			await persist(next);
		} catch (e) {
			const msg = e instanceof Error ? e.message : "Avatar upload failed";
			setError(msg);
			toast.error(<Toast title="Manage" message={msg} />);
		} finally {
			setUploading(false);
			if (fileInputRef.current) fileInputRef.current.value = "";
		}
	};

	const onDone = async () => {
		const dirty =
			form.nodeName.trim() !== saved.nodeName.trim()
			|| form.avatarUrl.trim() !== saved.avatarUrl.trim()
			|| form.lspAutoBuy !== saved.lspAutoBuy
			|| form.lspThreshold !== saved.lspThreshold;
		if (!needsUpgrade && dirty) {
			const ok = await persist(form);
			if (!ok) return;
		}
		router.push("/metrics", "back");
	};

	return (
		<DashboardShell title="Manage">
			{error && <DashErrorBanner message={error} />}
			{needsUpgrade && (
				<div className="dash-callout">
					<h6>Pub update needed</h6>
					<p>This Pub cannot edit name, image, automation, or backups yet.</p>
				</div>
			)}

			<div className="Manage">
				<Section title="Identity">
					<div className="dash-card identity">
						<div className="identity-shot">
							<button
								type="button"
								className="identity-avatar"
								disabled={identityBlocked || uploading || saving}
								onClick={() => fileInputRef.current?.click()}
								aria-label={uploading ? "Uploading image" : "Upload image"}
							>
								<img
									src={avatarPreviewUrl}
									alt=""
									referrerPolicy="no-referrer"
									onError={(e) => {
										const el = e.currentTarget;
										if (el.src !== robohashUrl) el.src = robohashUrl;
									}}
								/>
								<span className={`identity-avatar-veil${uploading ? " is-on" : ""}`}>
									{uploading ? "Uploading" : "Change"}
								</span>
							</button>
							{showingRobohash && <span className="identity-avatar-cap">Generated</span>}
						</div>
						<input
							ref={fileInputRef}
							type="file"
							accept="image/jpeg,image/png,image/webp,image/gif"
							hidden
							onChange={(e) => { void onPickAvatar(e.target.files?.[0]); }}
						/>
						<div className="identity-fields">
							{needsUpgrade ? null : loading ? (
								<p className="setting-hint">Loading…</p>
							) : (
								<>
									<label className={`setting-field${locks.name ? " is-locked" : ""}`}>
										<span className="setting-title">
											Name
											{locks.name && <StatusPill status="locked" />}
										</span>
										<input
											type="text"
											placeholder="Nodey McNodeFace"
											value={form.nodeName}
											disabled={locks.name}
											onChange={(e) => setForm({ ...form, nodeName: e.target.value })}
										/>
									</label>
									<label className="setting-field is-url">
										<span className="setting-title">Image URL</span>
										<input
											type="text"
											placeholder="https://"
											value={form.avatarUrl}
											disabled={uploading}
											onChange={(e) => setForm({ ...form, avatarUrl: e.target.value })}
										/>
									</label>
									{form.avatarUrl.trim() && !isHttpsAvatarUrl(form.avatarUrl) && (
										<p className="setting-hint is-warn">Must be an https URL</p>
									)}
								</>
							)}
						</div>
					</div>
				</Section>

				<Section title="Nostr">
					<div className="dash-card setting-stack">
						<SettingBlock
							title="Relay"
							status="readonly"
							hint="Changing relay is a live cutover. Not from here."
						>
							<p className="setting-value">{relayUrl || "No relay connected"}</p>
						</SettingBlock>
						<SettingBlock
							title="Public discovery"
							status="unavailable"
							hint="Whether new users need an invite is not editable from this dashboard yet."
						/>
						<SettingBlock
							title="Managed relay"
							status="unavailable"
							hint="Managed relay billing is not editable from this dashboard yet."
						/>
					</div>
				</Section>

				{(!loading || needsUpgrade) && (
					<Section
						title="Liquidity Automation"
						help={(
							<HelpTip>
								<p>
									Trust a peer until this node can afford a channel. That keeps
									you from buying a channel too early.
								</p>
								<a
									href="https://docs.shock.network/"
									target="_blank"
									rel="noreferrer"
								>
									Learn more
								</a>
							</HelpTip>
						)}
					>
						<div className="dash-card setting-stack">
							<SettingBlock
								title="Trust a peer until this node can afford a channel."
								status={autoStatus}
							>
								<Toggle
									id="automationService"
									checked={form.automate}
									disabled={!!autoStatus || needsUpgrade}
									onChange={() => { void onToggleAutomate(); }}
								/>
							</SettingBlock>
							<SettingBlock
								title="Auto-buy an LSP channel when inbound is below this amount."
								status={lspStatus}
								below={form.lspAutoBuy && !needsUpgrade ? (
									<LspThresholdField
										value={form.lspThreshold}
										disabled={!!lspStatus || saving}
										onChange={(lspThreshold) => setForm({ ...form, lspThreshold })}
										onBlur={() => { void onLspThresholdBlur(); }}
									/>
								) : undefined}
							>
								<Toggle
									id="lspAutoBuy"
									checked={form.lspAutoBuy}
									disabled={!!lspStatus || needsUpgrade}
									onChange={() => { void onToggleLsp(); }}
								/>
							</SettingBlock>
						</div>
					</Section>
				)}

				<Section title="Recovery">
					{(!loading || needsUpgrade) && (
						<div className="dash-card setting-stack">
							<SettingBlock
								title="Backup channels to the relay"
								status={backupStatus}
								hint="Stores channel backups on the relay you already use."
							>
								<Toggle
									id="channelBackup"
									checked={form.backups}
									disabled={!!backupStatus || needsUpgrade}
									onChange={() => { void onToggleBackups(); }}
								/>
							</SettingBlock>
						</div>
					)}
					<div className="dash-card seed-card">
						<SeedPanel
							revealed={isRevealed}
							words={seed}
							onToggle={() => { void fetchSeed(); }}
						/>
					</div>
				</Section>

				<button
					onClick={() => { void onDone(); }}
					disabled={saving}
					className="dash-btn dash-btn-lined Manage_save"
				>
					{saving ? "Saving…" : "Done"}
				</button>
				<div className="Manage_footer">
					Connected to <br />
					{nip19.nprofileEncode({ pubkey: adminSource.lpk, relays: adminSource.relays })}
				</div>
			</div>
		</DashboardShell>
	);
};

function Section({ title, help, children }: { title: string; help?: ReactNode; children: ReactNode }) {
	return (
		<section className="dash-section">
			<div className="dash-section-head">
				<h2>{title}</h2>
				{help}
			</div>
			{children}
		</section>
	);
}

function HelpTip({ children }: { children: ReactNode }) {
	const [open, setOpen] = useState(false);
	return (
		<div className="help-tip">
			<button
				type="button"
				className="help-tip-btn"
				aria-expanded={open}
				aria-label="What is liquidity automation?"
				onClick={() => setOpen(!open)}
			>
				?
			</button>
			{open && <div className="help-tip-panel">{children}</div>}
		</div>
	);
}

function SeedPanel({
	revealed,
	words,
	onToggle,
}: {
	revealed: boolean;
	words: string[];
	onToggle: () => void;
}) {
	if (!revealed) {
		return (
			<button type="button" className="seed-gate" onClick={onToggle}>
				<span className="seed-gate-title">Node seed</span>
				<span className="seed-gate-copy">
					Hidden. Anyone with these words can spend the node&apos;s funds.
				</span>
				<span className="seed-gate-action">Reveal seed</span>
			</button>
		);
	}
	return (
		<div className="seed">
			<div className="seed-box">
				{words.map((item, index) => (
					<span key={`${item}-${index}`} className="seed-item">{`${index + 1}. ${item}`}</span>
				))}
			</div>
			<button type="button" className="dash-text-btn seed-toggle" onClick={onToggle}>
				Hide seed
			</button>
		</div>
	);
}

function statusCopy(status: FieldStatus) {
	if (status === "unavailable") return "Coming soon";
	return "Read only";
}

function StatusPill({ status }: { status: FieldStatus }) {
	return <span className="dash-pill">{statusCopy(status)}</span>;
}

function SettingBlock({
	title,
	hint,
	status,
	below,
	children,
}: {
	title: string;
	hint?: string;
	status?: FieldStatus;
	below?: ReactNode;
	children?: ReactNode;
}) {
	const toggle = isToggleChild(children);
	return (
		<div className={`setting${status ? ` is-${status}` : ""}`}>
			<div className="setting-top">
				<span className="setting-title">{title}</span>
				<div className="setting-meta">
					{status && <StatusPill status={status} />}
					{toggle ? children : null}
				</div>
			</div>
			{!toggle && status !== "unavailable" && children && (
				<div className="setting-body">{children}</div>
			)}
			{below && <div className="setting-body">{below}</div>}
			{hint && <p className="setting-hint">{hint}</p>}
		</div>
	);
}

function LspThresholdField({
	value,
	disabled,
	onChange,
	onBlur,
}: {
	value: number;
	disabled: boolean;
	onChange: (n: number) => void;
	onBlur: () => void;
}) {
	return (
		<div className="setting-amount-row">
			<input
				className="setting-amount"
				type="text"
				inputMode="numeric"
				aria-label="Inbound below, in sats"
				value={value > 0 ? value.toLocaleString("en-US") : ""}
				disabled={disabled}
				onChange={(e) => {
					const digits = e.target.value.replace(/[^0-9]/g, "");
					onChange(Number.parseInt(digits, 10) || 0);
				}}
				onBlur={onBlur}
			/>
			<span className="setting-value">sats</span>
		</div>
	);
}

function isToggleChild(children: ReactNode) {
	return typeof children === "object" && children !== null && "type" in children && children.type === Toggle;
}

function Toggle({
	id,
	checked,
	disabled,
	onChange,
}: {
	id: string;
	checked: boolean;
	disabled?: boolean;
	onChange: () => void;
}) {
	return (
		<label className={`toggle${disabled ? " is-disabled" : ""}`} htmlFor={id}>
			<input
				id={id}
				type="checkbox"
				checked={checked}
				disabled={disabled}
				onChange={onChange}
			/>
			<span className="toggle-ui" aria-hidden />
		</label>
	);
}

function isHttpsAvatarUrl(url: string) {
	const trimmed = url.trim();
	if (!trimmed) return true;
	try {
		const parsed = new URL(trimmed);
		return parsed.protocol === "https:" && !parsed.username && !parsed.password && !!parsed.hostname;
	} catch {
		return false;
	}
}

export default Manage;
