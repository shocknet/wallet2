import { truncateTextMiddle } from "@/lib/format";
import { useToast } from "@/lib/contexts/useToast";
import {
	useGetManageAuthorizationsQuery,
	useGetProfileQuery,
	useResetManageAuthorizationMutation,
} from "@/State/api/api";
import { useSourceSelection } from "@/Hooks/useSourceSelection";
import { useLiveSourceView } from "@/Hooks/useSourceView";
import cn from "clsx";

type ManagementTab = "approved" | "banned";

export default function Management() {
	const { sourceId, setOverrideSourceId } = useSourceSelection();

	return (
		<IonPage className="ion-page-width">
			<IonHeader className="ion-no-border">
				<RootPageToolbar title="Management" />
				<IonToolbar>
					<div className="mx-auto flex w-full max-w-md flex-col gap-2 px-5 md:px-0">
						<SourceSelectionView
							sourceId={sourceId}
							onSourceId={setOverrideSourceId}
							title="Select source"
							showBalance={false}
							showTapToSwitch={false}
						/>
						<SourceReachabilityHint sourceId={sourceId} />
					</div>
				</IonToolbar>
			</IonHeader>
			<ManagementSource key={sourceId} sourceId={sourceId} />
		</IonPage>
	);
}

function ManagementSource({ sourceId }: { sourceId: string }) {
	const { refetch } = useGetManageAuthorizationsQuery({ sourceId });

	const handleRefresh = useCallback(
		async (event: CustomEvent<RefresherEventDetail>) => {
			try {
				await refetch();
			} finally {
				event.detail.complete();
			}
		},
		[refetch],
	);

	return (
		<IonContent className="ion-padding">
			<IonRefresher slot="fixed" onIonRefresh={handleRefresh}>
				<IonRefresherContent />
			</IonRefresher>

			<div className="mx-auto flex min-h-full w-full max-w-md flex-col gap-6 pb-8 pt-2">
				<NmanageShare sourceId={sourceId} />
				<section className="flex min-h-[40%] flex-1 flex-col">
					<p className="m-0 mb-3 text-xs font-medium uppercase tracking-wide text-muted">
						Offer access
					</p>
					<ManageAuthList sourceId={sourceId} />
				</section>
			</div>
		</IonContent>
	);
}

function NmanageShare({ sourceId }: { sourceId: string }) {
	const source = useLiveSourceView(sourceId);
	const nmanage = source.nmanage?.trim() || "";

	return (
		<section
			className="
				flex flex-wrap items-center gap-x-3 gap-y-2 rounded-xl
				bg-[var(--app-surface)] px-3 py-2 wallet-box-shadow
			"
		>
			<div className="flex min-w-0 flex-1 items-center gap-1">
				{nmanage ? (
					<>
						<span className="min-w-0 flex-1 truncate font-mono text-sm text-primary">
							{truncateTextMiddle(nmanage, 18, 14, "…")}
						</span>
						<CopyMorphButton
							value={nmanage}
							fill="clear"
							size="small"
							shape="round"
							className="m-0 shrink-0"
							aria-label="Copy manage string"
						/>
					</>
				) : (
					<span className="truncate text-sm text-muted">
						Manage string unavailable
					</span>
				)}
			</div>
		</section>
	);
}

function ManageAuthList({ sourceId }: { sourceId: string }) {
	const source = useLiveSourceView(sourceId);
	const { showToast } = useToast();
	const promptDanger = usePromptDangerModal();
	const [tab, setTab] = useState<ManagementTab>("approved");
	const [pendingNpub, setPendingNpub] = useState<string | null>(null);
	const {
		data: authorizations = [],
		isLoading,
		isFetching,
		isError,
		error,
	} = useGetManageAuthorizationsQuery({ sourceId: source.sourceId });
	const [resetManage] = useResetManageAuthorizationMutation();

	const { approved, banned } = useMemo(() => {
		const next = {
			approved: [] as ManageAuthorization[],
			banned: [] as ManageAuthorization[],
		};
		for (const auth of authorizations) {
			if (auth.authorized) next.approved.push(auth);
			else next.banned.push(auth);
		}
		return next;
	}, [authorizations]);

	const showing = tab === "approved" ? approved : banned;

	const revoke = (authorization: ManageAuthorization) => {
		const removingBan = !authorization.authorized;
		void promptDanger({
			title: removingBan ? "Remove ban?" : "Revoke offer access?",
			description: removingBan
				? "This app can request offer access again."
				: "This app will no longer be able to create, update, or delete offers on this source.",
			confirmButtonLabel: removingBan ? "Remove" : "Revoke",
		}).then(async (result) => {
			if (result.role !== "confirm") return;
			setPendingNpub(authorization.npub);
			try {
				const res = await resetManage({
					sourceId: source.sourceId,
					npub: authorization.npub,
				});
				if (res.error) {
					showToast({
						message: res.error.message ?? "Could not update offer access",
						color: "danger",
					});
					return;
				}
				showToast({
					message: removingBan ? "Ban removed" : "Offer access revoked",
					color: "success",
				});
			} finally {
				setPendingNpub(null);
			}
		});
	};

	if (isLoading || (isFetching && authorizations.length === 0)) {
		return (
			<div className="flex flex-1 items-center justify-center py-10">
				<IonSpinner name="crescent" />
			</div>
		);
	}

	if (isError) {
		return (
			<EmptyState
				variant="section"
				title="Couldn't load offer access"
				description={error?.message ?? "Could not load offer access"}
			/>
		);
	}

	return (
		<div className="flex flex-col gap-3">
			<IonSegment
				value={tab}
				onIonChange={(e) => {
					const value = e.detail.value;
					if (value === "approved" || value === "banned") setTab(value);
				}}
				className="
					wallet-box-shadow
					p-1 [--background:var(--app-surface)]
				"
			>
				<IonSegmentButton value="approved">
					<IonLabel>Approved ({approved.length})</IonLabel>
				</IonSegmentButton>
				<IonSegmentButton value="banned">
					<IonLabel>Banned ({banned.length})</IonLabel>
				</IonSegmentButton>
			</IonSegment>

			{showing.length === 0 ? (
				<EmptyState
					variant="section"
					title={
						tab === "approved" ? "No apps with offer access" : "No banned apps"
					}
					description={
						tab === "approved"
							? "Share the manage string above so an app can request access to your offers."
							: "Apps you ban from managing offers will show up here."
					}
				/>
			) : (
				<div className="flex flex-col gap-3">
					{showing.map((authorization) => (
						<ManageAuthItem
							key={authorization.manage_id || authorization.npub}
							authorization={authorization}
							relays={source.relays}
							busy={pendingNpub === authorization.npub}
							onRevoke={() => revoke(authorization)}
						/>
					))}
				</div>
			)}
		</div>
	);
}

function ManageAuthItem({
	authorization,
	relays,
	busy,
	onRevoke,
}: {
	authorization: ManageAuthorization;
	relays?: string[];
	busy: boolean;
	onRevoke: () => void;
}) {
	const profileRelays = relays?.length ? relays : NOSTR_RELAYS;
	const pubkey = authorization.npub;
	const { data: profile } = useGetProfileQuery({
		pubkey,
		relays: profileRelays,
	});
	const name = resolveDebitAppDisplayName(profile);
	const nip05 = profile?.nip05?.trim() || "";
	const npub = debitNpub(pubkey);
	const banned = !authorization.authorized;

	return (
		<IonItem
			detail={false}
			lines="none"
			className={cn(
				"rounded-xl",
				"[--background:var(--app-surface)]",
				"[--border-radius:0.75rem]",
				"[--padding-start:0] [--inner-padding-end:0]",
				"[--min-height:0]",
				"border border-[var(--app-border)]",
				"shadow-[0_6px_18px_-10px_rgba(var(--app-box-shadow-color),0.45)]",
				banned && "opacity-80",
			)}
		>
			<div className="flex w-full min-w-0 flex-col">
				<div className="flex items-start gap-3 px-3.5 py-3">
					<Avatar id={pubkey} avatarUrl={profile?.picture} size="md" />
					<div className="min-w-0 flex-1">
						<div className="flex min-w-0 items-center gap-2">
							<p className="m-0 min-w-0 truncate text-base font-semibold text-primary">
								{name}
							</p>
							{banned ? (
								<span className="shrink-0 rounded-md bg-[color-mix(in_srgb,var(--ion-color-danger)_14%,transparent)] px-1.5 py-0.5 text-[0.65rem] font-medium uppercase tracking-wide text-[var(--ion-color-danger)]">
									Banned
								</span>
							) : null}
						</div>
						{nip05 ? (
							<div className="mt-1">
								<Nip05
									pubkey={pubkey}
									nip05={nip05}
									className="!max-w-full !px-2 !py-0.5"
								/>
							</div>
						) : (
							<p className="m-0 mt-0.5 font-mono text-[0.7rem] text-faint">
								{truncateTextMiddle(npub, 10, 8, "…")}
							</p>
						)}
					</div>
					<button
						type="button"
						aria-label={banned ? `Remove ban for ${name}` : `Revoke offer access for ${name}`}
						disabled={busy}
						onClick={onRevoke}
						className="inline-flex shrink-0 appearance-none border-0 bg-transparent p-1 text-[var(--ion-color-danger)] disabled:opacity-50"
					>
						{busy ? (
							<IonSpinner name="crescent" className="h-5 w-5" />
						) : (
							<IonIcon icon={trashOutline} className="text-xl" aria-hidden />
						)}
					</button>
				</div>
				<div className="border-t border-[color-mix(in_srgb,var(--app-border)_60%,transparent)] px-3.5 py-2">
					<p className="m-0 text-sm text-muted">
						{banned
							? "Blocked from managing offers"
							: "Can create, update, and delete offers"}
					</p>
				</div>
			</div>
		</IonItem>
	);
}
