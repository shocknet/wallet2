import { useCallback, useEffect, useMemo, useState } from "react";
import {
	IonButton,
	IonButtons,
	IonContent,
	IonFooter,
	IonHeader,
	IonIcon,
	IonModal,
	IonTitle,
	IonToggle,
	IonToolbar,
} from "@ionic/react";
import {
	banOutline,
	checkmarkOutline,
	closeOutline,
	trashOutline,
} from "ionicons/icons";
import { getNostrClient } from "@/Api/nostr";
import type { DebitAuthorization, DebitRule } from "@/Api/pub/autogenerated/ts/types";
import { DebitRule_rule_type } from "@/Api/pub/autogenerated/ts/types";
import { ClinkRequestIdentityView } from "@/Components/ClinkRequests/ClinkRequestIdentityView";
import { DebitRulesSummary } from "@/Components/Debit/DebitRulesSummary";
import { ExpirationRuleEditor } from "@/Components/Debit/ExpirationRuleEditor";
import { FrequencyRuleEditor } from "@/Components/Debit/FrequencyRuleEditor";
import { useToast } from "@/lib/contexts/useToast";
import {
	DEFAULT_FREQUENCY,
	defaultExpiresAtUnix,
	getExpiresAtUnix,
	getFrequency,
	upsertExpiry,
	upsertFrequency,
	withoutRuleType,
} from "@/lib/debit/rules";
import { appApi } from "@/State/api/api";
import type { SourceView } from "@/State/scoped/backups/sources/selectors";
import { useAppDispatch } from "@/State/store/hooks";

const PANEL_CLASS = "app-panel bg-[var(--app-surface-muted)]";

type Phase = "edit" | "banConfirm" | "removeConfirm";

function ModalCloseButton({
	onClose,
	disabled,
}: {
	onClose: () => void;
	disabled?: boolean;
}) {
	return (
		<IonButtons slot="end">
			<IonButton
				onClick={onClose}
				disabled={disabled}
				aria-label="Close"
			>
				<IonIcon slot="icon-only" icon={closeOutline} />
			</IonButton>
		</IonButtons>
	);
}

function rulesSignature(rules: DebitRule[]): string {
	return JSON.stringify(rules);
}

export type EditDebitModalProps = {
	isOpen: boolean;
	authorization: DebitAuthorization | null;
	source: SourceView;
	onDidDismiss: () => void;
};

function EditDebitApprovedBody({
	authorization,
	source,
	onClose,
}: {
	authorization: DebitAuthorization;
	source: SourceView;
	onClose: () => void;
}) {
	const dispatch = useAppDispatch();
	const { showToast } = useToast();
	const [phase, setPhase] = useState<Phase>("edit");
	const [busy, setBusy] = useState(false);
	const [rules, setRules] = useState<DebitRule[]>(() =>
		structuredClone(authorization.rules),
	);
	const initialSig = useMemo(
		() => rulesSignature(authorization.rules),
		[authorization.rules],
	);
	const dirty = rulesSignature(rules) !== initialSig;

	useEffect(() => {
		setRules(structuredClone(authorization.rules));
		setPhase("edit");
	}, [authorization.debit_id, authorization.rules]);

	const frequency = getFrequency(rules);
	const expiresAtUnix = getExpiresAtUnix(rules);
	const isFullAccess = frequency === null && expiresAtUnix === null;

	const invalidate = useCallback(() => {
		dispatch(
			appApi.util.invalidateTags([
				{ type: "DebitAuthorizations", id: source.sourceId },
			]),
		);
	}, [dispatch, source.sourceId]);

	const saveRules = useCallback(async () => {
		const client = await getNostrClient(
			{ pubkey: source.lpk, relays: source.relays },
			source.keys,
		);
		const res = await client.EditDebit({
			authorize_npub: authorization.npub,
			rules,
		});
		if (res.status !== "OK") {
			throw new Error(res.reason || "Could not update debit rules");
		}
		invalidate();
	}, [authorization.npub, invalidate, rules, source]);

	const ban = useCallback(async () => {
		const client = await getNostrClient(
			{ pubkey: source.lpk, relays: source.relays },
			source.keys,
		);
		const res = await client.BanDebit({ npub: authorization.npub });
		if (res.status !== "OK") {
			throw new Error(res.reason || "Could not ban this app");
		}
		invalidate();
	}, [authorization.npub, invalidate, source]);

	const remove = useCallback(async () => {
		const client = await getNostrClient(
			{ pubkey: source.lpk, relays: source.relays },
			source.keys,
		);
		const res = await client.ResetDebit({ npub: authorization.npub });
		if (res.status !== "OK") {
			throw new Error(res.reason || "Could not remove this debit");
		}
		invalidate();
	}, [authorization.npub, invalidate, source]);

	const run = useCallback(
		async (action: () => Promise<void>, successToast: string) => {
			if (busy) return;
			setBusy(true);
			try {
				await action();
				showToast({ message: successToast, color: "success" });
				onClose();
			} catch (e: unknown) {
				const message =
					e instanceof Error ? e.message : "Something went wrong";
				showToast({ message, color: "danger" });
			} finally {
				setBusy(false);
			}
		},
		[busy, onClose, showToast],
	);

	if (phase === "banConfirm") {
		return (
			<>
				<IonHeader>
					<IonToolbar>
						<IonTitle>Ban app</IonTitle>
						<ModalCloseButton onClose={onClose} disabled={busy} />
					</IonToolbar>
				</IonHeader>
				<IonContent className="ion-padding">
					<div className="mx-auto flex min-h-full max-w-md flex-col items-center justify-center gap-4 text-center">
						<p className="m-0 text-base leading-relaxed text-secondary">
							Ban this app from debit access? Future requests will be
							rejected until you remove the ban.
						</p>
					</div>
				</IonContent>
				<IonFooter>
					<IonToolbar>
						<div className="grid grid-cols-2 gap-3 px-3 pb-3 pt-2">
							<IonButton
								expand="block"
								fill="outline"
								color="medium"
								disabled={busy}
								onClick={() => setPhase("edit")}
							>
								Cancel
							</IonButton>
							<IonButton
								expand="block"
								color="danger"
								disabled={busy}
								onClick={() => void run(ban, "App banned")}
							>
								<IonIcon icon={banOutline} slot="start" />
								Ban
							</IonButton>
						</div>
					</IonToolbar>
				</IonFooter>
			</>
		);
	}

	if (phase === "removeConfirm") {
		return (
			<>
				<IonHeader>
					<IonToolbar>
						<IonTitle>Remove access</IonTitle>
						<ModalCloseButton onClose={onClose} disabled={busy} />
					</IonToolbar>
				</IonHeader>
				<IonContent className="ion-padding">
					<div className="mx-auto flex min-h-full max-w-md flex-col items-center justify-center gap-4 text-center">
						<p className="m-0 text-base leading-relaxed text-secondary">
							Remove this debit grant? The app will need to request access
							again.
						</p>
					</div>
				</IonContent>
				<IonFooter>
					<IonToolbar>
						<div className="grid grid-cols-2 gap-3 px-3 pb-3 pt-2">
							<IonButton
								expand="block"
								fill="outline"
								color="medium"
								disabled={busy}
								onClick={() => setPhase("edit")}
							>
								Cancel
							</IonButton>
							<IonButton
								expand="block"
								color="danger"
								disabled={busy}
								onClick={() =>
									void run(remove, "Debit access removed")
								}
							>
								<IonIcon icon={trashOutline} slot="start" />
								Remove
							</IonButton>
						</div>
					</IonToolbar>
				</IonFooter>
			</>
		);
	}

	return (
		<>
			<IonHeader>
				<IonToolbar>
					<IonTitle>Edit linked app</IonTitle>
					<ModalCloseButton onClose={onClose} disabled={busy} />
				</IonToolbar>
			</IonHeader>
			<IonContent className="ion-padding">
				<div className="mx-auto flex w-full max-w-md min-w-0 flex-col gap-5 pb-6">
					<ClinkRequestIdentityView
						pubkey={authorization.npub}
						relays={source.relays}
					/>

					{isFullAccess ? (
						<div className="rounded-xl border border-[var(--ion-color-warning)]/40 bg-[color-mix(in_srgb,var(--ion-color-warning)_12%,transparent)] px-3.5 py-3">
							<p className="m-0 text-sm font-semibold text-[var(--ion-color-warning)]">
								Full access until you revoke
							</p>
							<p className="m-0 mt-1 text-sm leading-relaxed text-secondary">
								No spending limit or expiry set.
							</p>
						</div>
					) : (
						<div className="rounded-xl border border-[color-mix(in_srgb,var(--ion-color-primary)_35%,var(--app-border))] bg-[color-mix(in_srgb,var(--ion-color-primary)_10%,transparent)] px-3.5 py-3">
							<p className="mb-1 text-xs font-medium uppercase tracking-wide text-muted">
								Current grant
							</p>
							<DebitRulesSummary
								rules={rules}
								className="flex flex-col gap-1 text-sm leading-relaxed text-secondary"
							/>
						</div>
					)}

					<div className="flex flex-col gap-1">
						<p className="m-0 text-xs font-medium uppercase tracking-wide text-muted">
							Limits
						</p>
						<p className="m-0 text-xs text-muted">
							Change these to restrict what this app can spend.
						</p>
					</div>

					<section className="flex flex-col gap-3">
						<IonToggle
							checked={frequency !== null}
							onIonChange={(event) => {
								if (event.detail.checked) {
									setRules(upsertFrequency(rules, DEFAULT_FREQUENCY));
									return;
								}
								setRules(
									withoutRuleType(rules, DebitRule_rule_type.FREQUENCY_RULE),
								);
							}}
						>
							Spending limit
						</IonToggle>
						{frequency !== null ? (
							<div className={PANEL_CLASS}>
								<FrequencyRuleEditor
									value={frequency}
									onChange={(next) =>
										setRules(upsertFrequency(rules, next))
									}
								/>
							</div>
						) : null}
					</section>

					<section className="flex flex-col gap-3">
						<IonToggle
							checked={expiresAtUnix !== null}
							onIonChange={(event) => {
								if (event.detail.checked) {
									setRules(upsertExpiry(rules, defaultExpiresAtUnix()));
									return;
								}
								setRules(
									withoutRuleType(
										rules,
										DebitRule_rule_type.EXPIRATION_RULE,
									),
								);
							}}
						>
							Expiry
						</IonToggle>
						{expiresAtUnix !== null ? (
							<div className={PANEL_CLASS}>
								<ExpirationRuleEditor
									value={expiresAtUnix}
									onChange={(nextUnix) =>
										setRules(upsertExpiry(rules, nextUnix))
									}
								/>
							</div>
						) : null}
					</section>
				</div>
			</IonContent>
			<IonFooter>
				<IonToolbar>
					<div className="flex flex-col gap-2 px-3 pb-3 pt-2">
						<IonButton
							expand="block"
							disabled={busy || !dirty}
							onClick={() =>
								void run(saveRules, "Debit rules updated")
							}
						>
							<IonIcon icon={checkmarkOutline} slot="start" />
							Save changes
						</IonButton>
						<div className="grid grid-cols-2 gap-3">
							<IonButton
								expand="block"
								fill="outline"
								color="danger"
								disabled={busy}
								onClick={() => setPhase("banConfirm")}
							>
								<IonIcon icon={banOutline} slot="start" />
								Ban
							</IonButton>
							<IonButton
								expand="block"
								fill="outline"
								color="medium"
								disabled={busy}
								onClick={() => setPhase("removeConfirm")}
							>
								<IonIcon icon={trashOutline} slot="start" />
								Remove
							</IonButton>
						</div>
					</div>
				</IonToolbar>
			</IonFooter>
		</>
	);
}

function EditDebitBannedBody({
	authorization,
	source,
	onClose,
}: {
	authorization: DebitAuthorization;
	source: SourceView;
	onClose: () => void;
}) {
	const dispatch = useAppDispatch();
	const { showToast } = useToast();
	const [busy, setBusy] = useState(false);

	const removeBan = useCallback(async () => {
		if (busy) return;
		setBusy(true);
		try {
			const client = await getNostrClient(
				{ pubkey: source.lpk, relays: source.relays },
				source.keys,
			);
			const res = await client.ResetDebit({ npub: authorization.npub });
			if (res.status !== "OK") {
				throw new Error(res.reason || "Could not remove this ban");
			}
			dispatch(
				appApi.util.invalidateTags([
					{ type: "DebitAuthorizations", id: source.sourceId },
				]),
			);
			showToast({ message: "Ban removed", color: "success" });
			onClose();
		} catch (e: unknown) {
			const message =
				e instanceof Error ? e.message : "Could not remove this ban";
			showToast({ message, color: "danger" });
		} finally {
			setBusy(false);
		}
	}, [authorization.npub, busy, dispatch, onClose, showToast, source]);

	return (
		<>
			<IonHeader>
				<IonToolbar>
					<IonTitle>Banned app</IonTitle>
					<ModalCloseButton onClose={onClose} disabled={busy} />
				</IonToolbar>
			</IonHeader>
			<IonContent className="ion-padding">
				<div className="mx-auto flex min-h-full w-full max-w-md flex-col items-center justify-center gap-5">
					<ClinkRequestIdentityView
						pubkey={authorization.npub}
						relays={source.relays}
					/>
					<p className="m-0 max-w-sm text-center text-sm leading-relaxed text-muted">
						This app is banned from debit access. Remove the ban to let
						them request access again.
					</p>
				</div>
			</IonContent>
			<IonFooter>
				<IonToolbar>
					<div className="flex flex-col gap-2 px-3 pb-3 pt-2">
						<IonButton
							expand="block"
							color="danger"
							disabled={busy}
							onClick={() => void removeBan()}
						>
							<IonIcon icon={trashOutline} slot="start" />
							Remove ban
						</IonButton>
					</div>
				</IonToolbar>
			</IonFooter>
		</>
	);
}

export default function EditDebitModal({
	isOpen,
	authorization,
	source,
	onDidDismiss,
}: EditDebitModalProps) {
	return (
		<IonModal
			className="wallet-modal"
			isOpen={isOpen && authorization !== null}
			onDidDismiss={onDidDismiss}
		>
			{authorization ? (
				authorization.authorized ? (
					<EditDebitApprovedBody
						key={authorization.debit_id}
						authorization={authorization}
						source={source}
						onClose={onDidDismiss}
					/>
				) : (
					<EditDebitBannedBody
						key={authorization.debit_id}
						authorization={authorization}
						source={source}
						onClose={onDidDismiss}
					/>
				)
			) : null}
		</IonModal>
	);
}
