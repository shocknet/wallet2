import { useMemo, useState } from "react";
import { IonButton, IonContent, IonFooter, IonIcon, IonToolbar } from "@ionic/react";
import { closeOutline, shieldCheckmarkOutline } from "ionicons/icons";
import {
	DebitRule,
	DebitRule_rule_type,
	LiveDebitRequest,
	LiveDebitRequest_debit_type,
} from "@/Api/pub/autogenerated/ts/types";
import {
	BanPrompt,
} from "../shared";
import { ClinkRequestIdentityView } from "@/Components/ClinkRequests/ClinkRequestIdentityView";
import { DebitRulesSummary } from "@/Components/Debit/DebitRulesSummary";
import { DebitAuthProps, useDebitActions } from "./useDebitActions";

function rulesForSuggestedAsk(debit: LiveDebitRequest["debit"]): DebitRule[] {
	if (debit.type === LiveDebitRequest_debit_type.FREQUENCY) {
		return [
			{
				rule: {
					type: DebitRule_rule_type.FREQUENCY_RULE,
					frequency_rule: debit.frequency,
				},
			},
		];
	}
	return [];
}


export function SuggestedTermsDebitRequest({
	session,
	dismissWithRole,
}: DebitAuthProps) {
	const { busy, denyOnly, ban, authorize } = useDebitActions(
		session,
		dismissWithRole,
	);
	const [phase, setPhase] = useState<"decision" | "banPrompt">("decision");

	const rules = useMemo(
		() => rulesForSuggestedAsk(session.request.debit),
		[session.request.debit],
	);

	const headline =
		session.request.debit.type === LiveDebitRequest_debit_type.FREQUENCY
			? "Wants a spending budget"
			: "Wants full debit access";

	if (phase === "banPrompt") {
		return (
			<BanPrompt
				busy={busy}
				onBan={ban}
				onDenyOnly={denyOnly}
				onBack={() => setPhase("decision")}
			/>
		);
	}

	return (
		<>
			<IonContent className="ion-padding">
				<div className="flex min-h-full mx-auto w-full max-w-md min-w-0  flex-col items-center justify-center gap-2">
					<ClinkRequestIdentityView
						pubkey={session.request.npub}
						relays={session.source.relays}
					/>

					<div className="flex flex-col items-center gap-4 text-center">
						<p className="m-0 text-sm font-medium tracking-wide text-[var(--ion-color-warning)]">
							{headline}
						</p>

						<div className="rounded-xl border border-[var(--ion-color-warning)]/40 bg-[color-mix(in_srgb,var(--ion-color-warning)_12%,transparent)] px-3.5 py-3">
							<p className="mb-2 text-xs font-medium uppercase tracking-wide text-muted">
								Suggested terms
							</p>
							<DebitRulesSummary
								rules={rules}
								className="flex flex-col gap-1.5 text-base leading-relaxed text-secondary"
							/>
						</div>

						<p className="m-0 max-w-sm text-sm text-muted">
							Allow grants exactly these terms. You can change them later in
							Linked Apps.
						</p>
					</div>
				</div>
			</IonContent>
			<IonFooter>
				<IonToolbar>
					<div className="grid grid-cols-2 gap-3 px-3 pb-3 pt-2">
						<IonButton
							expand="block"
							fill="outline"
							color="medium"
							disabled={busy}
							onClick={() => setPhase("banPrompt")}
						>
							<IonIcon icon={closeOutline} slot="start" />
							Deny
						</IonButton>
						<IonButton
							expand="block"
							disabled={busy}
							onClick={() => authorize(rules, "Debit request authorized")}
						>
							<IonIcon icon={shieldCheckmarkOutline} slot="start" />
							Allow
						</IonButton>
					</div>
				</IonToolbar>
			</IonFooter>
		</>
	)


}


