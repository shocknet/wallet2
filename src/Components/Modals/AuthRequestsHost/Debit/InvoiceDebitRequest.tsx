import { useState } from "react";
import {
	IonButton,
	IonContent,
	IonFooter,
	IonIcon,
	IonToggle,
	IonToolbar,
} from "@ionic/react";
import { chevronForward, shieldCheckmarkOutline } from "ionicons/icons";
import {
	DebitRule,
	DebitRule_rule_type,
} from "@/Api/pub/autogenerated/ts/types";

import { FiatDisplay } from "@/Components/FiatDisplay";
import { decodeInvoice } from "@/lib/invoice";
import { formatSatoshi } from "@/lib/units";
import {
	BanPrompt,
} from "../shared";
import { DebitRulesSummary } from "@/Components/Debit/DebitRulesSummary";
import { DEFAULT_FREQUENCY, defaultExpiresAtUnix, getExpiresAtUnix, getFrequency, upsertExpiry, upsertFrequency, withoutRuleType } from "@/lib/debit/rules";
import { ExpirationRuleEditor } from "@/Components/Debit/ExpirationRuleEditor";
import { FrequencyRuleEditor } from "@/Components/Debit/FrequencyRuleEditor";
import { ClinkRequestIdentityView } from "@/Components/ClinkRequests/ClinkRequestIdentityView";
import { DebitAuthProps, useDebitActions } from "./useDebitActions";

type Phase = "decision" | "grant" | "banPrompt";

const PANEL_CLASS =
	"app-panel bg-[var(--app-surface-muted)]";

interface InvoiceDebitRequestProps extends DebitAuthProps {
	invoice: string;
}

function InvoiceDebitRequest({
	session,
	invoice,
	dismissWithRole,
}: InvoiceDebitRequestProps) {
	const { amount } = decodeInvoice(invoice);
	const { busy, denyOnly, ban, payOnce, authorize } = useDebitActions(
		session,
		dismissWithRole,
	);

	const [phase, setPhase] = useState<Phase>("decision");
	const [grantRules, setGrantRules] = useState<DebitRule[]>([]);

	if (phase === "banPrompt") {
		return (
			<BanPrompt
				busy={busy}
				onBan={ban}
				onDenyOnly={denyOnly}
				onBack={() => setPhase("decision")}
			/>
		);
	}

	if (phase === "grant") {
		return (
			<InvoiceGrantStep
				busy={busy}
				rules={grantRules}
				onChange={setGrantRules}
				onBack={() => setPhase("decision")}
				onConfirm={() =>
					authorize(
						grantRules,
						"Invoice paid & future access granted",
					)
				}
			/>
		);
	}

	return (
		<IonContent className="ion-padding ion-content-no-footer">
			<div className="flex min-h-full flex-col items-center justify-center gap-2">
				<ClinkRequestIdentityView
					pubkey={session.request.npub}
					relays={session.source.relays}
				/>
				<div className="flex flex-col items-center text-center">
					<p className="m-0 text-sm font-medium tracking-wide text-[var(--ion-color-warning)]">
						Wants you to pay an invoice of
					</p>
					<div className="mt-3 flex items-baseline justify-center gap-1.5">
						<span className="text-5xl font-bold tabular-nums tracking-tight text-primary">
							{formatSatoshi(amount)}
						</span>
						<span className="text-sm font-medium text-muted">sats</span>
					</div>
					<FiatDisplay
						className="mt-1.5 m-0 text-sm text-muted"
						sats={amount}
						sign="~"
					/>
				</div>
				<div className="mt-12 flex w-full max-w-sm flex-col gap-1">
					<IonButton
						className="[--border-radius:12px]"
						color="secondary"
						expand="block"
						disabled={busy}
						onClick={payOnce}
					>
						Pay once
					</IonButton>
					<IonButton
						className="[--border-radius:12px]"
						color="medium"
						fill="solid"
						expand="block"
						disabled={busy}
						onClick={() => {
							setGrantRules([]);
							setPhase("grant");
						}}
					>
						Set future access rules
						<IonIcon icon={chevronForward} slot="end" />
					</IonButton>
					<IonButton
						className="[--border-radius:12px]"
						color="dark"
						fill="solid"
						expand="block"
						disabled={busy}
						onClick={() => setPhase("banPrompt")}
					>
						Deny
					</IonButton>
				</div>
			</div>
		</IonContent>
	);
}


function InvoiceGrantStep({
	busy,
	rules,
	onChange,
	onBack,
	onConfirm,
}: {
	busy: boolean;
	rules: DebitRule[];
	onChange: (rules: DebitRule[]) => void;
	onBack: () => void;
	onConfirm: () => void;
}) {
	const frequency = getFrequency(rules);
	const expiresAtUnix = getExpiresAtUnix(rules);
	const isFullAccess = frequency === null && expiresAtUnix === null;
	const confirmLabel = isFullAccess
		? "Pay & grant full access"
		: "Pay & grant";

	return (
		<>
			<IonContent className="ion-padding">
				<div className="mx-auto flex w-full max-w-md min-w-0 flex-col gap-4 pt-6">
					{isFullAccess ? (
						<div className="rounded-xl border border-[var(--ion-color-warning)]/40 bg-[color-mix(in_srgb,var(--ion-color-warning)_12%,transparent)] px-3.5 py-3">
							<p className="block text-sm font-semibold text-[var(--ion-color-warning)]">
								Full access until you revoke
							</p>
							<p className="mt-1 text-sm leading-relaxed text-secondary">
								No spending limit or expiry set. This app can request payments
								within your balance until you remove access.
							</p>
						</div>
					) : (
						<div className="rounded-xl border border-[var(--ion-color-primary)]/40 bg-[color-mix(in_srgb,var(--ion-color-primary)_12%,transparent)] px-3.5 py-3">
							<p className="mb-1 text-xs font-medium uppercase tracking-wide text-muted">
								Current grant
							</p>
							<DebitRulesSummary
								rules={rules}
								className="flex flex-col gap-1 text-sm leading-relaxed text-secondary"
							/>
						</div>
					)}

					<div className="flex flex-col gap-1">
						<p className="m-0 text-xs font-medium uppercase tracking-wide text-muted">
							Add limits (optional)
						</p>
						<p className="m-0 text-xs text-muted">
							Turn these on to restrict what this app can spend later.
						</p>
					</div>

					<section className="flex flex-col gap-3">
						<IonToggle
							checked={frequency !== null}
							onIonChange={(event) => {
								if (event.detail.checked) {
									onChange(upsertFrequency(rules, DEFAULT_FREQUENCY));
									return;
								}
								onChange(
									withoutRuleType(rules, DebitRule_rule_type.FREQUENCY_RULE),
								);
							}}
						>
							Spending limit
						</IonToggle>
						{frequency !== null ? (
							<div className={PANEL_CLASS}>
								<FrequencyRuleEditor
									value={frequency}
									onChange={(next) =>
										onChange(upsertFrequency(rules, next))
									}
								/>
							</div>
						) : null}
					</section>

					<section className="flex flex-col gap-3">
						<IonToggle
							checked={expiresAtUnix !== null}
							onIonChange={(event) => {
								if (event.detail.checked) {
									onChange(upsertExpiry(rules, defaultExpiresAtUnix()));
									return;
								}
								onChange(
									withoutRuleType(rules, DebitRule_rule_type.EXPIRATION_RULE),
								);
							}}
						>
							Expiry
						</IonToggle>
						{expiresAtUnix !== null ? (
							<div className={PANEL_CLASS}>
								<ExpirationRuleEditor
									value={expiresAtUnix}
									onChange={(nextUnix) =>
										onChange(upsertExpiry(rules, nextUnix))
									}
								/>
							</div>
						) : null}
					</section>
				</div>
			</IonContent>
			<IonFooter>
				<IonToolbar>
					<div className="grid grid-cols-2 gap-3 px-4 pb-4 pt-2">
						<IonButton
							expand="block"
							fill="outline"
							color="medium"
							disabled={busy}
							onClick={onBack}
						>
							Cancel
						</IonButton>
						<IonButton
							expand="block"
							color={isFullAccess ? "warning" : "primary"}
							disabled={busy}
							onClick={onConfirm}
						>
							<IonIcon icon={shieldCheckmarkOutline} slot="start" />
							{confirmLabel}
						</IonButton>
					</div>
				</IonToolbar>
			</IonFooter>
		</>
	);
}


export default InvoiceDebitRequest;
