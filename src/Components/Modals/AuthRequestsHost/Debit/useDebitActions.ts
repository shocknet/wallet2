import { PendingClinkDebitSession } from "@/State/clinkRequests/types";
import { DebitDismissRole } from "../types";
import { useAppDispatch } from "@/State/store/hooks";
import { useToast } from "@/lib/contexts/useToast";
import { useCallback, useState } from "react";
import { authorizePendingDebitRequest, banPendingDebitRequest, denyPendingDebitRequest, payInvoicePendingDebitRequest } from "@/State/clinkRequests/thunks";
import { DebitRule } from "@/Api/pub/autogenerated/ts/types";

export type DebitAuthProps = {
	session: PendingClinkDebitSession;
	dismissWithRole: (role: DebitDismissRole) => Promise<void>;
};

type DebitActionResult = { ok: true } | { ok: false; reason: string };

export function useDebitActions(
	session: PendingClinkDebitSession,
	dismissWithRole: (role: DebitDismissRole) => Promise<void>,
) {
	const dispatch = useAppDispatch();
	const { showToast } = useToast();
	const [busy, setBusy] = useState(false);

	const runAction = useCallback(
		async (
			role: DebitDismissRole,
			action: () => Promise<DebitActionResult>,
			options?: { successToast?: string; },
		) => {
			if (busy) {
				return;
			}
			setBusy(true);
			try {
				const result = await action();
				if (!result.ok) {
					showToast({ message: result.reason, color: "danger" });
				} else if (options?.successToast) {
					showToast({ message: options?.successToast, color: "success" });
				}
				await dismissWithRole(role);
			} finally {
				setBusy(false);
			}
		},
		[busy, dismissWithRole, showToast],
	);

	const denyOnly = useCallback(() => {
		void runAction(
			"deny",
			() => dispatch(denyPendingDebitRequest(session)),
			{ successToast: "Debit request denied" },
		);
	}, [dispatch, session, runAction]);

	const ban = useCallback(() => {
		void runAction(
			"ban",
			() => dispatch(banPendingDebitRequest(session)),
			{ successToast: "Requestor banned from issuing future requests" },
		);
	}, [dispatch, session, runAction]);

	const payOnce = useCallback(() => {
		void runAction(
			"allow",
			() => dispatch(payInvoicePendingDebitRequest(session)),
			{ successToast: "Invoice paid" },
		);
	}, [dispatch, session, runAction]);

	const authorize = useCallback(
		(rules: DebitRule[], successToast = "Linked app authorized") => {
			void runAction(
				"allow",
				() =>
					dispatch(
						authorizePendingDebitRequest({
							session,
							rules,
						}),
					),
				{ successToast },
			);
		},
		[dispatch, session, runAction],
	);

	return { busy, denyOnly, ban, payOnce, authorize };
}
