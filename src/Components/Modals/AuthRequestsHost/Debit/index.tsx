import { LiveDebitRequest_debit_type } from "@/Api/pub/autogenerated/ts/types";
import InvoiceDebitRequest from "./InvoiceDebitRequest";
import { SuggestedTermsDebitRequest } from "./SuggestedTermsDebitRequest";

import { IonHeader, IonTitle, IonToolbar } from "@ionic/react";
import { DebitAuthProps } from "./useDebitActions";

function DebitAuthRequest(props: DebitAuthProps) {

	return (
		<>
			<IonHeader>
				<IonToolbar>
					<IonTitle>Incoming Debit Request</IonTitle>
				</IonToolbar>
			</IonHeader>
			{
				props.session.request.debit.type === LiveDebitRequest_debit_type.INVOICE ? (
					<InvoiceDebitRequest {...props} invoice={props.session.request.debit.invoice} />
				) : (
					<SuggestedTermsDebitRequest {...props} />
				)
			}
		</>
	)
}

export default DebitAuthRequest;
