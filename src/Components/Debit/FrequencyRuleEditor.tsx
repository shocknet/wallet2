import { IonInput } from "@ionic/react";
import { FrequencyRule, IntervalType } from "@/Api/pub/autogenerated/ts/types";
import { CustomSelect } from "../CustomSelect";
import { AmountField } from "../AmountField";
import { DEFAULT_FREQUENCY, intervalLabel } from "@/lib/debit/rules";
import { satoshi } from "@/lib/units";

type Props = {
	value: FrequencyRule;
	onChange: (next: FrequencyRule) => void;
};

const INTERVAL_OPTIONS = [
	IntervalType.DAY,
	IntervalType.WEEK,
	IntervalType.MONTH,
] as const;

export function FrequencyRuleEditor({ value, onChange }: Props) {
	const count = value.number_of_intervals;


	return (
		<div className="flex flex-col gap-3">
			<div>
				<p className="mb-2 text-base text-secondary">Spend up to</p>
				<AmountField
					initialSats={satoshi(value.amount)}
					onChange={(next) => onChange({ ...value, amount: next.sats ?? DEFAULT_FREQUENCY.amount })}
					initialUnit="sats"
					placeholder="sats"
					label="Cap amount"
					fill="solid"
					mode="md"
					className="filled-input"
					allowUnitToggle={false}
					showFiat={false}
					labelPlacement="stacked"
				/>
			</div>


			<div>
				<p className="mb-2 text-base text-secondary">Every</p>
				<div className="flex flex-wrap items-stretch gap-2">
					<div className="w-14 shrink-0">
						<IonInput
							mode="md"
							className="filled-input [--padding-start:0] [--padding-end:0] text-center"
							type="number"
							fill="solid"
							inputmode="numeric"
							min={1}
							aria-label="Number of intervals"
							value={count}
							onIonInput={(event) => {
								const raw = event.detail.value ?? "";
								const number_of_intervals =
									raw === "" ? 1 : Math.max(1, Math.floor(+raw));
								if (Number.isNaN(number_of_intervals)) {
									return;
								}
								onChange({ ...value, number_of_intervals });
							}}
						/>
					</div>

					<CustomSelect<IntervalType>
						className="min-w-[6.5rem] flex-1"
						items={INTERVAL_OPTIONS}
						selectedItem={value.interval}
						getIndex={(interval) => interval}
						onSelect={(interval) => {
							onChange({ ...value, interval });
						}}
						renderSelected={(interval) => {
							return <div className="text-sm text-muted">{intervalLabel(interval, count)}</div>;
						}}
						title="Select Interval"
						renderItem={(interval) => {
							return <div className="text-sm text-secondary">{intervalLabel(interval, count)}</div>;
						}}
					/>
				</div>
			</div>
		</div>
	);
}
