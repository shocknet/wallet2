import type { DebitRule } from "@/Api/pub/autogenerated/ts/types";
import { formatDebitRulesSummary, intervalLabel } from "@/lib/debit/rules";
import { nip19 } from "nostr-tools";

export function debitNpub(npubOrHex: string): string {
	try {
		if (npubOrHex.startsWith("npub1")) return npubOrHex;
		return nip19.npubEncode(npubOrHex);
	} catch {
		return npubOrHex;
	}
}

export function resolveDebitAppDisplayName(profile?: {
	display_name?: string;
	name?: string;
} | null): string {
	return profile?.display_name || profile?.name || "Unknown app";
}


export function shortDebitRulesParts(rules: DebitRule[]): string[] {
	const summary = formatDebitRulesSummary(rules);
	const { frequencyRule, expirationRule } = summary;

	if (!frequencyRule && !expirationRule) {
		return ["Unlimited until revoked"];
	}

	const parts: string[] = [];

	if (frequencyRule) {
		const amount = new Intl.NumberFormat("en-US").format(frequencyRule.amount);
		const unit = intervalLabel(
			frequencyRule.interval,
			frequencyRule.numberOfIntervals,
		).toLowerCase();
		const window =
			frequencyRule.numberOfIntervals === 1
				? unit
				: `${frequencyRule.numberOfIntervals} ${unit}`;
		parts.push(`${amount} sats / ${window}`);
	}

	if (expirationRule?.expiresAt) {
		const ms = expirationRule.expiresAt.getTime() - Date.now();
		if (ms <= 0) {
			parts.push("expired");
		} else {
			const days = Math.ceil(ms / (24 * 60 * 60 * 1000));
			parts.push(days <= 1 ? "expires today" : `expires in ${days}d`);
		}
	}

	return parts;
}

// e.g. "10k"
export function debitBudgetLabel(rules: DebitRule[]): string | null {
	const { frequencyRule } = formatDebitRulesSummary(rules);
	if (!frequencyRule) return null;
	return new Intl.NumberFormat("en-US", {
		notation: "compact",
		compactDisplay: "short",
		maximumFractionDigits: 1,
	}).format(frequencyRule.amount);
}
