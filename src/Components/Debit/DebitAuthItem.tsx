import { IonItem } from "@ionic/react";
import type { DebitAuthorization } from "@/Api/pub/autogenerated/ts/types";
import { Avatar } from "@/Components/Avatar";
import {
	debitBudgetLabel,
	debitNpub,
	resolveDebitAppDisplayName,
	shortDebitRulesParts,
} from "@/Components/Debit/debitDisplay";
import { Nip05 } from "@/Components/User/Nip05";
import { NOSTR_RELAYS } from "@/constants";
import { truncateTextMiddle } from "@/lib/format";
import { useGetProfileQuery } from "@/State/api/api";
import cn from "clsx";

export type DebitAuthItemProps = {
	authorization: DebitAuthorization;
	// Relays for kind 0 profile / nip05 lookup (usually the Pub source relays)
	relays?: string[];
	onClick?: () => void;
	className?: string;
};


export function DebitAuthItem({
	authorization,
	relays,
	onClick,
	className,
}: DebitAuthItemProps) {
	const profileRelays = relays?.length ? relays : NOSTR_RELAYS;
	const pubkey = authorization.npub;
	const { data: profile } = useGetProfileQuery({
		pubkey,
		relays: profileRelays,
	});

	const name = resolveDebitAppDisplayName(profile);
	const nip05 = profile?.nip05?.trim() || "";
	const npub = debitNpub(pubkey);
	const budget = debitBudgetLabel(authorization.rules);
	const rulesParts = shortDebitRulesParts(authorization.rules);
	const interactive = typeof onClick === "function";
	const banned = !authorization.authorized;

	return (
		<IonItem
			button={interactive}
			detail={false}
			lines="none"
			onClick={onClick}
			aria-label={`Open debit for ${name}`}
			className={cn(
				"rounded-xl",
				"[--background:var(--app-surface)]",
				"[--border-radius:0.75rem]",
				"[--padding-start:0] [--inner-padding-end:0]",
				"[--min-height:0]",
				"border border-[var(--app-border)]",
				"shadow-[0_6px_18px_-10px_rgba(var(--app-box-shadow-color),0.45)]",
				banned && "opacity-80",
				className,
			)}
		>
			<div className="flex w-full min-w-0 flex-col">
				<div className="flex items-start gap-3 px-3.5 py-3">
					<Avatar id={pubkey} avatarUrl={profile?.picture} size="md" />

					<div className="min-w-0 flex-1">
						<div className="flex min-w-0 items-center gap-2">
							<p className="m-0 min-w-0 truncate text-base font-semibold text-primary">
								{name}
							</p>
							{banned ? (
								<span className="shrink-0 rounded-md bg-[color-mix(in_srgb,var(--ion-color-danger)_14%,transparent)] px-1.5 py-0.5 text-[0.65rem] font-medium uppercase tracking-wide text-[var(--ion-color-danger)]">
									Banned
								</span>
							) : null}
						</div>
						{nip05 ? (
							<div className="mt-1">
								<Nip05
									pubkey={pubkey}
									nip05={nip05}
									className="!max-w-full !px-2 !py-0.5"
								/>
							</div>
						) : (
							<p className="m-0 mt-0.5 font-mono text-[0.7rem] text-faint">
								{truncateTextMiddle(npub, 10, 8, "…")}
							</p>
						)}
					</div>

					<div className="shrink-0 pt-0.5 text-right">
						{budget ? (
							<>
								<p className="m-0 text-base font-semibold tabular-nums text-primary">
									{budget}
								</p>
								<p className="m-0 text-[0.65rem] font-medium uppercase tracking-wide text-faint">
									sats
								</p>
							</>
						) : (
							<>
								<p className="m-0 text-sm font-medium text-muted">∞</p>
								<p className="m-0 text-[0.65rem] font-medium uppercase tracking-wide text-faint">
									open
								</p>
							</>
						)}
					</div>
				</div>

				<div className="border-t border-[color-mix(in_srgb,var(--app-border)_60%,transparent)] px-3.5 py-2">
					<p className="m-0 flex flex-wrap items-center gap-x-2 gap-y-1 text-sm text-muted">
						{rulesParts.map((part, i) => (
							<span key={`${part}-${i}`} className="inline-flex items-center gap-x-2">
								{i > 0 ? (
									<span
										className="inline-block size-1 shrink-0 rounded-full bg-[var(--app-text-secondary)]"
										aria-hidden
									/>
								) : null}
								{part}
							</span>
						))}
					</p>
				</div>
			</div>
		</IonItem>
	);
}
