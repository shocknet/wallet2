import { createApi, fakeBaseQuery } from "@reduxjs/toolkit/query/react";
import type { DebitAuthorization } from "@/Api/pub/autogenerated/ts/types";
import { getNostrClient } from "@/Api/nostr";
import { selectSourceViewById } from "@/State/scoped/backups/sources/selectors";
import type { RootState } from "@/State/store/store";
import {
	fetchProfile,
	normalizeRelays,
	type NostrProfile,
	verifyNip05Claim,
} from "../../lib/profile";
import { requestLnurlServiceParams } from "@/lib/lnurl/get";
import type { LnurlPayServiceResponse } from "@/lib/types/lnurl";

const ONE_HOUR_SECONDS = 60 * 60;

export type AppApiError = {
	message: string;
};

export type AppApiResult<T> = { data: T } | { error: AppApiError };

export function appApiError(message: string): { error: AppApiError } {
	return { error: { message } };
}

export function appApiCaughtError(err: unknown, fallback: string) {
	return appApiError(err instanceof Error ? err.message : fallback);
}

export type GetDebitAuthorizationsArg = {
	sourceId: string;
};

function normalizeLnAddress(address: string): string {
	return address.trim().toLowerCase();
}

export const appApi = createApi({
	reducerPath: "appApi",
	baseQuery: fakeBaseQuery<AppApiError>(),
	tagTypes: [
		"DebitAuthorizations", "Offers", "OfferInvoices",
		"LndInfo", "AppsMetrics", "LndMetrics", "LndForwarding",
		"OpenChannels", "LndPeers", "UsersAdmin", "InvoiceSwaps",
		"TxSwaps", "UserOperations", "AssetsLiabilities",
		"LndUtxos", "AdminNodeSettings",
	],
	endpoints: (b) => ({
		getProfile: b.query<NostrProfile | null, { pubkey: string; relays: string[] }>({
			serializeQueryArgs: ({ queryArgs }) => ({
				pubkey: queryArgs.pubkey,
				relays: normalizeRelays(queryArgs.relays),
			}),
			queryFn: async ({ pubkey, relays }) => {
				try {
					const profile = await fetchProfile(pubkey, relays);
					return { data: profile };
				} catch (e: unknown) {
					return appApiCaughtError(e, "failed");
				}
			},
		}),
		getLnurlPay: b.query<LnurlPayServiceResponse, { address: string }>({
			keepUnusedDataFor: ONE_HOUR_SECONDS,
			serializeQueryArgs: ({ queryArgs }) =>
				normalizeLnAddress(queryArgs.address),
			queryFn: async ({ address }) => {
				const normalized = normalizeLnAddress(address);
				if (!normalized) {
					return appApiError("Missing lightning address");
				}
				try {
					const params = await requestLnurlServiceParams(normalized, true);
					if (params.tag !== "payRequest") {
						return appApiError("Expected LNURL payRequest");
					}
					return { data: params };
				} catch (e: unknown) {
					return appApiCaughtError(e, "Failed to fetch LNURL pay");
				}
			},
		}),
		verifyNip05: b.query<boolean, { pubkey: string; nip05: string }>({
			keepUnusedDataFor: ONE_HOUR_SECONDS,
			queryFn: async ({ pubkey, nip05 }) => {
				try {
					const verification = await verifyNip05Claim(pubkey, nip05);
					return { data: verification };
				} catch (e: unknown) {
					return appApiCaughtError(e, "failed");
				}
			},
		}),
		getDebitAuthorizations: b.query<
			DebitAuthorization[],
			GetDebitAuthorizationsArg
		>({
			providesTags: (_result, _error, { sourceId }) => [
				{ type: "DebitAuthorizations", id: sourceId },
			],
			queryFn: async ({ sourceId }, api) => {
				const state = api.getState() as RootState;
				const source = selectSourceViewById(state, sourceId);
				if (!source) return appApiError("Source is not available");

				try {
					const client = await getNostrClient(
						{ pubkey: source.lpk, relays: source.relays },
						source.keys,
					);
					const res = await client.GetDebitAuthorizations();
					if (res.status !== "OK") {
						return appApiError(
							res.reason || "Could not load debit authorizations",
						);
					}
					return { data: res.debits };
				} catch (e: unknown) {
					return appApiCaughtError(e, "Could not load debit authorizations");
				}
			},
		}),
	}),
});

export const {
	useGetProfileQuery,
	useGetLnurlPayQuery,
	useVerifyNip05Query,
	useGetDebitAuthorizationsQuery,
	useLazyGetDebitAuthorizationsQuery,
} = appApi;
