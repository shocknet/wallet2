import type { OfferConfig, OfferInvoice } from "@/Api/pub/autogenerated/ts/types";
import { selectSourceViewById } from "@/State/scoped/backups/sources/selectors";
import type { RootState } from "@/State/store/store";
import {
	addUserOffer,
	deleteUserOffer,
	getUserOfferInvoices,
	getUserOffers,
	updateUserOffer,
} from "@/lib/noffer";
import { appApi, appApiCaughtError, appApiError } from "./api";

type SourceIdArg = { sourceId: string };

export const offersApi = appApi.injectEndpoints({
	endpoints: (b) => ({
		getOffers: b.query<OfferConfig[], SourceIdArg>({
			providesTags: (_result, _error, { sourceId }) => [
				{ type: "Offers", id: sourceId },
			],
			queryFn: async ({ sourceId }, api) => {
				const source = selectSourceViewById(api.getState() as RootState, sourceId);
				if (!source) return appApiError("Source is not available");
				try {
					const offers = await getUserOffers(
						{ pubkey: source.lpk, relays: source.relays },
						source.keys,
					);
					return { data: offers || [] };
				} catch (err: unknown) {
					return appApiCaughtError(err, "Failed to fetch offers");
				}
			},
		}),
		getOfferInvoices: b.query<
			OfferInvoice[],
			SourceIdArg & { offerId: string }
		>({
			providesTags: (_result, _error, { sourceId, offerId }) => [
				{ type: "OfferInvoices", id: `${sourceId}:${offerId}` },
			],
			queryFn: async ({ sourceId, offerId }, api) => {
				const source = selectSourceViewById(api.getState() as RootState, sourceId);
				if (!source) return appApiError("Source is not available");
				try {
					const invoices = await getUserOfferInvoices(
						{ pubkey: source.lpk, relays: source.relays },
						source.keys,
						offerId,
					);
					return { data: invoices };
				} catch (err: unknown) {
					return appApiCaughtError(err, "Failed to fetch offer invoice");
				}
			},
		}),
		addOffer: b.mutation<{ ok: true }, SourceIdArg & { offer: OfferConfig }>({
			invalidatesTags: (_result, _error, { sourceId }) => [
				{ type: "Offers", id: sourceId },
			],
			queryFn: async ({ sourceId, offer }, api) => {
				const source = selectSourceViewById(api.getState() as RootState, sourceId);
				if (!source) return appApiError("Source is not available");
				try {
					await addUserOffer(
						{ pubkey: source.lpk, relays: source.relays },
						source.keys,
						offer,
					);
					return { data: { ok: true } };
				} catch (err: unknown) {
					return appApiCaughtError(err, "Failed to save offer");
				}
			},
		}),
		updateOffer: b.mutation<{ ok: true }, SourceIdArg & { offer: OfferConfig }>({
			invalidatesTags: (_result, _error, { sourceId, offer }) => [
				{ type: "Offers", id: sourceId },
				{ type: "OfferInvoices", id: `${sourceId}:${offer.offer_id}` },
			],
			queryFn: async ({ sourceId, offer }, api) => {
				const source = selectSourceViewById(api.getState() as RootState, sourceId);
				if (!source) return appApiError("Source is not available");
				try {
					await updateUserOffer(
						{ pubkey: source.lpk, relays: source.relays },
						source.keys,
						offer,
					);
					return { data: { ok: true } };
				} catch (err: unknown) {
					return appApiCaughtError(err, "Failed to save offer");
				}
			},
		}),
		deleteOffer: b.mutation<{ ok: true }, SourceIdArg & { offerId: string }>({
			invalidatesTags: (_result, _error, { sourceId, offerId }) => [
				{ type: "Offers", id: sourceId },
				{ type: "OfferInvoices", id: `${sourceId}:${offerId}` },
			],
			queryFn: async ({ sourceId, offerId }, api) => {
				const source = selectSourceViewById(api.getState() as RootState, sourceId);
				if (!source) return appApiError("Source is not available");
				try {
					await deleteUserOffer(
						{ pubkey: source.lpk, relays: source.relays },
						source.keys,
						offerId,
					);
					return { data: { ok: true } };
				} catch (err: unknown) {
					return appApiCaughtError(err, "Failed to delete offer");
				}
			},
		}),
	}),
});

export const {
	useGetOffersQuery,
	useGetOfferInvoicesQuery,
	useAddOfferMutation,
	useUpdateOfferMutation,
	useDeleteOfferMutation,
} = offersApi;
