import { getNostrClient } from "@/Api/nostr";
import {
	DebitResponse_response_type,
	DebitRule,
	LiveDebitRequest_debit_type,
} from "@/Api/pub/autogenerated/ts/types";
import type { AppThunk } from "@/State/store/store";
import { clinkRequestsActions } from "./slice";
import { PendingClinkDebitSession, PendingClinkManageSession } from "./types";



export type ClinkAuthThunkResult =
	| { ok: true }
	| { ok: false; reason: string };



export const denyPendingDebitRequest =
	(session: PendingClinkDebitSession): AppThunk<Promise<ClinkAuthThunkResult>> =>
		async (dispatch) => {
			try {
				const client = await getNostrClient(
					{ pubkey: session.source.lpk, relays: session.source.relays },
					session.source.keys,
				);
				const res = await client.RespondToDebit({
					npub: session.request.npub,
					request_id: session.request.request_id,
					response: {
						type: DebitResponse_response_type.DENIED,
						denied: {},
					},
				});
				if (res.status !== "OK") {
					return {
						ok: false,
						reason: res.reason || "Could not deny debit request",
					};
				}

				return { ok: true };
			} catch {
				return { ok: false, reason: "Could not deny debit request" };
			} finally {
				dispatch(clinkRequestsActions.removePendingClinkRequest({
					requestId: session.request.request_id,
				}));
			}
		};


export const banPendingDebitRequest =
	(session: PendingClinkDebitSession): AppThunk<Promise<ClinkAuthThunkResult>> =>
		async (dispatch) => {
			try {
				const client = await getNostrClient(
					{ pubkey: session.source.lpk, relays: session.source.relays },
					session.source.keys,
				);
				const denyRes = await client.RespondToDebit({
					npub: session.request.npub,
					request_id: session.request.request_id,
					response: {
						type: DebitResponse_response_type.DENIED,
						denied: {},
					},
				});
				if (denyRes.status !== "OK") {
					return {
						ok: false,
						reason: denyRes.reason || "Could not deny debit request",
					};
				}
				const banRes = await client.BanDebit({ npub: session.request.npub });
				if (banRes.status !== "OK") {
					return {
						ok: false,
						reason: banRes.reason || "Could not ban this app",
					};
				}
				return { ok: true };
			} catch {
				return { ok: false, reason: "Could not deny or ban debit request" };
			} finally {
				dispatch(clinkRequestsActions.removePendingClinkRequest({
					requestId: session.request.request_id,
				}));
			}
		};

// Pay this invoice once (no lasting grant), then clear from queue
export const payInvoicePendingDebitRequest =
	(session: PendingClinkDebitSession): AppThunk<Promise<ClinkAuthThunkResult>> =>
		async (dispatch) => {
			if (session.request.debit.type !== LiveDebitRequest_debit_type.INVOICE) {
				return { ok: false, reason: "Request is not an invoice debit" };
			}

			try {
				const client = await getNostrClient(
					{ pubkey: session.source.lpk, relays: session.source.relays },
					session.source.keys,
				);
				const res = await client.RespondToDebit({
					npub: session.request.npub,
					request_id: session.request.request_id,
					response: {
						type: DebitResponse_response_type.INVOICE,
						invoice: session.request.debit.invoice,
					},
				});

				if (res.status !== "OK") {
					return {
						ok: false,
						reason: res.reason || "Could not pay invoice debit request",
					};
				}
				return { ok: true };
			} catch {
				return { ok: false, reason: "Could not pay invoice debit request" };
			} finally {
				dispatch(clinkRequestsActions.removePendingClinkRequest({
					requestId: session.request.request_id,
				}));
			}
		};

// Authorize with rules (± invoice), then clear from queue
export const authorizePendingDebitRequest =
	(args: {
		session: PendingClinkDebitSession;
		rules: DebitRule[];
	}): AppThunk<Promise<ClinkAuthThunkResult>> =>
		async (dispatch) => {
			const { session, rules } = args;

			const invoice =
				session.request.debit.type === LiveDebitRequest_debit_type.INVOICE
					? session.request.debit.invoice
					: undefined;


			try {
				const client = await getNostrClient(
					{ pubkey: session.source.lpk, relays: session.source.relays },
					session.source.keys,
				);
				const res = await client.RespondToDebit({
					npub: session.request.npub,
					request_id: session.request.request_id,
					response: {
						type: DebitResponse_response_type.AUTHORIZE,
						authorize: {
							rules,
							invoice,
						},
					},
				});

				if (res.status !== "OK") {
					return {
						ok: false,
						reason: res.reason || "Could not authorize debit request",
					};
				}
				return { ok: true };
			} catch {
				return { ok: false, reason: "Could not authorize debit request" };
			} finally {
				dispatch(clinkRequestsActions.removePendingClinkRequest({
					requestId: session.request.request_id,
				}));
			}
		};


export const banPendingManageRequest =
	(session: PendingClinkManageSession): AppThunk<Promise<ClinkAuthThunkResult>> =>
		async (dispatch) => {
			try {
				const res = await (
					await getNostrClient(
						{ pubkey: session.source.lpk, relays: session.source.relays },
						session.source.keys,
					)
				).AuthorizeManage({
					authorize_npub: session.request.npub,
					request_id: session.request.request_id,
					ban: true,
				});

				if (res.status !== "OK") {
					return {
						ok: false,
						reason: res.reason || "Could not ban this app",
					};
				}

				return { ok: true };
			} catch {
				return { ok: false, reason: "Could not ban this app" };
			} finally {
				dispatch(clinkRequestsActions.removePendingClinkRequest({
					requestId: session.request.request_id,
				}));
			}
		};

