import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { createDeferred } from "@/lib/deferred";
import { LiveDebitRequest_debit_type } from "@/Api/pub/autogenerated/ts/types";
import { identityUnloaded } from "@/State/listeners/actions";
import { identitiesRegistryActions } from "@/State/identitiesRegistry/slice";
import { sourcesActions } from "@/State/scoped/backups/sources/slice";
import { TEST_CLOCK_BY, TEST_IDENTITY_PUBKEY, TEST_RUNTIME_IDENTITY } from "@tests/support/identityFixtures";
import { createTestSources, type TestSource } from "@tests/support/sourcesHelpers";
import { makeListenerStore } from "@tests/support/listenerStore";
import { clinkRequestsActions } from "./slice";
import type { PendingClinkDebitRequest, PendingClinkManageRequest, PendingClinkRequest } from "./types";
import {
	pendingClinkRequestsListenerSpec,
	RECONCILE_DELAY_MS,
} from "./clinkRequestsListener";

const NOW_MS = 1_000_000;
const OTHER_IDENTITY = "other-identity-pubkey";

type ClinkStore = ReturnType<typeof openClinkStore>;

function openClinkStore(opts: {
	sources?: TestSource[];
	loadIdentity?: boolean;
} = {}) {
	const loadIdentity = opts.loadIdentity ?? true;
	const { store } = makeListenerStore({
		specs: [pendingClinkRequestsListenerSpec],
		sources: opts.sources,
		loadIdentity: false,
	});
	if (loadIdentity) {
		store.dispatch(identitiesRegistryActions.setActiveIdentityRuntime({
			identity: TEST_RUNTIME_IDENTITY,
		}));
	}
	return store;
}

function debitPending(
	source: TestSource,
	over: Partial<PendingClinkDebitRequest> & { requestId?: string } = {},
): PendingClinkRequest {
	const { requestId = "debit-1", ...rest } = over;
	return {
		kind: "debit",
		identityId: TEST_IDENTITY_PUBKEY,
		sourceId: source.id,
		enqueuedAtMs: NOW_MS,
		request: {
			npub: "npub-app",
			request_id: requestId,
			debit: {
				type: LiveDebitRequest_debit_type.INVOICE,
				invoice: "lnbc1test",
			},
		},
		...rest,
	};
}

function managePending(
	source: TestSource,
	over: Partial<PendingClinkManageRequest> & { requestId?: string } = {},
): PendingClinkRequest {
	const { requestId = "manage-1", ...rest } = over;
	return {
		kind: "manage",
		identityId: TEST_IDENTITY_PUBKEY,
		sourceId: source.id,
		enqueuedAtMs: NOW_MS,
		request: {
			npub: "npub-app",
			request_id: requestId,
		},
		...rest,
	};
}

function enqueue(store: ClinkStore, request: PendingClinkRequest) {
	store.dispatch(clinkRequestsActions.enqueuePendingClinkRequest(request));
}

function session(store: ClinkStore) {
	return store.getState().clinkRequests.pendingClinkRequestSession;
}

function queue(store: ClinkStore) {
	return store.getState().clinkRequests.pendingClinkRequests;
}

async function settle() {
	await vi.runAllTimersAsync();
}

describe("pending clink requests listener", () => {
	beforeEach(() => {
		vi.useFakeTimers();
		vi.setSystemTime(NOW_MS);
	});

	afterEach(() => {
		vi.useRealTimers();
	});

	describe("kick", () => {
		it("claims a queued debit for a live source after identity load", async () => {
			const [source] = createTestSources(1);
			const store = openClinkStore({ sources: [source], loadIdentity: false });
			enqueue(store, debitPending(source));

			expect(session(store)).toBeNull();

			store.dispatch(identitiesRegistryActions.setActiveIdentityRuntime({
				identity: TEST_RUNTIME_IDENTITY,
			}));
			await settle();

			expect(session(store)).toMatchObject({
				kind: "debit",
				request: { request_id: "debit-1" },
				source: { sourceId: source.id },
			});
			expect(queue(store)).toHaveLength(1);
		});

		it("prefers a debit over a manage when both are queued", async () => {
			const [source] = createTestSources(1);
			const store = openClinkStore({ sources: [source], loadIdentity: false });
			enqueue(store, managePending(source));
			enqueue(store, debitPending(source));

			store.dispatch(identitiesRegistryActions.setActiveIdentityRuntime({
				identity: TEST_RUNTIME_IDENTITY,
			}));
			await settle();

			expect(session(store)?.kind).toBe("debit");
			expect(session(store)?.request.request_id).toBe("debit-1");
		});

		it("claims a manage when no debit is available", async () => {
			const [source] = createTestSources(1);
			const store = openClinkStore({ sources: [source], loadIdentity: false });
			enqueue(store, managePending(source));

			store.dispatch(identitiesRegistryActions.setActiveIdentityRuntime({
				identity: TEST_RUNTIME_IDENTITY,
			}));
			await settle();

			expect(session(store)).toMatchObject({
				kind: "manage",
				request: { request_id: "manage-1" },
				source: { sourceId: source.id },
			});
		});

		it("prunes a request whose source is gone and does not claim it", async () => {
			const [source] = createTestSources(1);
			const store = openClinkStore({ loadIdentity: false });
			enqueue(store, debitPending(source));

			store.dispatch(identitiesRegistryActions.setActiveIdentityRuntime({
				identity: TEST_RUNTIME_IDENTITY,
			}));
			await settle();

			expect(session(store)).toBeNull();
			expect(queue(store)).toEqual([]);
		});

		it("ignores a request for another identity", async () => {
			const [source] = createTestSources(1);
			const store = openClinkStore({ sources: [source], loadIdentity: false });
			enqueue(store, debitPending(source, { identityId: OTHER_IDENTITY }));

			store.dispatch(identitiesRegistryActions.setActiveIdentityRuntime({
				identity: TEST_RUNTIME_IDENTITY,
			}));
			await settle();

			expect(session(store)).toBeNull();
			expect(queue(store)).toHaveLength(1);
		});
	});

	describe("enqueue", () => {
		it("does not claim until the reconcile delay elapses", async () => {
			const [source] = createTestSources(1);
			const store = openClinkStore({ sources: [source] });
			await settle();

			enqueue(store, debitPending(source));
			await vi.advanceTimersByTimeAsync(RECONCILE_DELAY_MS - 1);
			expect(session(store)).toBeNull();

			await vi.advanceTimersByTimeAsync(1);
			expect(session(store)?.request.request_id).toBe("debit-1");
		});

		it("restarts the delay when another request is enqueued", async () => {
			const [source] = createTestSources(1);
			const store = openClinkStore({ sources: [source] });
			await settle();

			enqueue(store, debitPending(source, { requestId: "debit-1" }));
			await vi.advanceTimersByTimeAsync(RECONCILE_DELAY_MS / 2);
			enqueue(store, debitPending(source, { requestId: "debit-2" }));
			await vi.advanceTimersByTimeAsync(RECONCILE_DELAY_MS / 2);
			expect(session(store)).toBeNull();

			await vi.advanceTimersByTimeAsync(RECONCILE_DELAY_MS / 2);
			expect(session(store)?.request.request_id).toBe("debit-1");
			expect(queue(store)).toHaveLength(2);
		});

		it("does not replace an existing session", async () => {
			const [source] = createTestSources(1);
			const store = openClinkStore({ sources: [source] });
			enqueue(store, debitPending(source, { requestId: "debit-1" }));
			await settle();
			expect(session(store)?.request.request_id).toBe("debit-1");

			enqueue(store, debitPending(source, { requestId: "debit-2" }));
			await settle();

			expect(session(store)?.request.request_id).toBe("debit-1");
		});

		it("does not listen until the runtime identity is set", async () => {
			const [source] = createTestSources(1);
			const store = openClinkStore({ sources: [source], loadIdentity: false });

			enqueue(store, debitPending(source));
			await settle();

			expect(session(store)).toBeNull();
			expect(queue(store)).toHaveLength(1);
		});
	});

	describe("session clear", () => {
		it("claims the same request again if it is still queued", async () => {
			const [source] = createTestSources(1);
			const store = openClinkStore({ sources: [source] });
			enqueue(store, debitPending(source));
			await settle();

			store.dispatch(clinkRequestsActions.clearPendingClinkRequestSession());
			expect(session(store)).toBeNull();
			await settle();

			expect(session(store)?.request.request_id).toBe("debit-1");
		});

		it("claims the next request after the current one is removed", async () => {
			const [source] = createTestSources(1);
			const store = openClinkStore({ sources: [source] });
			enqueue(store, debitPending(source, { requestId: "debit-1" }));
			enqueue(store, debitPending(source, { requestId: "debit-2" }));
			await settle();
			expect(session(store)?.request.request_id).toBe("debit-1");

			store.dispatch(clinkRequestsActions.removePendingClinkRequest({ requestId: "debit-1" }));
			store.dispatch(clinkRequestsActions.clearPendingClinkRequestSession());
			await settle();

			expect(session(store)?.request.request_id).toBe("debit-2");
			expect(queue(store).map(r => r.request.request_id)).toEqual(["debit-2"]);
		});
	});

	describe("source deletion", () => {
		it("drops requests for a deleted source and claims the next live one", async () => {
			const [keep, drop] = createTestSources(2);
			const store = openClinkStore({ sources: [keep, drop] });
			enqueue(store, debitPending(drop, { requestId: "drop-debit" }));
			enqueue(store, debitPending(keep, { requestId: "keep-debit" }));
			await settle();
			expect(session(store)?.request.request_id).toBe("drop-debit");

			store.dispatch(sourcesActions.markDeleted({
				sourceId: drop.id,
				by: TEST_CLOCK_BY,
			}));
			await settle();

			expect(queue(store).map(r => r.request.request_id)).toEqual(["keep-debit"]);
			expect(session(store)).toMatchObject({
				kind: "debit",
				request: { request_id: "keep-debit" },
				source: { sourceId: keep.id },
			});
		});
	});

	describe("unload", () => {
		it("clears the session and leaves the queue", async () => {
			const [source] = createTestSources(1);
			const store = openClinkStore({ sources: [source] });
			enqueue(store, debitPending(source));
			await settle();
			expect(session(store)).not.toBeNull();

			const unloaded = createDeferred<void>();
			store.dispatch(identityUnloaded({ deferred: unloaded }));
			await unloaded;

			expect(session(store)).toBeNull();
			expect(queue(store)).toHaveLength(1);
		});

		it("claims again after a later identity load", async () => {
			const [source] = createTestSources(1);
			const store = openClinkStore({ sources: [source] });
			enqueue(store, debitPending(source));
			await settle();

			const unloaded = createDeferred<void>();
			store.dispatch(identityUnloaded({ deferred: unloaded }));
			await unloaded;

			store.dispatch(identitiesRegistryActions.setActiveIdentityRuntime({
				identity: TEST_RUNTIME_IDENTITY,
			}));
			await settle();

			expect(session(store)?.request.request_id).toBe("debit-1");
		});
	});
});
