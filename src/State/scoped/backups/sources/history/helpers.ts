export const makeKey = (sourceId: string, operationId: string): OpKey =>
	`${sourceId}/${operationId}`;

export const breakKey = (key: string) => {

	const [sourceId, operationId] = key.split("/");
	return [sourceId, operationId];
}

export const emptyCursor = (): HistoryCursor => ({
	latestIncomingInvoice: { ts: 0, id: 0 },
	latestIncomingTx: { ts: 0, id: 0 },
	latestIncomingUserToUserPayment: { ts: 0, id: 0 },
	latestOutgoingInvoice: { ts: 0, id: 0 },
	latestOutgoingTx: { ts: 0, id: 0 },
	latestOutgoingUserToUserPayment: { ts: 0, id: 0 },
	max_size: 10
})


export function ensureHistoryIndex(state: SourcesState, sourceId: string) {
	return (state.history.bySource[sourceId] ??= { ids: [], cursor: emptyCursor() })
}

export function sortSourceHistory(state: SourcesState, sourceId: string) {
	const idx = ensureHistoryIndex(state, sourceId);
	idx.ids.sort((ka, kb) => {
		const a = state.history.ops.entities[ka]!;
		const b = state.history.ops.entities[kb]!;
		return b.paidAtUnix - a.paidAtUnix;
	});
}

function dropHistoryOp(state: SourcesState, sourceId: string, key: string) {
	if (!state.history.ops.entities[key]) return;
	opsAdapter.removeOne(state.history.ops, key);
	const idx = ensureHistoryIndex(state, sourceId);
	const pos = idx.ids.indexOf(key);
	if (pos !== -1) idx.ids.splice(pos, 1);
}

function outgoingInvoiceOptimisticKey(sourceId: string, operation: UserOperation) {
	if (operation.type !== UserOperationType.OUTGOING_INVOICE) return null;
	if (!operation.identifier) return null;
	return makeKey(sourceId, operation.identifier);
}

/** True if this ingest should bump newPaymentsCount. */
export function upsertUserOperation(
	state: SourcesState,
	sourceId: string,
	operation: UserOperation,
	notify: boolean,
): boolean {
	const optimisticKey = outgoingInvoiceOptimisticKey(sourceId, operation);
	const candidate = optimisticKey
		? state.history.ops.entities[optimisticKey]
		: undefined;
	const optimisticRow = candidate?.optimistic ? candidate : undefined;
	const opKey = makeKey(sourceId, operation.operationId);

	if (operation.paidAtUnix < 0) {
		if (optimisticRow) dropHistoryOp(state, sourceId, optimisticRow.opKey);
		dropHistoryOp(state, sourceId, opKey);
		return false;
	}

	const existingAtPub = state.history.ops.entities[opKey];
	const local = optimisticRow ?? existingAtPub;
	const sourceOperation = userOperationToSourceOperation(
		operation,
		sourceId,
		local,
		notify,
	);

	if (optimisticRow && optimisticRow.opKey !== opKey) {
		dropHistoryOp(state, sourceId, optimisticRow.opKey);
	}

	const idx = ensureHistoryIndex(state, sourceId);
	const hadPub = !!state.history.ops.entities[opKey];
	opsAdapter.upsertOne(state.history.ops, sourceOperation);
	if (!idx.ids.includes(opKey)) idx.ids.push(opKey);

	return !hadPub && !optimisticRow;
}

export function isInFlightOutgoingInvoice(
	op: SourceOperation,
): op is Extract<SourceOperation, { type: "INVOICE"; inbound: false }> {
	if (op.type !== "INVOICE" || op.inbound) return false;
	return !!op.optimistic || op.paidAtUnix === 0;
}

export function addOptimisticOperation(
	state: SourcesState,
	sourceId: string,
	operation: SourceOptimsticOperation,
) {
	const key = operation.opKey;
	if (state.history.ops.entities[key]) return;

	if (operation.type === "INVOICE") {
		const idx = state.history.bySource[sourceId];
		if (idx) {
			for (const id of idx.ids) {
				const existing = state.history.ops.entities[id];
				if (
					existing &&
					!existing.optimistic &&
					existing.type === "INVOICE" &&
					existing.invoice === operation.invoice
				) {
					return;
				}
			}
		}
	}

	const idx = ensureHistoryIndex(state, sourceId);
	opsAdapter.addOne(state.history.ops, operation);
	idx.ids.push(key);
}

export function removeOptimisticOperation(
	state: SourcesState,
	sourceId: string,
	operationId: string,
) {
	const key = makeKey(sourceId, operationId);
	const existing = state.history.ops.entities[key];
	if (!existing?.optimistic) return;
	dropHistoryOp(state, sourceId, key);
}

// Helper function to convert a UserOperation to a SourceOperation
export const userOperationToSourceOperation = (op: UserOperation, sourceId: string, local?: SourceOperation, notify = false): SourceActualOperation => {
	const incoming = transformUserOperationToSourceOperation(op, sourceId);


	if (local === undefined) {
		if (notify && incoming.inbound) {
			import("@/notifications/local/display")
				.then(({ notifyReceivedOperation }) => notifyReceivedOperation(incoming.amount, incoming.operationId, incoming.type === "ON-CHAIN").catch(() => {/* no-op */ }))
				.catch(err => console.error("Failed to lazy-load local notification display", err));
		}
		return incoming;
	}

	// Operations may have data that is truly local, like the local memo and the lnurl the
	// invoice was generated from in case of invoice operations. This function makes sure we merge
	// the incoming operation (UserOperation from pub) with the local one, so we don"t lose that data.
	const operation: SourceActualOperation = {
		...incoming,
		memo: local.memo, // preserve local memo
		...((incoming.type === "INVOICE" && local.type === "INVOICE") ? { // preserve local invoice data
			invoiceMemo: local.invoiceMemo,
			invoiceSource: local.invoiceSource,
		} : {}),
	}
	return operation;
}

export const payInvoiceReponseToUserOperation = (
	resp: Omit<PayInvoiceResponse, "latest_balance">,
	optimisticOperation: SourceOptimsiticInvoice,
): UserOperation => {
	const userOperation: UserOperation = {
		operationId: resp.operation_id,
		type: UserOperationType.OUTGOING_INVOICE,
		identifier: optimisticOperation.invoice,
		amount: resp.amount_paid as Satoshi,
		paidAtUnix: Math.floor(Date.now() / 1000),
		service_fee: resp.service_fee,
		network_fee: resp.network_fee,
		inbound: false,
		...(resp.preimage === ""
			? { internal: true }
			: {
				internal: false,
			}
		),
		confirmed: true,
		tx_hash: ""
	}
	return userOperation;
}

export function getPaymentStateResponseToUserOperation(
	resp: PaymentState,
	invoice: string,
): UserOperation {
	return {
		operationId: resp.operation_id,
		type: UserOperationType.OUTGOING_INVOICE,
		identifier: invoice,
		amount: resp.amount,
		paidAtUnix: resp.paid_at_unix,
		service_fee: resp.service_fee,
		network_fee: resp.network_fee,
		inbound: false,
		...(resp.internal
			? { internal: true }
			: {
				internal: false,
			}
		),
		confirmed: true,
		tx_hash: "",
	};
}


const transformUserOperationToSourceOperation = (op: UserOperation, sourceId: string): SourceActualOperation => {
	const base: SourceOperationBase = {
		opKey: makeKey(sourceId, op.operationId),
		amount: op.amount as Satoshi,
		operationId: op.operationId,
		sourceId,
		paidAtUnix: op.paidAtUnix * 1000,
	}
	switch (op.type) {
		case UserOperationType.INCOMING_INVOICE:
		case UserOperationType.OUTGOING_INVOICE:
			return {
				...base,
				type: "INVOICE",
				invoice: op.identifier,
				inbound: op.type === UserOperationType.INCOMING_INVOICE,
				invoiceMemo: decodeInvoice(op.identifier)?.description,
				serviceFee: op.service_fee,

				...(op.internal
					? { internal: true }
					: {
						internal: false,
						networkFee: op.network_fee
					})
			}
		case UserOperationType.INCOMING_TX:
		case UserOperationType.OUTGOING_TX:
			return {
				...base,
				type: "ON-CHAIN",
				address: op.identifier,
				inbound: op.type === UserOperationType.INCOMING_TX,
				serviceFee: op.service_fee,
				...(op.internal
					? { internal: true }
					: {
						internal: false,
						networkFee: op.network_fee,
						txHash: op.tx_hash
					})
			}
		case UserOperationType.INCOMING_USER_TO_USER:
		case UserOperationType.OUTGOING_USER_TO_USER:
			return {
				...base,
				type: "USER_TO_USER",
				inbound: op.type === UserOperationType.INCOMING_USER_TO_USER,
				serviceFee: op.service_fee,
			}
		default:
			throw new Error("Unknown operation type" + op.type)
	}
};





/* Pub source history fetching helpers for cursor management */
export const isAnyArrayLong = (arrays: any[][], max: number): boolean => {
	for (let i = 0; i < arrays.length; i++) {
		const array = arrays[i];
		if (array.length >= max) {
			return true
		}
	}
	return false
}

export const parseOperationsResponse = (r: GetUserOperationsResponse, c: HistoryCursor) => {
	const newCursor: HistoryCursor = {
		latestIncomingInvoice: { ts: r.latestIncomingInvoiceOperations.toIndex.ts || c.latestIncomingInvoice.ts, id: r.latestIncomingInvoiceOperations.toIndex.id || c.latestIncomingInvoice.id },
		latestOutgoingInvoice: { ts: r.latestOutgoingInvoiceOperations.toIndex.ts || c.latestOutgoingInvoice.ts, id: r.latestOutgoingInvoiceOperations.toIndex.id || c.latestOutgoingInvoice.id },
		latestIncomingTx: { ts: r.latestIncomingTxOperations.toIndex.ts || c.latestIncomingTx.ts, id: r.latestIncomingTxOperations.toIndex.id || c.latestIncomingTx.id },
		latestOutgoingTx: { ts: r.latestOutgoingTxOperations.toIndex.ts || c.latestOutgoingTx.ts, id: r.latestOutgoingTxOperations.toIndex.id || c.latestOutgoingTx.id },
		latestIncomingUserToUserPayment: { ts: r.latestIncomingUserToUserPayemnts.toIndex.ts || c.latestIncomingUserToUserPayment.ts, id: r.latestIncomingUserToUserPayemnts.toIndex.id || c.latestIncomingUserToUserPayment.id },
		latestOutgoingUserToUserPayment: { ts: r.latestOutgoingUserToUserPayemnts.toIndex.ts || c.latestOutgoingUserToUserPayment.ts, id: r.latestOutgoingUserToUserPayemnts.toIndex.id || c.latestOutgoingUserToUserPayment.id },
		max_size: 10
	}

	const operations = [
		...r.latestIncomingInvoiceOperations.operations,
		...r.latestOutgoingInvoiceOperations.operations,
		...r.latestIncomingTxOperations.operations,
		...r.latestOutgoingTxOperations.operations,
		...r.latestIncomingUserToUserPayemnts.operations,
		...r.latestOutgoingUserToUserPayemnts.operations,
	]

	const needMoreData = isAnyArrayLong([
		r.latestIncomingInvoiceOperations.operations,
		r.latestOutgoingInvoiceOperations.operations,
		r.latestIncomingTxOperations.operations,
		r.latestOutgoingTxOperations.operations,
		r.latestIncomingUserToUserPayemnts.operations,
		r.latestOutgoingUserToUserPayemnts.operations,
	], 10)

	return { newCursor, operations, needMoreData }
}
