const presentRelayUrls = (relays?: Record<string, { present: boolean }>) =>
	relays ? Object.keys(relays).filter(url => relays[url]?.present) : [];

const sourceRelays = (relays?: SourceDocV0["relays"]) =>
	canonicalRelayUrls(presentRelayUrls(relays));

const isDeleted = (d: SourceDocV0) => Boolean(d.deleted.value);


export const selectLiveSourceIds = createSelector(
	[docsSelectors.selectAll],
	entities =>
		entities
			.filter(entity => !isDeleted(entity.draft))
			.map(entity => entity.draft.source_id),
	{
		memoizeOptions: {
			resultEqualityCheck: sameArray,
		},
	},
);


export const selectAdminSourceIds = createSelector(
	[docsSelectors.selectAll],
	entities =>
		entities
			.filter(entity => !isDeleted(entity.draft) && entity.draft.admin_token.value)
			.map(entity => entity.draft.source_id),
	{
		memoizeOptions: {
			resultEqualityCheck: sameArray,
		},
	},
);



export type SourceView = {
	sourceId: string;
	label: string | null;
	relays: string[];
	beaconStale: BeaconHealth;
	beaconLastSeenAtMs: number;
	beaconName?: string;
	beaconAvatarUrl?: string;
	beaconFees?: CumulativeFees;
	beaconNextRelay?: string;
	balanceSats: Satoshi;
	maxWithdrawableSats: Satoshi;
	lpk: string;
	topicId?: string;
	keys: NostrKeyPair;
	bridgeUrl: string | null;
	isNDebitDiscoverable: boolean;
	adminToken: string | null;
	vanityName?: string;
	ndebit?: string;
	noffer?: string;
	nmanage?: string;
};


const createSourceView = (
	d: SourceDocV0,
	m: SourceMetadata,
	relays: string[],
	beacon: SourceBeaconJoin,
): SourceView => ({
	sourceId: d.source_id,
	label: d.label.value,
	relays,
	lpk: d.lpk,
	topicId: m.topicId,
	keys: d.keys,
	balanceSats: m.balance,
	maxWithdrawableSats: m.maxWithdrable,
	isNDebitDiscoverable: d.is_ndebit_discoverable.value,
	ndebit: m.ndebit,
	noffer: m.noffer,
	nmanage: m.nmanage,
	vanityName: m.vanityName,
	bridgeUrl: d.bridgeUrl.value,
	beaconStale: beacon.health,
	beaconLastSeenAtMs: beacon.lastSeenAtMs,
	beaconName: beacon.name,
	beaconAvatarUrl: beacon.avatarUrl,
	beaconFees: beacon.fees,
	beaconNextRelay: beacon.nextRelay,
	adminToken: d.admin_token.value,
});



const selectLiveDraft = (state: RootState, sourceId: string) => {
	const entity = docsSelectors.selectById(state, sourceId);
	if (!entity || isDeleted(entity.draft)) return undefined;
	return entity.draft;
};

export const makeSelectSourceViewById = () => {
	const selectBeaconJoin = makeSelectSourceBeaconJoin();

	const selectBeaconForSource = (state: RootState, sourceId: string) => {
		const draft = selectLiveDraft(state, sourceId);
		if (!draft) return undefined;
		return selectBeaconJoin(state, draft.lpk, sourceRelays(draft.relays));
	};

	return createSelector(
		[
			selectLiveDraft,
			metadataSelectors.selectById,
			selectBeaconForSource,
		],
		(draft, metadata, beacon): SourceView | null => {
			if (!draft) return null;

			if (!metadata) {
				throw new Error(`No metadata for source ${draft.source_id}`);
			}

			if (!beacon) {
				throw new Error(`No beacon join for source ${draft.source_id}`);
			}

			return createSourceView(draft, metadata, sourceRelays(draft.relays), beacon);
		},
	);
};


/*
 * Shared instance for ordinary selector composition / imperative access.
 */
export const selectSourceViewById = makeSelectSourceViewById();





export const selectTotalBalance = createSelector(
	[
		metadataSelectors.selectEntities,
		selectLiveSourceIds,
	],
	(metadata, liveIds) => {
		let total = 0;

		for (const sourceId of liveIds) {
			const meta = metadata[sourceId];
			if (meta) total += meta.balance;
		}

		return total as Satoshi;
	},
);

export const selectResolvedSourceId = createSelector(
	[
		selectLiveSourceIds,
		selectFavoriteSourceId,
		(_state: RootState, overrideSourceId: string | null) => overrideSourceId,
	],
	(sourceIds, favoriteSourceId, overrideSourceId): string => {
		if (overrideSourceId && sourceIds.includes(overrideSourceId)) {
			return overrideSourceId;
		}

		if (favoriteSourceId && sourceIds.includes(favoriteSourceId)) {
			return favoriteSourceId;
		}


		return sourceIds[0];
	},
);


// With several admin nodes the user must pick one; the favorite is only a pre-selection.
export const selectResolvedAdminSourceId = createSelector(
	[
		selectAdminSourceIds,
		(_state: RootState, overrideSourceId: string | null) => overrideSourceId,
	],
	(adminIds, overrideSourceId): string | null => {
		if (overrideSourceId && adminIds.includes(overrideSourceId)) {
			return overrideSourceId;
		}

		if (adminIds.length === 1) return adminIds[0];

		return null;
	},
);


export type LiveSourceBalance = {
	sourceId: string;
	balanceSats: Satoshi;
	maxWithdrawableSats: Satoshi;
};

const sameBalances = (
	a: LiveSourceBalance[],
	b: LiveSourceBalance[],
) =>
	a.length === b.length &&
	a.every((item, i) =>
		item.sourceId === b[i].sourceId &&
		item.balanceSats === b[i].balanceSats &&
		item.maxWithdrawableSats === b[i].maxWithdrawableSats,
	);

/*
 * Balances only
 */
export const selectLiveSourceBalances = createSelector(
	[selectLiveSourceIds, metadataSelectors.selectEntities],
	(ids, metadata): LiveSourceBalance[] =>
		ids.map(id => {
			const meta = metadata[id];
			return {
				sourceId: id,
				balanceSats: meta?.balance ?? (0 as Satoshi),
				maxWithdrawableSats: meta?.maxWithdrable ?? (0 as Satoshi),
			};
		}),
	{
		memoizeOptions: {
			resultEqualityCheck: sameBalances,
		},
	},
);


export const selectLiveSourceIdsByLpk = createSelector(
	[
		selectLiveSourceIds,
		docsSelectors.selectEntities,
		(_state: RootState, lpk: string) => lpk,
	],
	(ids, docs, lpk) =>
		ids.filter(id => docs[id]?.draft.lpk === lpk),
	{
		memoizeOptions: {
			resultEqualityCheck: sameArray,
		},
	},
);


export const selectExistingAdminTokenByLpk = createSelector(
	[selectLiveSourceIdsByLpk, docsSelectors.selectEntities],
	(ids, docs): string | null => {
		for (const id of ids) {
			const token = docs[id]?.draft.admin_token.value;
			if (token) return token;
		}
		return null;
	},
);


export const selectAllLiveSourcesDown = createSelector(
	[
		selectLiveSourceIds,
		docsSelectors.selectEntities,
		beaconRelayNodesSelectors.selectEntities,
	],
	(ids, docs, nodes): boolean => {
		if (ids.length === 0) return false;
		for (const id of ids) {
			const draft = docs[id].draft;
			const relays = sourceRelays(draft.relays);
			const health = joinBeaconNodes(
				relays.map(relay => nodes[beaconRelayNodeKey(draft.lpk, relay)]),
			).health;
			if (health !== "stale") return false;
		}
		return true;
	},
);



export function readLiveSourceViews(state: RootState): SourceView[] {
	const views: SourceView[] = [];
	for (const id of selectLiveSourceIds(state)) {
		const view = selectSourceViewById(state, id);
		if (view) views.push(view);
	}
	return views;
}

export function readLiveSourceViewsByLpk(state: RootState, lpk: string): SourceView[] {
	const views: SourceView[] = [];
	for (const id of selectLiveSourceIdsByLpk(state, lpk)) {
		const view = selectSourceViewById(state, id);
		if (view) views.push(view);
	}
	return views;
}

