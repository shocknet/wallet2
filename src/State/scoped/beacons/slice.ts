import { createSlice, type PayloadAction } from "@reduxjs/toolkit";
import { createTransform } from "redux-persist";
import type { BeaconData } from "@/Api/pub/autogenerated/ts/types";

import {
	getPersistConfigKey,
	makeScopedPersistedReducer,
} from "@/State/scope/buildPersistedScopedReducer";

import { createEncryptedScopedStorage } from "@/storage/encryptedScopedStorage";
import type { RootState } from "@/State/store/store";
import { selectScopedStrict } from "@/State/scope/stricScopedSelector";

import { canonicalRelayUrl } from "./relays";

import {
	beaconRelayNodeKey,
	beaconRelayNodesAdapter,
	getInitialBeaconsState,
	isBeaconRelayFreshAt,
	type BeaconRelayNode,
	type BeaconsState,
} from "./state";


export type BeaconLookupCandidate = {
	id: string;
	lpk: string;
	relay: string;

	expectedLastSeenAtMs: number | null;
};


export const beaconsSlice = createSlice({
	name: "beacons",
	initialState: getInitialBeaconsState(),
	reducers: {
		recordBeacon(
			state,
			a: PayloadAction<{
				lpk: string;
				relay: string;
				seenAtMs: number;
				observedAtMs: number;
				data: BeaconData;
			}>,
		) {
			const relay = canonicalRelayUrl(a.payload.relay);
			if (!relay) return;

			const {
				lpk,
				seenAtMs,
				observedAtMs,
				data,
			} = a.payload;

			const id = beaconRelayNodeKey(lpk, relay);
			let node = state.nodes.entities[id];

			if (!node) {
				beaconRelayNodesAdapter.addOne(state.nodes, {
					id,
					lpk,
					relay,
				});

				node = state.nodes.entities[id]!;
			}

			/*
			 * Persist only the newest observation for this exact
			 * LPK + relay pair.
			 */
			if (
				node.lastSeenAtMs === undefined ||
				seenAtMs > node.lastSeenAtMs
			) {
				node.lastSeenAtMs = seenAtMs;
				node.name = data.name;
				node.avatarUrl = data.avatarUrl;
				node.fees = data.fees;
				node.nextRelay = data.nextRelay;
			}


			// A currently fresh beacon resolves lookup state.
			if (isBeaconRelayFreshAt(seenAtMs, observedAtMs)) {
				delete node.lookup;
			}
		},


		startLookups(
			state,
			a: PayloadAction<{
				pairs: BeaconLookupCandidate[];
				epoch: number;
			}>,
		) {
			for (const pair of a.payload.pairs) {
				const relay = canonicalRelayUrl(pair.relay);
				if (!relay) continue;

				const id = beaconRelayNodeKey(pair.lpk, relay);
				let node = state.nodes.entities[id];

				const currentLastSeenAtMs =
					node?.lastSeenAtMs ?? null;

				if (currentLastSeenAtMs !== pair.expectedLastSeenAtMs) {
					continue;
				}

				if (!node) {
					beaconRelayNodesAdapter.addOne(state.nodes, {
						id,
						lpk: pair.lpk,
						relay,
					});

					node = state.nodes.entities[id]!;
				}

				node.lookup = {
					status: "probing",
					epoch: a.payload.epoch,
				};
			}
		},


		finishLookup(
			state,
			a: PayloadAction<{
				id: string;
				epoch: number;
			}>,
		) {
			const node = state.nodes.entities[a.payload.id];
			if (!node?.lookup) return;

			if (node.lookup.status !== "probing") return;
			if (node.lookup.epoch !== a.payload.epoch) return;

			node.lookup.status = "done";
		},


		dropIds(
			state,
			a: PayloadAction<{ ids: string[] }>,
		) {
			if (!a.payload.ids.length) return;

			beaconRelayNodesAdapter.removeMany(
				state.nodes,
				a.payload.ids,
			);
		},
	},
});


/*
 * When writing  to storage, remove the runtime-only lookup state.
 * also strip out nodes with no lastSeenAtMs.
 */
const beaconNodesPersistTransform = createTransform(
	(nodes: BeaconsState["nodes"]) => {
		const ids: string[] = [];
		const entities: Record<string, BeaconRelayNode> = {};

		for (const id of nodes.ids) {
			const node = nodes.entities[id];
			if (!node) continue;

			if (node.lastSeenAtMs === undefined) {
				continue;
			}

			const {
				lookup: _lookup,
				...persisted
			} = node;

			ids.push(id);
			entities[id] = persisted;
		}

		return {
			ids,
			entities,
		};
	},

	(nodes: BeaconsState["nodes"]) => nodes,

	{
		whitelist: ["nodes"],
	},
);


const persistKey = "__beacons_v2";
// Pre-v2 state shape; never rehydrated, only kept so the old blob can be deleted.
const legacyPersistKey = "__beacons";


export function getScopedBeaconsReducer(
	identityPubkey: string,
	DataKey: CryptoKey,
) {
	return makeScopedPersistedReducer(
		beaconsSlice.reducer,
		persistKey,
		identityPubkey,
		{
			version: 0,
			storage: createEncryptedScopedStorage({
				identityId: identityPubkey,
				sliceName: beaconsSlice.name,
				dataKey: DataKey,
			}),
			transforms: [
				beaconNodesPersistTransform,
			],
		},
	);
}


export function getScopedBeaconsPersistKey(
	identityPubkey: string,
) {
	return getPersistConfigKey(
		persistKey,
		identityPubkey,
	);
}

export function getLegacyScopedBeaconsPersistKey(identityPubkey: string) {
	return getPersistConfigKey(legacyPersistKey, identityPubkey);
}


export const beaconsActions = beaconsSlice.actions;


export const beaconRelayNodesSelectors =
	beaconRelayNodesAdapter.getSelectors<RootState>(
		state => selectScopedStrict(state).beacons.nodes,
	);
