import { createSelector } from "@reduxjs/toolkit";
import { selectNowMs } from "@/State/runtime/slice";
import type { CumulativeFees } from "@/Api/pub/autogenerated/ts/types";
import {
	beaconLookupKey,
	BEACON_STALE_OLDER_THAN,
	BeaconLookupStatus,
	BeaconNode,
} from "./state";
import { beaconLookupsSelectors, beaconNodesSelectors } from "./slice";



export type BeaconHealth = "warmingUp" | "stale" | "fresh";

export const computeBeaconHealth = (args: {
	nowMs: number;
	lastSeenAtMs: number;
	probe?: { status: BeaconLookupStatus };
	lookupStatuses?: Array<BeaconLookupStatus | undefined>;
	canDiscover?: boolean;
}): BeaconHealth => {
	const { nowMs, lastSeenAtMs, probe, canDiscover = true } = args;

	if (nowMs - lastSeenAtMs <= BEACON_STALE_OLDER_THAN) return "fresh";
	if (!canDiscover) return "stale";

	const statuses = args.lookupStatuses
		?? [probe?.status];

	if (statuses.some(s => !s || s === "probing")) return "warmingUp";

	return "stale";
};

export type SourceBeaconJoin = {
	health: BeaconHealth;
	lastSeenAtMs: number;
	name?: string;
	avatarUrl?: string;
	fees?: CumulativeFees;
	nextRelay?: string;
};

export function joinSourceBeacon(args: {
	nowMs: number;
	lpk: string;
	relays: string[];
	node: BeaconNode | undefined;
	lookups: Record<string, { status: BeaconLookupStatus } | undefined>;
}): SourceBeaconJoin {
	const { nowMs, lpk, relays, node, lookups } = args;

	let lastSeenAtMs = 0;
	for (const relay of relays) {
		const seen = node?.relays[relay]?.lastSeenAtMs ?? 0;
		if (seen > lastSeenAtMs) lastSeenAtMs = seen;
	}

	const lookupStatuses = relays.map(relay => lookups[beaconLookupKey(lpk, relay)]?.status);

	return {
		health: computeBeaconHealth({
			nowMs,
			lastSeenAtMs,
			lookupStatuses,
			canDiscover: relays.length > 0,
		}),
		lastSeenAtMs,
		name: node?.name,
		avatarUrl: node?.avatarUrl,
		fees: node?.fees,
		nextRelay: node?.nextRelay,
	};
}

export const selectBeaconJoinState = createSelector(
	[
		beaconNodesSelectors.selectEntities,
		beaconLookupsSelectors.selectEntities,
		selectNowMs,
	],
	(nodes, lookups, nowMs) => ({ nodes, lookups, nowMs }),
);
