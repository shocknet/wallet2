import { createSelector } from "@reduxjs/toolkit";
import type { CumulativeFees } from "@/Api/pub/autogenerated/ts/types";
import type { RootState } from "@/State/store/store";

import {
	beaconRelayNodeKey,
	isBeaconRelayFreshAt,
	type BeaconRelayNode,
} from "./state";

import {
	beaconRelayNodesSelectors,
} from "./slice";
import { sameArray } from "@/utils";


export type BeaconHealth =
	| "warmingUp"
	| "stale"
	| "fresh";


export type SourceBeaconJoin = {
	health: BeaconHealth;
	lastSeenAtMs: number;

	name?: string;
	avatarUrl?: string;
	fees?: CumulativeFees;
	nextRelay?: string;
};





const sameJoin = (
	a: SourceBeaconJoin,
	b: SourceBeaconJoin,
) =>
	a.health === b.health &&
	a.lastSeenAtMs === b.lastSeenAtMs &&
	a.name === b.name &&
	a.avatarUrl === b.avatarUrl &&
	a.fees === b.fees &&
	a.nextRelay === b.nextRelay;



const makeSelectRelayNodes = () => {
	let previousIds: string[] = [];
	let previousNodes: Array<BeaconRelayNode | undefined> = [];

	return (
		state: RootState,
		lpk: string,
		relays: string[],
	): Array<BeaconRelayNode | undefined> => {
		const ids = relays.map(relay =>
			beaconRelayNodeKey(lpk, relay)
		);

		const nodes = ids.map(id =>
			beaconRelayNodesSelectors.selectById(state, id)
		);

		if (
			sameArray(previousIds, ids) &&
			sameArray(previousNodes, nodes)
		) {
			return previousNodes;
		}

		previousIds = ids;
		previousNodes = nodes;

		return nodes;
	};
};


export const joinBeaconNodes = (
	nodes: ReadonlyArray<BeaconRelayNode | undefined>,
): SourceBeaconJoin => {
	const nowMs = Date.now();

	let newestNode: BeaconRelayNode | undefined;
	let hasFresh = false;
	let hasUnresolved = false;

	for (const node of nodes) {
		if (
			node?.lastSeenAtMs !== undefined &&
			(
				!newestNode ||
				node.lastSeenAtMs > newestNode.lastSeenAtMs!
			)
		) {
			newestNode = node;
		}

		const fresh =
			node?.lastSeenAtMs !== undefined &&
			isBeaconRelayFreshAt(
				node.lastSeenAtMs,
				nowMs,
			);

		if (fresh) {
			hasFresh = true;
			continue;
		}

		/*
		 * Missing node:
		 *     startup / not checked yet
		 *
		 * Missing lookup:
		 *     startup / not checked yet
		 *
		 * probing:
		 *     actively warming up
		 */
		if (
			!node ||
			!node.lookup ||
			node.lookup.status === "probing"
		) {
			hasUnresolved = true;
		}
	}

	let health: BeaconHealth;

	if (hasFresh) {
		health = "fresh";
	} else if (nodes.length === 0) {
		health = "stale";
	} else if (hasUnresolved) {
		health = "warmingUp";
	} else {
		health = "stale";
	}

	return {
		health,
		lastSeenAtMs:
			newestNode?.lastSeenAtMs ?? 0,

		name:
			newestNode?.name,

		avatarUrl:
			newestNode?.avatarUrl,

		fees:
			newestNode?.fees,

		nextRelay:
			newestNode?.nextRelay,
	};
};

export const sourceBeaconJoin = (
	state: RootState,
	lpk: string,
	relays: string[],
): SourceBeaconJoin =>
	joinBeaconNodes(
		relays.map(relay =>
			beaconRelayNodesSelectors.selectById(
				state,
				beaconRelayNodeKey(lpk, relay),
			),
		),
	);

export const makeSelectSourceBeaconJoin = () => {
	const selectRelayNodes = makeSelectRelayNodes();

	return createSelector(
		[
			selectRelayNodes,
		],
		joinBeaconNodes,
		{
			memoizeOptions: {
				resultEqualityCheck:
					sameJoin,
			},
		},
	);
};
