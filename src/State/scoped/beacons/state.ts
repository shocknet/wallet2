import { createEntityAdapter, type EntityState } from "@reduxjs/toolkit";
import type { CumulativeFees } from "@/Api/pub/autogenerated/ts/types";
import { BEACON_STALE_OLDER_THAN } from "@/constants";


export const beaconRelayNodeKey = (lpk: string, relay: string) =>
	`${lpk}\0${relay}`;


export const beaconRelayStaleAtMs = (lastSeenAtMs: number) =>
	lastSeenAtMs + BEACON_STALE_OLDER_THAN + 1;


export const isBeaconRelayFreshAt = (
	lastSeenAtMs: number,
	nowMs: number,
) =>
	nowMs < beaconRelayStaleAtMs(lastSeenAtMs);


export type BeaconLookupStatus = "probing" | "done";


export type BeaconLookup = {
	status: BeaconLookupStatus;
	epoch: number;
};


export type BeaconRelayNode = {
	id: string;

	lpk: string;
	relay: string;

	lastSeenAtMs?: number;

	name?: string;
	avatarUrl?: string;
	fees?: CumulativeFees;
	nextRelay?: string;

	/*
	 * Runtime only.
	 *
	 * Stripped before persistence.
	 */
	lookup?: BeaconLookup;
};


export const beaconRelayNodesAdapter =
	createEntityAdapter<BeaconRelayNode, string>({
		selectId: node => node.id,
	});


export type BeaconsState = {
	nodes: EntityState<BeaconRelayNode, string>;
};

export const getInitialBeaconsState = (): BeaconsState => ({
	nodes: beaconRelayNodesAdapter.getInitialState(),
});
