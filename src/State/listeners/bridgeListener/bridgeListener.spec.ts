import { afterEach, beforeEach, describe, expect, it, vi, type Mock } from "vitest";
import { getNostrClient, type Client } from "@/Api/nostr";
import Bridge from "@/Api/bridge";
import { nip98 } from "nostr-tools";
import type { UserInfo } from "@/Api/pub/autogenerated/ts/types";
import { createDeferred } from "@/lib/deferred";
import { newLww } from "@/State/sync/lww";
import { identityUnloaded } from "@/State/listeners/actions";
import { identitiesRegistryActions } from "@/State/identitiesRegistry/slice";
import { runtimeActions } from "@/State/runtime/slice";
import { sourcesActions } from "@/State/scoped/backups/sources/slice";
import { TEST_CLOCK_BY, TEST_RUNTIME_IDENTITY } from "@tests/support/identityFixtures";
import {
	createTestSource,
	TEST_RELAY_URL,
	type TestSource,
} from "@tests/support/sourcesHelpers";
import { makeListenerStore } from "@tests/support/listenerStore";
import { bridgeListenerSpec } from "./bridgeListener";

vi.mock("@/Api/nostr", () => ({
	getNostrClient: vi.fn(),
}));
vi.mock("@/Api/bridge", () => ({
	default: vi.fn(),
}));
vi.mock("nostr-tools", async () => {
	const actual = await vi.importActual<typeof import("nostr-tools")>("nostr-tools");
	return {
		...actual,
		nip98: {
			...actual.nip98,
			getToken: vi.fn(),
		},
	};
});

const getNostrClientMock = vi.mocked(getNostrClient);
const BridgeMock = vi.mocked(Bridge);
const getTokenMock = vi.mocked(nip98.getToken);

const NOW_MS = 1_000_000;
const LOCAL_BRIDGE = "https://custom-bridge.example";
const USERINFO_BRIDGE = "https://bridge-from-userinfo.com";
const NOFFER = "noffer1abc";

type BridgeClient = {
	GetUserInfo: Mock<Client["GetUserInfo"]>;
};
type BridgeHandle = {
	GetOrCreateNofferName: Mock;
};
type BridgeStore = ReturnType<typeof openBridgeStore>;

function okUserInfo(over: Partial<UserInfo> = {}): { status: "OK" } & UserInfo {
	return {
		status: "OK",
		balance: 40,
		max_withdrawable: 30,
		ndebit: "ndebit-string",
		noffer: NOFFER,
		nmanage: "nmanage1abc",
		topic_id: "topic-1",
		bridge_url: USERINFO_BRIDGE,
		callback_url: "",
		network_max_fee_bps: 0,
		network_max_fee_fixed: 0,
		service_fee_bps: 0,
		userId: "user-1",
		user_identifier: "user-1",
		...over,
	};
}

function mockClient(partial: Partial<BridgeClient> = {}): BridgeClient {
	return {
		GetUserInfo: vi.fn().mockResolvedValue(okUserInfo()),
		...partial,
	};
}

function useClient(client: BridgeClient) {
	getNostrClientMock.mockResolvedValue(client as unknown as Client);
	return client;
}

function bindBridge(handle: BridgeHandle) {
	BridgeMock.mockReturnValue(handle as unknown as Bridge);
	return handle;
}

function okBridge(vanity = "alice"): BridgeHandle {
	return bindBridge({
		GetOrCreateNofferName: vi.fn().mockResolvedValue({
			status: "OK",
			vanity_name: vanity,
		}),
	});
}

function sourceWithBridge(url: string | null, over: Parameters<typeof createTestSource>[0] = {}) {
	return createTestSource({
		...over,
		doc: {
			...over.doc,
			bridgeUrl: newLww(url, TEST_CLOCK_BY),
		},
	});
}

function delay(ms: number) {
	return new Promise<void>(resolve => {
		setTimeout(resolve, ms);
	});
}

function openBridgeStore(opts: {
	sources?: TestSource[];
	loadIdentity?: boolean;
} = {}) {
	const loadIdentity = opts.loadIdentity ?? true;
	const { store } = makeListenerStore({
		specs: [bridgeListenerSpec],
		sources: opts.sources,
		loadIdentity: false,
	});
	store.dispatch(runtimeActions.clockTick({ nowMs: NOW_MS }));
	if (loadIdentity) {
		store.dispatch(identitiesRegistryActions.setActiveIdentityRuntime({
			identity: TEST_RUNTIME_IDENTITY,
		}));
	}
	return store;
}

function vanityName(store: BridgeStore, sourceId: string) {
	return store.getState().scoped.sources.metadata.entities[sourceId]?.vanityName;
}

function clearCalls(client?: BridgeClient) {
	getNostrClientMock.mockClear();
	getTokenMock.mockClear();
	BridgeMock.mockClear();
	client?.GetUserInfo.mockClear();
}

async function settle() {
	await vi.runAllTimersAsync();
}

describe("bridgeListener", () => {
	beforeEach(() => {
		vi.resetAllMocks();
		vi.useFakeTimers();
		vi.setSystemTime(NOW_MS);
		getTokenMock.mockResolvedValue("nostr-header");
	});

	afterEach(() => {
		vi.useRealTimers();
	});

	describe("vanity fetch", () => {
		it("uses the source bridge url over GetUserInfo and writes vanityName", async () => {
			const client = useClient(mockClient());
			const bridge = okBridge("alice");
			const store = openBridgeStore();
			await settle();

			const source = sourceWithBridge(LOCAL_BRIDGE);
			store.dispatch(sourcesActions._createDraftDoc({
				sourceId: source.id,
				draft: source.doc,
			}));
			await settle();

			expect(getNostrClientMock).toHaveBeenCalledTimes(1);
			expect(getNostrClientMock).toHaveBeenCalledWith(
				{ pubkey: source.lpk, relays: [TEST_RELAY_URL] },
				source.keys,
			);
			expect(client.GetUserInfo).toHaveBeenCalledTimes(1);
			expect(getTokenMock).toHaveBeenCalledWith(
				`${LOCAL_BRIDGE}/api/v1/noffer/vanity`,
				"POST",
				expect.any(Function),
				true,
				{ noffer: NOFFER },
			);
			expect(BridgeMock).toHaveBeenCalledWith(LOCAL_BRIDGE, "nostr-header");
			expect(bridge.GetOrCreateNofferName).toHaveBeenCalledWith({ noffer: NOFFER });
			expect(vanityName(store, source.id)).toBe("alice@custom-bridge.example");
		});

		it("falls back to GetUserInfo.bridge_url when the source has none", async () => {
			useClient(mockClient());
			okBridge("bob");
			const store = openBridgeStore();
			await settle();

			const source = createTestSource();
			store.dispatch(sourcesActions._createDraftDoc({
				sourceId: source.id,
				draft: source.doc,
			}));
			await settle();

			expect(getTokenMock.mock.calls[0][0]).toBe(
				`${USERINFO_BRIDGE}/api/v1/noffer/vanity`,
			);
			expect(BridgeMock).toHaveBeenCalledWith(USERINFO_BRIDGE, "nostr-header");
			expect(vanityName(store, source.id)).toBe("bob@bridge-from-userinfo.com");
		});
	});

	describe("triggers", () => {
		it("on identity load, fetches sources that still have no vanity", async () => {
			const needs = sourceWithBridge(LOCAL_BRIDGE);
			const has = sourceWithBridge(LOCAL_BRIDGE, {
				meta: { vanityName: "frank@custom-bridge.example" },
			});
			const lv = sourceWithBridge(LOCAL_BRIDGE, {
				meta: { vanityName: "guest@lightning.video" },
			});
			useClient(mockClient());
			okBridge("erin");
			const store = openBridgeStore({ sources: [needs, has, lv] });
			await settle();

			expect(getNostrClientMock).toHaveBeenCalledTimes(1);
			expect(getNostrClientMock).toHaveBeenCalledWith(
				{ pubkey: needs.lpk, relays: [TEST_RELAY_URL] },
				needs.keys,
			);
			expect(vanityName(store, needs.id)).toBe("erin@custom-bridge.example");
			expect(vanityName(store, has.id)).toBe("frank@custom-bridge.example");
			expect(vanityName(store, lv.id)).toBe("guest@lightning.video");
		});

		it("fetches when a remote source is applied", async () => {
			useClient(mockClient());
			okBridge("carol");
			const store = openBridgeStore();
			await settle();

			const source = sourceWithBridge(LOCAL_BRIDGE);
			store.dispatch(sourcesActions.applyRemoteSource({
				sourceId: source.id,
				remote: source.doc,
			}));
			await settle();

			expect(getNostrClientMock).toHaveBeenCalledTimes(1);
			expect(vanityName(store, source.id)).toBe("carol@custom-bridge.example");
		});

		it("fetches when the local bridge url is updated", async () => {
			const source = sourceWithBridge(LOCAL_BRIDGE, {
				meta: { vanityName: "old@custom-bridge.example" },
			});
			useClient(mockClient());
			okBridge("dave");
			const store = openBridgeStore({ sources: [source] });
			await settle();
			clearCalls();

			const nextBridge = "https://other-bridge.example";
			store.dispatch(sourcesActions.updateBridgeUrl({
				sourceId: source.id,
				bridgeUrl: nextBridge,
				by: TEST_CLOCK_BY,
			}));
			await settle();

			expect(getTokenMock.mock.calls[0][0]).toBe(
				`${nextBridge}/api/v1/noffer/vanity`,
			);
			expect(vanityName(store, source.id)).toBe("dave@other-bridge.example");
		});

		it("does not fetch when the source already has a vanity and the bridge url is unchanged", async () => {
			const source = sourceWithBridge(LOCAL_BRIDGE, {
				meta: { vanityName: "frank@custom-bridge.example" },
			});
			useClient(mockClient());
			okBridge();
			const store = openBridgeStore({ sources: [source] });
			await settle();
			clearCalls();

			store.dispatch(sourcesActions.applyRemoteSource({
				sourceId: source.id,
				remote: source.doc,
			}));
			await settle();

			expect(getNostrClientMock).not.toHaveBeenCalled();
			expect(vanityName(store, source.id)).toBe("frank@custom-bridge.example");
		});
	});

	describe("skips and errors", () => {
		it("does not replace a lightning.video vanity", async () => {
			const source = sourceWithBridge(LOCAL_BRIDGE, {
				meta: { vanityName: "guest@lightning.video" },
			});
			useClient(mockClient());
			okBridge();
			const store = openBridgeStore({ sources: [source] });
			await settle();

			store.dispatch(sourcesActions.updateBridgeUrl({
				sourceId: source.id,
				bridgeUrl: "https://should-not-be-used.example",
				by: TEST_CLOCK_BY,
			}));
			await settle();

			expect(getNostrClientMock).not.toHaveBeenCalled();
			expect(vanityName(store, source.id)).toBe("guest@lightning.video");
		});

		it("does not set vanityName when GetUserInfo fails", async () => {
			useClient(mockClient({
				GetUserInfo: vi.fn().mockResolvedValue({ status: "ERROR", reason: "info-down" }),
			}));
			okBridge();
			const store = openBridgeStore();
			await settle();

			const source = sourceWithBridge(LOCAL_BRIDGE);
			store.dispatch(sourcesActions._createDraftDoc({
				sourceId: source.id,
				draft: source.doc,
			}));
			await settle();

			expect(getTokenMock).not.toHaveBeenCalled();
			expect(BridgeMock).not.toHaveBeenCalled();
			expect(vanityName(store, source.id)).toBeUndefined();
		});

		it("does not set vanityName when the bridge call fails", async () => {
			useClient(mockClient());
			bindBridge({
				GetOrCreateNofferName: vi.fn().mockResolvedValue({
					status: "ERROR",
					reason: "bridge-down",
				}),
			});
			const store = openBridgeStore();
			await settle();

			const source = sourceWithBridge(LOCAL_BRIDGE);
			store.dispatch(sourcesActions._createDraftDoc({
				sourceId: source.id,
				draft: source.doc,
			}));
			await settle();

			expect(getTokenMock).toHaveBeenCalledTimes(1);
			expect(vanityName(store, source.id)).toBeUndefined();
		});

		it("does not set vanityName when neither source nor GetUserInfo has a bridge url", async () => {
			useClient(mockClient({
				GetUserInfo: vi.fn().mockResolvedValue(okUserInfo({ bridge_url: "" })),
			}));
			okBridge();
			const store = openBridgeStore();
			await settle();

			const source = createTestSource();
			store.dispatch(sourcesActions._createDraftDoc({
				sourceId: source.id,
				draft: source.doc,
			}));
			await settle();

			expect(getTokenMock).not.toHaveBeenCalled();
			expect(vanityName(store, source.id)).toBeUndefined();
		});

		it("does not set vanityName when identity unloads mid-fetch", async () => {
			useClient(mockClient({
				GetUserInfo: vi.fn(async () => {
					await delay(50);
					return okUserInfo();
				}),
			}));
			okBridge();
			const store = openBridgeStore();
			await settle();

			const source = sourceWithBridge(LOCAL_BRIDGE);
			store.dispatch(sourcesActions._createDraftDoc({
				sourceId: source.id,
				draft: source.doc,
			}));
			await vi.advanceTimersByTimeAsync(5);

			const unloaded = createDeferred<void>();
			store.dispatch(identityUnloaded({ deferred: unloaded }));
			await unloaded;
			await settle();

			expect(vanityName(store, source.id)).toBeUndefined();
		});
	});
});
