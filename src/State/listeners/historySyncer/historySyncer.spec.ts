import { afterEach, beforeEach, describe, expect, it, vi, type Mock } from "vitest";
import { getNostrClient, type Client } from "@/Api/nostr";
import type { UserInfo } from "@/Api/pub/autogenerated/ts/types";
import { createDeferred } from "@/lib/deferred";
import type { TaskResult } from "@reduxjs/toolkit";
import { newLww } from "@/State/sync/lww";
import {
	historyFetchAllRequested,
	historyFetchSourceRequested,
	identityUnloaded,
} from "@/State/listeners/actions";
import { identitiesRegistryActions } from "@/State/identitiesRegistry/slice";
import { runtimeActions } from "@/State/runtime/slice";
import { sourcesActions } from "@/State/scoped/backups/sources/slice";
import { makeKey } from "@/State/scoped/backups/sources/history/helpers";
import type { Satoshi } from "@/lib/types/units";
import { beaconsActions } from "@/State/scoped/beacons/slice";
import { TEST_CLOCK_BY, TEST_RUNTIME_IDENTITY } from "@tests/support/identityFixtures";
import { makeOpsPage } from "@tests/support/historyFixtures";
import {
	createTestSource,
	createTestSources,
	TEST_RELAY_URL,
	type TestSource,
} from "@tests/support/sourcesHelpers";
import { makeListenerStore } from "@tests/support/listenerStore";
import type { BeaconsState } from "@/State/scoped/beacons/state";
import { historySyncerSpec } from "./historySyncer";

vi.mock("@/Api/nostr", () => ({
	getNostrClient: vi.fn(),
}));
vi.mock("@/lib/invoice", () => ({
	decodeInvoice: vi.fn(() => undefined),
}));

const getNostrClientMock = vi.mocked(getNostrClient);

const NOW_MS = 1_000_000;
const OTHER_RELAY = "wss://other-relay.lightning.pub";
const INVOICE = "lnbc1testinvoice";

type HistoryClient = {
	GetUserInfo: Mock<Client["GetUserInfo"]>;
	GetUserOperations: Mock<Client["GetUserOperations"]>;
	GetPaymentState: Mock<Client["GetPaymentState"]>;
};
type HistoryStore = ReturnType<typeof openHistoryStore>;

const getUserInfoResponse: UserInfo = {
	balance: 40,
	max_withdrawable: 30,
	ndebit: "ndebit-string",
	noffer: "noffer1abc",
	nmanage: "nmanage1abc",
	topic_id: "topic-1",
	bridge_url: "",
	callback_url: "",
	network_max_fee_bps: 0,
	network_max_fee_fixed: 0,
	service_fee_bps: 0,
	userId: "user-1",
	user_identifier: "user-1",
}

function okUserInfo(over: Partial<UserInfo> = {}): { status: "OK" } & UserInfo {
	return {
		status: "OK",
		...getUserInfoResponse,
		...over,
	};
}

function mockHistoryClient(partial: Partial<HistoryClient> = {}): HistoryClient {
	return {
		GetUserInfo: vi.fn().mockResolvedValue(okUserInfo()),
		GetUserOperations: vi.fn().mockResolvedValue(makeOpsPage({})),
		GetPaymentState: vi.fn().mockResolvedValue({ status: "ERROR", reason: "unused" }),
		...partial,
	};
}

function useClient(client: HistoryClient) {
	getNostrClientMock.mockResolvedValue(client as unknown as Client);
	return client;
}

function clearCalls(client: HistoryClient) {
	getNostrClientMock.mockClear();
	client.GetUserInfo.mockClear();
	client.GetUserOperations.mockClear();
	client.GetPaymentState.mockClear();
}

function delay(ms: number) {
	return new Promise<void>(resolve => {
		setTimeout(resolve, ms);
	});
}

function openHistoryStore(opts: {
	sources?: TestSource[];
	beacons?: BeaconsState;
	loadIdentity?: boolean;
} = {}) {
	const loadIdentity = opts.loadIdentity ?? true;
	const { store } = makeListenerStore({
		specs: [historySyncerSpec],
		sources: opts.sources,
		beacons: opts.beacons,
		loadIdentity: false,
	});
	store.dispatch(runtimeActions.clockTick({ nowMs: NOW_MS }));
	if (loadIdentity) {
		store.dispatch(identitiesRegistryActions.setActiveIdentityRuntime({ identity: TEST_RUNTIME_IDENTITY }));
	}
	return store;
}

function seeBeacon(lpk: string, relay = TEST_RELAY_URL, seenAtMs = NOW_MS) {
	return beaconsActions.recordBeacon({
		lpk,
		relay,
		seenAtMs,
		data: { type: "service", name: "node" },
	});
}

function optimisticInvoice(sourceId: string) {
	return {
		optimistic: true as const,
		sourceId,
		operationId: INVOICE,
		opKey: makeKey(sourceId, INVOICE),
		amount: 12 as Satoshi,
		paidAtUnix: NOW_MS,
		type: "INVOICE" as const,
		inbound: false as const,
		invoice: INVOICE,
	};
}

function sourceMeta(store: HistoryStore, sourceId: string) {
	return store.getState().scoped.sources.metadata.entities[sourceId];
}

function historyOps(store: HistoryStore) {
	return store.getState().scoped.sources.history.ops;
}

async function settle() {
	await vi.runAllTimersAsync();
}

describe("historySyncer", () => {
	beforeEach(() => {
		vi.resetAllMocks();
		vi.useFakeTimers();
		vi.setSystemTime(NOW_MS);
	});

	afterEach(() => {
		vi.useRealTimers();
	});

	describe("fetch source", () => {
		it("commits user info on identity load", async () => {
			const [source] = createTestSources(1);
			const client = useClient(mockHistoryClient());
			const store = openHistoryStore({ sources: [source] });

			await settle();

			expect(getNostrClientMock).toHaveBeenCalledTimes(2);
			expect(getNostrClientMock).toHaveBeenCalledWith(
				{ pubkey: source.lpk, relays: [TEST_RELAY_URL] },
				source.keys,
			);
			expect(client.GetUserInfo).toHaveBeenCalledTimes(1);
			expect(client.GetUserOperations).toHaveBeenCalledTimes(1);

			const meta = sourceMeta(store, source.id);
			expect(meta.balance).toBe(getUserInfoResponse.balance);
			expect(meta.maxWithdrable).toBe(getUserInfoResponse.max_withdrawable);
			expect(meta.ndebit).toBe(getUserInfoResponse.ndebit);
			expect(meta.noffer).toBe(getUserInfoResponse.noffer);
			expect(meta.nmanage).toBe(getUserInfoResponse.nmanage);
			expect(meta.topicId).toBe(getUserInfoResponse.topic_id);
		});

		it("pages GetUserOperations until no group is full", async () => {
			const [source] = createTestSources(1);
			const client = useClient(mockHistoryClient({
				GetUserOperations: vi.fn()
					.mockResolvedValueOnce(makeOpsPage({ inInv: 10, outInv: 5 }))
					.mockResolvedValueOnce(makeOpsPage({ inTx: 5 })),
			}));
			const store = openHistoryStore({ sources: [source] });

			await settle();

			expect(client.GetUserOperations).toHaveBeenCalledTimes(2);
			expect(client.GetUserOperations).toHaveBeenNthCalledWith(1, expect.objectContaining({
				max_size: 10,
				latestIncomingInvoice: { ts: 0, id: 0 },
			}));
			expect(historyOps(store).ids).toHaveLength(20);
		});

		it("still commits ops when GetUserInfo fails", async () => {
			const [source] = createTestSources(1);
			useClient(mockHistoryClient({
				GetUserInfo: vi.fn().mockResolvedValue({ status: "ERROR", reason: "info-down" }),
				GetUserOperations: vi.fn().mockResolvedValue(makeOpsPage({ inInv: 3 })),
			}));
			const store = openHistoryStore({ sources: [source] });

			await settle();

			expect(sourceMeta(store, source.id).balance).toBe(0);
			expect(historyOps(store).ids).toHaveLength(3);
		});

		it("still commits user info when GetUserOperations fails", async () => {
			const [source] = createTestSources(1);
			useClient(mockHistoryClient({
				GetUserOperations: vi.fn().mockResolvedValue({ status: "ERROR", reason: "ops-down" }),
			}));
			const store = openHistoryStore({ sources: [source] });

			await settle();

			expect(sourceMeta(store, source.id).balance).toBe(40);
			expect(historyOps(store).ids).toHaveLength(0);
		});

		it("dedups concurrent fetches for the same source", async () => {
			const [source] = createTestSources(1);
			const client = useClient(mockHistoryClient({
				GetUserInfo: vi.fn(async () => {
					await delay(20);
					return okUserInfo();
				}),
				GetUserOperations: vi.fn().mockResolvedValue(makeOpsPage({ inInv: 5, outInv: 5 })),
			}));
			const store = openHistoryStore({ sources: [source] });

			const first = createDeferred<TaskResult<void>>();
			const second = createDeferred<TaskResult<void>>();
			store.dispatch(historyFetchSourceRequested({ sourceId: source.id, deferred: first }));
			store.dispatch(historyFetchSourceRequested({ sourceId: source.id, deferred: second }));

			await settle();

			expect(client.GetUserOperations).toHaveBeenCalledTimes(1);
			await expect(first).resolves.toBeUndefined();
			await expect(second).resolves.toBeUndefined();
			expect(historyOps(store).ids).toHaveLength(10);
		});

		it("does not commit user info when identity unloads mid-fetch", async () => {
			const [source] = createTestSources(1);
			useClient(mockHistoryClient({
				GetUserInfo: vi.fn(async () => {
					await delay(50);
					return okUserInfo();
				}),
			}));
			const store = openHistoryStore({ sources: [source] });

			await vi.advanceTimersByTimeAsync(5);

			const unloaded = createDeferred<void>();
			store.dispatch(identityUnloaded({ deferred: unloaded }));
			await unloaded;
			await settle();

			expect(sourceMeta(store, source.id).balance).toBe(0);
			expect(sourceMeta(store, source.id).maxWithdrable).toBe(0);
		});
	});

	describe("triggers", () => {
		it("fetches every live source on identity load and skips deleted ones", async () => {
			const live = createTestSources(2);
			const deleted = createTestSource({
				doc: { deleted: newLww(true, TEST_CLOCK_BY) },
			});
			const client = useClient(mockHistoryClient({
				GetUserOperations: vi.fn().mockResolvedValue(makeOpsPage({ inInv: 2 })),
			}));
			openHistoryStore({ sources: [...live, deleted] });

			await settle();

			expect(client.GetUserInfo).toHaveBeenCalledTimes(2);
			expect(client.GetUserOperations).toHaveBeenCalledTimes(2);
		});

		it("historyFetchAllRequested fetches every live source again", async () => {
			const sources = createTestSources(2);
			const client = useClient(mockHistoryClient());
			const store = openHistoryStore({ sources });
			await settle();
			clearCalls(client);

			const done = createDeferred<void>();
			store.dispatch(historyFetchAllRequested({ deferred: done }));
			await settle();
			await done;

			expect(client.GetUserOperations).toHaveBeenCalledTimes(2);
		});

		it("starts a fetch when a draft source is added", async () => {
			const client = useClient(mockHistoryClient({
				GetUserOperations: vi.fn().mockResolvedValue(makeOpsPage({ inInv: 4, outInv: 1 })),
			}));
			const store = openHistoryStore();
			await settle();
			expect(client.GetUserOperations).not.toHaveBeenCalled();

			const source = createTestSource();
			store.dispatch(sourcesActions._createDraftDoc({
				sourceId: source.id,
				draft: source.doc,
			}));
			await settle();

			expect(client.GetUserOperations).toHaveBeenCalledTimes(1);
			expect(historyOps(store).ids).toHaveLength(5);
		});

		it("starts a fetch when a remote source is applied", async () => {
			const client = useClient(mockHistoryClient({
				GetUserOperations: vi.fn().mockResolvedValue(makeOpsPage({ outTx: 3 })),
			}));
			const store = openHistoryStore();
			await settle();

			const source = createTestSource();
			store.dispatch(sourcesActions.applyRemoteSource({
				sourceId: source.id,
				remote: source.doc,
			}));
			await settle();

			expect(client.GetUserOperations).toHaveBeenCalledTimes(1);
			expect(historyOps(store).ids).toHaveLength(3);
		});

		it("starts a fetch when relay presence changes on a live source", async () => {
			const [source] = createTestSources(1);
			useClient(mockHistoryClient());
			const store = openHistoryStore({ sources: [source] });
			await settle();

			expect(getNostrClientMock.mock.calls.map(call => call[0])).toEqual([
				{ pubkey: source.lpk, relays: [TEST_RELAY_URL] },
				{ pubkey: source.lpk, relays: [TEST_RELAY_URL] },
			]);

			store.dispatch(sourcesActions.setRelayPresence({
				sourceId: source.id,
				relayUrl: OTHER_RELAY,
				present: true,
				by: TEST_CLOCK_BY,
			}));
			await settle();

			expect(getNostrClientMock.mock.calls.slice(2).map(call => call[0])).toEqual([
				{ pubkey: source.lpk, relays: [OTHER_RELAY, TEST_RELAY_URL] },
				{ pubkey: source.lpk, relays: [OTHER_RELAY, TEST_RELAY_URL] },
			]);
		});

		it("does not fetch when a beacon is for a relay the source does not use", async () => {
			const [source] = createTestSources(1);
			const client = useClient(mockHistoryClient());
			const store = openHistoryStore({ sources: [source] });
			await settle();
			clearCalls(client);

			store.dispatch(seeBeacon(source.lpk, OTHER_RELAY));
			await settle();

			expect(client.GetUserOperations).not.toHaveBeenCalled();
		});

		it("fetches when a source becomes fresh", async () => {
			const sources = createTestSources(2);
			const client = useClient(mockHistoryClient({
				GetUserOperations: vi.fn().mockResolvedValue(makeOpsPage({ inInv: 2 })),
			}));
			const store = openHistoryStore({ sources });
			await settle();
			clearCalls(client);

			store.dispatch(seeBeacon(sources[0].lpk));
			store.dispatch(seeBeacon(sources[0].lpk, TEST_RELAY_URL, NOW_MS + 1_000));
			await settle();

			expect(client.GetUserOperations).toHaveBeenCalledTimes(1);
		});

		it("fetches every live source sharing that lpk", async () => {
			const lpk = createTestSource().lpk;
			const a = createTestSource({ lpk, relays: [TEST_RELAY_URL] });
			const b = createTestSource({ lpk, relays: [TEST_RELAY_URL] });
			const other = createTestSource();
			const client = useClient(mockHistoryClient({
				GetUserOperations: vi.fn().mockResolvedValue(makeOpsPage({ inInv: 1 })),
			}));
			const store = openHistoryStore({ sources: [a, b, other] });
			await settle();
			clearCalls(client);

			store.dispatch(seeBeacon(lpk));
			await settle();

			expect(client.GetUserOperations).toHaveBeenCalledTimes(2);
		});

		it("only refreshes the source whose relay saw the beacon", async () => {
			const lpk = createTestSource().lpk;
			const onTestRelay = createTestSource({ lpk, relays: [TEST_RELAY_URL] });
			const onOtherRelay = createTestSource({ lpk, relays: [OTHER_RELAY] });
			const client = useClient(mockHistoryClient({
				GetUserOperations: vi.fn().mockResolvedValue(makeOpsPage({ inInv: 1 })),
			}));
			const store = openHistoryStore({ sources: [onTestRelay, onOtherRelay] });
			await settle();
			clearCalls(client);

			store.dispatch(seeBeacon(lpk, TEST_RELAY_URL));
			await settle();

			expect(client.GetUserOperations).toHaveBeenCalledTimes(1);
		});
	});

	describe("in-flight outgoing invoices", () => {
		it("checks payment state on app resume and replaces the optimistic row", async () => {
			const [source] = createTestSources(1);
			const client = useClient(mockHistoryClient({
				GetPaymentState: vi.fn().mockResolvedValue({
					status: "OK",
					amount: 12,
					internal: false,
					network_fee: 1,
					operation_id: "pub-op-1",
					paid_at_unix: 123,
					service_fee: 2,
				}),
			}));
			const store = openHistoryStore({ sources: [source] });
			await settle();
			clearCalls(client);

			store.dispatch(sourcesActions.addOptimistic({
				sourceId: source.id,
				operation: optimisticInvoice(source.id),
			}));

			store.dispatch(runtimeActions.setAppActiveStatus({ active: true }));
			await settle();

			expect(client.GetPaymentState).toHaveBeenCalledWith({ invoice: INVOICE });
			expect(historyOps(store).entities[makeKey(source.id, INVOICE)]).toBeUndefined();
			expect(historyOps(store).entities[makeKey(source.id, "pub-op-1")]).toMatchObject({
				type: "INVOICE",
				inbound: false,
				invoice: INVOICE,
			});
		});

		it("does not check payment state when the app goes inactive", async () => {
			const [source] = createTestSources(1);
			const client = useClient(mockHistoryClient());
			const store = openHistoryStore({ sources: [source] });
			await settle();
			clearCalls(client);

			store.dispatch(sourcesActions.addOptimistic({
				sourceId: source.id,
				operation: optimisticInvoice(source.id),
			}));
			store.dispatch(runtimeActions.setAppActiveStatus({ active: false }));
			await settle();

			expect(client.GetPaymentState).not.toHaveBeenCalled();
		});
	});
});
