function resolveSourcePrivateKey(
	state: RootState,
	sourceId: string,
): string | null {
	const sourceEntity = docsSelectors.selectById(state, sourceId);
	if (!sourceEntity) {
		return null;
	}

	const draft = sourceEntity.draft;
	if (!draft || draft.type !== SourceType.NPROFILE_SOURCE) {
		return null;
	}

	return draft.keys.privateKey;
}

/**
 * When the active identity matches the push topic's identity and source keys
 * are available, decrypt the envelope into either a route pendingNav or a
 * pending auth request, then clear push.
 */
export const materializePushIntent =
	(): AppThunk<void> => (dispatch, getState) => {
		const state = getState();
		const pushIntent = selectPushIntent(state);
		const activeIdentityId = selectActiveIdentity(state)?.pubkey ?? null;

		if (!pushIntent || !activeIdentityId) {
			return;
		}

		const topicEntry = selectTopicIndexFromRegistry(
			state,
			pushIntent.envelope.topic_id,
		);

		if (
			!topicEntry ||
			topicEntry.identityId !== activeIdentityId
		) {
			return;
		}

		const privateKey = resolveSourcePrivateKey(
			state,
			topicEntry.sourceId,
		);
		if (!privateKey) {
			return;
		}

		const payload = decryptPushPayload({
			privateKey,
			appNpubHex: pushIntent.envelope.app_npub_hex,
			encryptedPayload: pushIntent.envelope.encrypted_payload,
		});

		if (!payload) {
			dispatch(shellActions.pushIntentCleared());
			return;
		}

		const authRequest = toPendingAuthRequest({
			identityId: topicEntry.identityId,
			sourceId: topicEntry.sourceId,
			payload,
			enqueuedAtMs: pushIntent.receivedAtMs,
		});

		if (authRequest) {
			dispatch(clinkRequestsActions.enqueuePendingClinkRequest(authRequest));
			dispatch(shellActions.pushIntentCleared());
			return;
		}

		const route = toPushRouteIntent({
			sourceId: topicEntry.sourceId,
			payload,
		});

		const pendingNav: PendingNav = {
			kind: "route",
			path: route.path,
			state: route.state as Record<string, unknown> | undefined,
			identityId: topicEntry.identityId,
		};

		dispatch(shellActions.pendingNavSet(pendingNav));
		dispatch(shellActions.pushIntentCleared());
	};

export function pendingNavReadyForIdentity(
	pendingNav: PendingNav,
	readyIdentityId: string | null,
): boolean {
	if (!readyIdentityId) {
		return false;
	}

	return (
		!pendingNav.identityId ||
		pendingNav.identityId === readyIdentityId
	);
}

// After createIdentity: only enqueue bootstrap when no remote backup was found
export const enqueueBootstrapIfNoBackup =
	(args: {
		foundBackup: boolean;
		identityId: string;
	}): AppThunk<void> =>
		(dispatch) => {
			if (args.foundBackup) {
				return;
			}

			dispatch(
				shellActions.pendingNavSet({
					kind: "route",
					path: "/bootstrap",
					identityId: args.identityId,
				}),
			);
		};


export function decryptPushPayload(args: {
	privateKey: string;
	appNpubHex: string;
	encryptedPayload: string;
}): PushNotificationPayload | null {
	try {
		const sharedSecret = nip44.getConversationKey(
			hexToBytes(args.privateKey),
			args.appNpubHex
		);
		const plaintext = nip44.decrypt(args.encryptedPayload, sharedSecret);
		const parsed = JSON.parse(plaintext) as PushNotificationPayload;
		const validationError = PushNotificationPayloadValidate(parsed);
		if (validationError) return null;
		return parsed;
	} catch {
		return null;
	}
}

function toPendingAuthRequest(args: {
	identityId: string;
	sourceId: string;
	payload: PushNotificationPayload;
	enqueuedAtMs: number;
}): PendingClinkRequest | null {
	if (args.payload.data.type === PushNotificationPayload_data_type.DEBIT_AUTH_REQ) {
		return {
			kind: "debit",
			identityId: args.identityId,
			sourceId: args.sourceId,
			request: args.payload.data.debit_auth_req,
			enqueuedAtMs: args.enqueuedAtMs,
		};
	}

	if (args.payload.data.type === PushNotificationPayload_data_type.MANAGE_AUTH_REQ) {
		return {
			kind: "manage",
			identityId: args.identityId,
			sourceId: args.sourceId,
			request: args.payload.data.manage_auth_req,
			enqueuedAtMs: args.enqueuedAtMs,
		};
	}

	return null;
}

function toPushRouteIntent(args: {
	sourceId: string;
	payload: PushNotificationPayload;
}): { path: string; state?: unknown } {
	if (args.payload.data.type === PushNotificationPayload_data_type.RECEIVED_OPERATION) {
		const operationId = args.payload.data.received_operation.operationId;
		if (operationId) {
			return {
				path: "/home",
				state: { notif_op_id: operationId, sourceId: args.sourceId },
			};
		}
	}
	if (args.payload.data.type === PushNotificationPayload_data_type.SENT_OPERATION) {
		const operationId = args.payload.data.sent_operation.operationId;
		if (operationId) {
			return {
				path: "/home",
				state: { notif_op_id: operationId, sourceId: args.sourceId },
			};
		}
	}
	return { path: "/home" };
}
