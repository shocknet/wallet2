import type { PushNotificationEnvelope } from "@/Api/pub/autogenerated/ts/types";
import { IdentityExtension, IdentityKeys, IdentitySanctum, type Identity } from "@/State/identitiesRegistry/types";
import type { DeviceToIdentitiesMigrationFailure } from "./migrations/deviceToIdentities";
import type { SecureIdentitiesMigrationFailure } from "./migrations/secureIdentities";
import type { AppIntent } from "@/intents/types";
export type { DeviceToIdentitiesMigrationFailure } from "./migrations/deviceToIdentities/errors";
export type { DeviceToIdentitiesRepairAction } from "./migrations/deviceToIdentities/errors";
export type { SecureIdentitiesMigrationFailure } from "./migrations/secureIdentities/errors";
export type { SecureIdentitiesRepairAction } from "./migrations/secureIdentities/errors";



type ScopedRuntimeIdentityBase<TIdentity extends Identity> =
	Pick<TIdentity, "type" | "pubkey"> & {
		unlockedAtMs: number;
	}

export type ScopedRuntimeIdentityKeys = ScopedRuntimeIdentityBase<IdentityKeys> & { privateKey: string, relays: string[] }
export type ScopedRuntimeIdentitySanctum = ScopedRuntimeIdentityBase<IdentitySanctum>
export type ScopedRuntimeIdentityExtension = ScopedRuntimeIdentityBase<IdentityExtension> & { relays: string[] }
export type ScopedRuntimeIdentity = ScopedRuntimeIdentityKeys | ScopedRuntimeIdentitySanctum | ScopedRuntimeIdentityExtension

export type UnlockReason =
	| "push-intent"
	| "single-identity"
	| "last-active"
	| "user-selected";

export type MigrationFailure =
	| DeviceToIdentitiesMigrationFailure
	| SecureIdentitiesMigrationFailure;

export type MigrationStatus =
	| { kind: "running" }
	| { kind: "succeeded" }
	| { kind: "failed"; failure: MigrationFailure };

export type StartupIdentityStatus =
	| { kind: "resolving" }
	| { kind: "resolved" };

export type PushIntent = {
	receivedAtMs: number;
	envelope: PushNotificationEnvelope;
};


export type IdentitySessionStatus =
	| { kind: "none" }
	| {
		kind: "unlock-requested";
		reason: UnlockReason;
		identityId: string;
	}
	| {
		kind: "sanctum-reauth";
		runtimeIdentity: ScopedRuntimeIdentitySanctum;
		reason?: string;
	}
	| { kind: "loading"; identityId: string }
	| {
		kind: "load-failed";
		identityId: string;
		message: string;
	};

export type ShellPhase =
	| { kind: "starting-up" }
	| {
		kind: "device-to-identities-migration-failed";
		failure: DeviceToIdentitiesMigrationFailure;
	}
	| {
		kind: "secure-identities-migration-failed";
		failure: SecureIdentitiesMigrationFailure;
	}
	| {
		kind: "identity-gate";
		initialView: "create" | "select";
	}
	| {
		kind: "unlocking-identity";
		identityId: string;
		reason: UnlockReason;
	}
	| {
		kind: "sanctum-reauth";
		runtimeIdentity: ScopedRuntimeIdentitySanctum;
		reason?: string;
	}
	| { kind: "loading-identity"; identityId: string }
	| {
		kind: "identity-load-failed";
		identityId: string;
		message: string;
	}
	| { kind: "ready"; runtimeIdentity: ScopedRuntimeIdentity };




export type ShellSnapshot = {
	migration: MigrationStatus;
	startupIdentity: StartupIdentityStatus;
	identitySession: IdentitySessionStatus;
	identityCount: number;
	activeIdentity: ScopedRuntimeIdentity | null;
};

export type ShellState = {
	migration: MigrationStatus;
	startupIdentity: StartupIdentityStatus;
	identitySession: IdentitySessionStatus;
	pushIntent: PushIntent | null;
	pendingIntent: AppIntent | null;
};
