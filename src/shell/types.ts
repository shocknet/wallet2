/* Runtime types for active identity */
type RuntimeIdentityBase<TIdentity extends Identity> =
	Pick<TIdentity, "type" | "pubkey" | "label"> & {
		unlockedAtMs: number;
		wrappedDataKeyCiphertext: string;
	};

export type RuntimeIdentityKeys =
	RuntimeIdentityBase<IdentityKeys> & {
		privateKey: string;
		relays: string[];
	};

export type RuntimeIdentitySanctum =
	RuntimeIdentityBase<IdentitySanctum> & {
		tokensData: TokensData | null;
		reauthReason: string | null;
	};

export type RuntimeIdentityExtension =
	RuntimeIdentityBase<IdentityExtension> & {
		relays: string[];
	};

export type RuntimeIdentity =
	| RuntimeIdentityKeys
	| RuntimeIdentitySanctum
	| RuntimeIdentityExtension;

export type UnlockReason =
	| "push-intent"
	| "single-identity"
	| "last-active"
	| "user-selected";

export type MigrationFailure =
	| DeviceToIdentitiesMigrationFailure
	| SecureIdentitiesMigrationFailure;

export type MigrationStatus =
	| { kind: "running" }
	| { kind: "succeeded" }
	| { kind: "failed"; failure: MigrationFailure };

export type StartupIdentityStatus =
	| { kind: "resolving" }
	| { kind: "resolved" };

export type PushIntent = {
	receivedAtMs: number;
	envelope: PushNotificationEnvelope;
};


export type IdentitySessionStatus =
	| { kind: "none" }
	| {
		kind: "unlock-requested";
		reason: UnlockReason;
		identityId: string;
	}
	| {
		kind: "sanctum-reauth";
		runtimeIdentity: RuntimeIdentity;
		reason?: string;
	}
	| { kind: "loading"; identityId: string }
	| {
		kind: "load-failed";
		identityId: string;
		message: string;
	};

export type ShellPhase =
	| { kind: "starting-up" }
	| {
		kind: "device-to-identities-migration-failed";
		failure: DeviceToIdentitiesMigrationFailure;
	}
	| {
		kind: "secure-identities-migration-failed";
		failure: SecureIdentitiesMigrationFailure;
	}
	| {
		kind: "identity-gate";
		initialView: "create" | "select";
	}
	| {
		kind: "unlocking-identity";
		identityId: string;
		reason: UnlockReason;
	}
	| {
		kind: "sanctum-reauth";
		runtimeIdentity: RuntimeIdentity;
		reason?: string;
	}
	| { kind: "loading-identity"; identityId: string }
	| {
		kind: "identity-load-failed";
		identityId: string;
		message: string;
	}
	| { kind: "ready"; runtimeIdentity: RuntimeIdentity };




export type ShellSnapshot = {
	migration: MigrationStatus;
	startupIdentity: StartupIdentityStatus;
	identitySession: IdentitySessionStatus;
	identityCount: number;
	activeIdentity: RuntimeIdentity | null;
};

export type ShellState = {
	migration: MigrationStatus;
	startupIdentity: StartupIdentityStatus;
	identitySession: IdentitySessionStatus;
	pushIntent: PushIntent | null;
	pendingNav: PendingNav | null;
};
