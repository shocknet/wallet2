import { useEffect, useReducer } from "react";
import { fetchBeaconDiscovery } from "@/Api/nostrHandler";
import type { BeaconData } from "@/Api/pub/autogenerated/ts/types";
import type { BeaconHealth } from "@/State/scoped/beacons/selectors";
import {
	isBeaconRelayFreshAt,
	type BeaconLookupStatus,
} from "@/State/scoped/beacons/state";

export type BeaconDiscovery = {
	health: BeaconHealth;
	lastSeenAtMs: number;
	data: BeaconData | null;
};

type State = {
	lastSeenAtMs: number;
	probe?: { status: BeaconLookupStatus };
	data: BeaconData | null;
};

type Action =
	| { type: "reset" }
	| { type: "probing" }
	| { type: "done"; lastSeenAtMs: number; data: BeaconData | null };

const initialState: State = {
	lastSeenAtMs: 0,
	probe: undefined,
	data: null,
};

function reducer(_state: State, action: Action): State {
	switch (action.type) {
		case "reset":
			return initialState;
		case "probing":
			return { lastSeenAtMs: 0, probe: { status: "probing" }, data: null };
		case "done":
			return {
				lastSeenAtMs: action.lastSeenAtMs,
				probe: { status: "done" },
				data: action.data,
			};
	}
}

export function useBeaconDiscovery(target: { pubkey: string; relays: string[] } | null): BeaconDiscovery {
	const [state, dispatch] = useReducer(reducer, initialState);

	const pubkey = target?.pubkey ?? null;
	const relays = target?.relays;

	useEffect(() => {
		if (!pubkey || !relays) {
			dispatch({ type: "reset" });
			return;
		}

		let cancelled = false;
		dispatch({ type: "probing" });
		void fetchBeaconDiscovery(pubkey, relays)
			.then((result) => {
				if (cancelled) return;
				dispatch({
					type: "done",
					lastSeenAtMs: result?.beaconLastSeenAtMs ?? 0,
					data: result?.data ?? null,
				});
			})
			.catch(() => {
				if (cancelled) return;
				dispatch({ type: "done", lastSeenAtMs: 0, data: null });
			});

		return () => {
			cancelled = true;
		};
	}, [pubkey, relays]);

	const fresh =
		isBeaconRelayFreshAt(state.lastSeenAtMs, Date.now());

	let health: BeaconHealth;
	if (fresh) {
		health = "fresh";
	} else if (!state.probe || state.probe.status === "probing") {
		health = "warmingUp";
	} else {
		health = "stale";
	}

	return {
		health,
		lastSeenAtMs: state.lastSeenAtMs,
		data: state.data,
	};
}
