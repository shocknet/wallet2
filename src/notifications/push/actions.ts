import { createAction } from "@reduxjs/toolkit";
import type { PushNotificationEnvelope } from "@/Api/pub/autogenerated/ts/types";
import type { AppThunk } from "@/State/store/store";
import { shellActions } from "@/shell/slice";
import dLogger from "@/Api/helpers/debugLog";

const log = dLogger.withContext({ component: "push-capture" });

export const pushTokenUpdated = createAction<{ token: string }>("push/tokenUpdated");

export const capturePushIntent =
	(args: {
		envelope: PushNotificationEnvelope;
		source: string;
	}): AppThunk<void> =>
		(dispatch) => {
			log.debug("envelope_received", { data: { source: args.source } });
			dispatch(
				shellActions.pushIntentSet({
					receivedAtMs: Date.now(),
					envelope: args.envelope,
				}),
			);
			log.info("push_intent_captured", {
				data: { source: args.source, topicId: args.envelope.topic_id },
			});
		};
