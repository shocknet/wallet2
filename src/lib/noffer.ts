export class NofferRangeError extends Error {
	readonly name = "NofferRangeError";
	readonly code = 5 as const;

	constructor(
		readonly range: { min: number; max: number },
		message: string,
	) {
		super(message);
	}
}

export async function createNofferInvoice(noffer: OfferPointer, keys: NostrKeyPair, amount?: Satoshi): Promise<ParsedInvoiceInput> {
	let expectedAmount;
	if (noffer.priceType === OfferPriceType.Spontaneous) {
		if (!amount) {
			throw new Error("Amount is required for spontaneous offers");
		}
		expectedAmount = amount;
	} else {
		if (!noffer.price) {
			throw new Error("Price is required for non-spontaneous offers");
		}
		expectedAmount = noffer.price as Satoshi;
	}



	const sdk = new ClinkSDK({
		privateKey: new Uint8Array(Buffer.from(keys.privateKey, 'hex')),
		relays: [noffer.relay],
		toPubKey: noffer.pubkey,
	});
	const data: NofferData = { offer: noffer.offer, amount_sats: amount };
	const res = await sdk.Noffer(data);
	if ("error" in res) {
		if (res.code === 5 && res.range) {
			throw new NofferRangeError(res.range, res.error);
		}
		throw new Error(res.error);
	}

	return parseAs(res.bolt11, InputClassification.LN_INVOICE, expectedAmount);
}

export function priceTypeToString(priceType: OfferPriceType) {
	switch (priceType) {
		case OfferPriceType.Fixed:
			return "Fixed";
		case OfferPriceType.Variable:
			return "Variable";
		case OfferPriceType.Spontaneous:
			return "Spontaneous";
		default:
			throw new Error("Unknown noffer price type");
	}
}


export async function getUserOffer(pastefield: { pubkey: string, relays?: string[] } | string, keys: NostrKeyPair, offerId: string): Promise<OfferConfig> {
	const client = await getNostrClient(pastefield, keys);
	const res = await client.GetUserOffer({ offer_id: offerId });
	if (res.status !== "OK") {
		throw new Error("Failed to fetch offer: " + res.reason);
	}

	return res;
}

