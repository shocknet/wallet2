import { DebitRule, DebitRule_rule_type, FrequencyRule, IntervalType } from "@/Api/pub/autogenerated/ts/types";

export function intervalLabel(
	interval: IntervalType,
	count: number,
): string {
	const plural = count === 1 ? "" : "s";
	switch (interval) {
		case IntervalType.DAY:
			return `Day${plural}`;
		case IntervalType.WEEK:
			return `Week${plural}`;
		case IntervalType.MONTH:
			return `Month${plural}`;
	}
}

export function formatRollingBudgetSummary(args: {
	amount: number;
	numberOfIntervals: number;
	interval: IntervalType;
}): string {
	const amount = new Intl.NumberFormat("en-US").format(args.amount);
	const unit = intervalLabel(args.interval, args.numberOfIntervals);
	const window =
		args.numberOfIntervals === 1
			? `1 ${unit}`
			: `${args.numberOfIntervals} ${unit}`;
	return `Up to ${amount} sats in any rolling ${window}`;
}

export interface DebitRuleSummary {
	frequencyRule?: {
		amount: number;
		numberOfIntervals: number;
		interval: IntervalType;
	};
	expirationRule?: {
		expiresAt: Date;
	};
}
export function formatDebitRulesSummary(rules: DebitRule[]): DebitRuleSummary {
	if (rules.length === 0) {
		return {
			frequencyRule: undefined,
			expirationRule: undefined,
		};
	}

	const summary: DebitRuleSummary = {
		frequencyRule: undefined,
		expirationRule: undefined,
	};

	for (const item of rules) {
		if (item.rule.type === DebitRule_rule_type.FREQUENCY_RULE) {
			summary.frequencyRule = {
				amount: item.rule.frequency_rule.amount,
				numberOfIntervals: item.rule.frequency_rule.number_of_intervals,
				interval: item.rule.frequency_rule.interval,
			};
		} else if (item.rule.type === DebitRule_rule_type.EXPIRATION_RULE) {
			summary.expirationRule = {
				expiresAt: new Date(item.rule.expiration_rule.expires_at_unix * 1000),
			};
		}
	}

	return summary;
}

export const DEFAULT_FREQUENCY: FrequencyRule = {
	amount: 10,
	number_of_intervals: 1,
	interval: IntervalType.DAY,
};


export function getFrequency(rules: DebitRule[]): FrequencyRule | null {
	for (const item of rules) {
		if (item.rule.type === DebitRule_rule_type.FREQUENCY_RULE) {
			return item.rule.frequency_rule;
		}
	}
	return null;
}

export function getExpiresAtUnix(rules: DebitRule[]): number | null {
	for (const item of rules) {
		if (item.rule.type === DebitRule_rule_type.EXPIRATION_RULE) {
			return item.rule.expiration_rule.expires_at_unix;
		}
	}
	return null;
}

export function withoutRuleType(rules: DebitRule[], type: DebitRule_rule_type): DebitRule[] {
	return rules.filter((item) => item.rule.type !== type);
}

export function upsertFrequency(rules: DebitRule[], frequency: FrequencyRule): DebitRule[] {
	const next = withoutRuleType(rules, DebitRule_rule_type.FREQUENCY_RULE);
	next.push({
		rule: {
			type: DebitRule_rule_type.FREQUENCY_RULE,
			frequency_rule: frequency,
		},
	});
	return next;
}

export function upsertExpiry(rules: DebitRule[], expiresAtUnix: number): DebitRule[] {
	const next = withoutRuleType(rules, DebitRule_rule_type.EXPIRATION_RULE);
	next.push({
		rule: {
			type: DebitRule_rule_type.EXPIRATION_RULE,
			expiration_rule: { expires_at_unix: expiresAtUnix },
		},
	});
	return next;
}

export function defaultExpiresAtUnix(): number {
	return Math.floor(Date.now() / 1000) + 7 * 24 * 60 * 60;
}
